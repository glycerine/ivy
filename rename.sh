# Replays the 357 git mv operations used to prepare the core Go packages for flattening.
# The helper treats already-renamed files as a no-op so this is safe to run on this branch too.

processed=0

rename_one() {
  local src=$1
  local dst=$2

  if [[ -e "$src" ]]; then
    git mv -- "$src" "$dst"
  elif [[ -e "$dst" ]]; then
    printf 'already renamed: %s\n' "$dst"
  else
    printf 'missing source and target: %s -> %s\n' "$src" "$dst" >&2
    return 1
  fi

  processed=$((processed + 1))
}

