package abc

// Deterministic DOT rendering from src/aig/aig/aigShow.c.

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type AigDOTOptions struct {
	HAIG       bool
	Bold       []AigID
	MaxNodes   int // zero: native limit of 200 AND nodes
	MaxBytes   int // zero: four MiB
	MaxObjects int // zero: one million allocated IDs
	Stop       func() bool
}

func (graph *AigManager) DOT(options AigDOTOptions) ([]byte, error) {
	if graph == nil || options.MaxNodes < 0 || options.MaxBytes < 0 || options.MaxObjects < 0 {
		return nil, ErrDimension
	}
	if err := graph.Check(); err != nil {
		return nil, err
	}
	maximumObjects := options.MaxObjects
	if maximumObjects == 0 {
		maximumObjects = 1 << 20
	}
	if len(graph.objects) > maximumObjects {
		return nil, ErrLimit
	}
	maximumNodes := options.MaxNodes
	if maximumNodes == 0 {
		maximumNodes = 200
	}
	nodeCount := 0
	for _, object := range graph.objects {
		if object.Type == AigAND {
			nodeCount++
		}
	}
	if nodeCount > maximumNodes {
		return nil, ErrLimit
	}
	bold := make([]bool, len(graph.objects))
	for _, id := range options.Bold {
		if uint64(id) >= uint64(len(graph.objects)) || graph.objects[id].Type == AigNone {
			return nil, ErrInvalidLiteral
		}
		bold[id] = true
	}
	visit := func() error {
		if options.Stop != nil && options.Stop() {
			return ErrCancelled
		}
		return nil
	}
	levelMaximum := uint32(0)
	for _, id := range graph.cos {
		if err := visit(); err != nil {
			return nil, err
		}
		level := graph.objects[graph.objects[id].Fanin0.ID()].Level
		if level > levelMaximum {
			levelMaximum = level
		}
	}
	levelMaximum++
	var output strings.Builder
	fmt.Fprintln(&output, "# AIG structure generated by IVY package")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "digraph AIG {")
	fmt.Fprintln(&output, "size = \"7.5,10\";")
	fmt.Fprintln(&output, "center = true;")
	fmt.Fprintln(&output, "edge [dir = back];")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "{")
	fmt.Fprintln(&output, "  node [shape = plaintext];")
	fmt.Fprintln(&output, "  edge [style = invis];")
	fmt.Fprintln(&output, "  LevelTitle1 [label=\"\"];")
	fmt.Fprintln(&output, "  LevelTitle2 [label=\"\"];")
	for level := int64(levelMaximum); level >= 0; level-- {
		fmt.Fprintf(&output, "  Level%d [label = \"\"];\n", level)
	}
	fmt.Fprint(&output, "  LevelTitle1 ->  LevelTitle2 ->")
	for level := int64(levelMaximum); level >= 0; level-- {
		fmt.Fprintf(&output, "  Level%d", level)
		if level != 0 {
			fmt.Fprint(&output, " ->")
		} else {
			fmt.Fprint(&output, ";")
		}
	}
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "{")
	fmt.Fprintln(&output, "  rank = same;")
	fmt.Fprintln(&output, "  LevelTitle1;")
	fmt.Fprintln(&output, "  title1 [shape=plaintext,")
	fmt.Fprintln(&output, "          fontsize=20,")
	fmt.Fprintln(&output, "          fontname = \"Times-Roman\",")
	fmt.Fprintln(&output, "          label=\"AIG structure visualized by ABC\\nBenchmark \\\"aig\\\". \"")
	fmt.Fprintln(&output, "         ];")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "{")
	fmt.Fprintln(&output, "  rank = same;")
	fmt.Fprintln(&output, "  LevelTitle2;")
	fmt.Fprintln(&output, "  title2 [shape=plaintext,")
	fmt.Fprintln(&output, "          fontsize=18,")
	fmt.Fprintln(&output, "          fontname = \"Times-Roman\",")
	fmt.Fprintf(&output, "          label=\"The set contains %d logic nodes and spans %d levels.\\n\"\n", nodeCount, levelMaximum)
	fmt.Fprintln(&output, "         ];")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "{")
	fmt.Fprintln(&output, "  rank = same;")
	fmt.Fprintf(&output, "  Level%d;\n", levelMaximum)
	for _, id := range graph.cos {
		fmt.Fprintf(&output, "  Node%d [label = \"%d\", shape = invtriangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	for level := int64(levelMaximum) - 1; level > 0; level-- {
		if err := visit(); err != nil {
			return nil, err
		}
		fmt.Fprintln(&output, "{")
		fmt.Fprintln(&output, "  rank = same;")
		fmt.Fprintf(&output, "  Level%d;\n", level)
		for id, object := range graph.objects {
			if object.Type == AigNone || object.Type == AigCO || int64(object.Level) != level {
				continue
			}
			fmt.Fprintf(&output, "  Node%d [label = \"%d\", shape = ellipse", id, id)
			if bold[id] {
				fmt.Fprint(&output, ", style = filled")
			}
			fmt.Fprintln(&output, "];")
		}
		fmt.Fprintln(&output, "}")
		fmt.Fprintln(&output)
	}
	fmt.Fprintln(&output, "{")
	fmt.Fprintln(&output, "  rank = same;")
	fmt.Fprintln(&output, "  Level0;")
	if graph.objects[0].RefCount > 0 {
		fmt.Fprintln(&output, "  Node0 [label = \"Const1\", shape = ellipse, color = coral, fillcolor = coral];")
	}
	for _, id := range graph.cis {
		fmt.Fprintf(&output, "  Node%d [label = \"%d\", shape = triangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "title1 -> title2 [style = invis];")
	for _, id := range graph.cos {
		fmt.Fprintf(&output, "title2 -> Node%d [style = invis];\n", id)
	}
	for index := 1; index < len(graph.cos); index++ {
		fmt.Fprintf(&output, "Node%d -> Node%d [style = invis];\n", graph.cos[index-1], graph.cos[index])
	}
	for id, object := range graph.objects {
		if err := visit(); err != nil {
			return nil, err
		}
		if object.Type != AigAND && object.Type != AigCO && object.Type != AigBuffer {
			continue
		}
		style := "bold"
		if object.Fanin0.Complemented() {
			style = "dotted"
		}
		fmt.Fprintf(&output, "Node%d -> Node%d [style = %s];\n", id, object.Fanin0.ID(), style)
		if object.Type != AigAND {
			continue
		}
		style = "bold"
		if object.Fanin1.Complemented() {
			style = "dotted"
		}
		fmt.Fprintf(&output, "Node%d -> Node%d [style = %s];\n", id, object.Fanin1.ID(), style)
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	maximumBytes := options.MaxBytes
	if maximumBytes == 0 {
		maximumBytes = 4 << 20
	}
	if output.Len() > maximumBytes {
		return nil, ErrLimit
	}
	return []byte(output.String()), nil
}

func (graph *AigManager) WriteDOT(path string, options AigDOTOptions) error {
	if path == "" {
		return ErrDimension
	}
	data, err := graph.DOT(options)
	if err != nil {
		return err
	}
	if options.Stop != nil && options.Stop() {
		return ErrCancelled
	}
	return os.WriteFile(path, data, 0666)
}

// WriteShowDOT is the non-launching replacement for Aig_ManShow. It writes
// Name with its final extension replaced by .dot and returns that path.
func (graph *AigManager) WriteShowDOT(options AigDOTOptions) (string, error) {
	if graph == nil || graph.Name == "" {
		return "", ErrDimension
	}
	extension := filepath.Ext(graph.Name)
	path := strings.TrimSuffix(graph.Name, extension) + ".dot"
	if err := graph.WriteDOT(path, options); err != nil {
		return "", err
	}
	return path, nil
}
