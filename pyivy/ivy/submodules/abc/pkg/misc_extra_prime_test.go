func FuzzExtraPrimeArtifacts(f *testing.F) {
	for _, seed := range []struct {
		variables byte
		mask      uint64
	}{{0, 0}, {1, 3}, {3, 0xff}, {6, 0x9562c13d}, {10, ^uint64(0)}} {
		f.Add(seed.variables, seed.mask)
	}
	f.Fuzz(func(t *testing.T, rawVariables byte, mask uint64) {
		variables := int(rawVariables%12) + 1
		limit := 1 << uint(variables)
		values := make([]int, 0, 64)
		for value := 0; value < limit && value < 64; value++ {
			if mask&(uint64(1)<<uint(value)) != 0 {
				values = append(values, value)
			}
		}
		pairs, err := ExtraPrimeDistanceOnePairs(values, variables, ExtraPrimeLimits{})
		if err != nil || !slices.Equal(pairs, extraPrimePairModel(values)) {
			t.Fatalf("variables=%d values=%v pairs=%v err=%v", variables, values, pairs, err)
		}
		pla, err := MarshalExtraPrimePLA(values, variables, "fuzz", ExtraPrimeLimits{})
		if err != nil {
			t.Fatal(err)
		}
		lines := strings.Split(string(pla), "\n")
		if len(lines) != len(values)+7 {
			t.Fatalf("PLA line count=%d want=%d", len(lines), len(values)+7)
		}
		for index, value := range values {
			want := ""
			for bit := variables - 1; bit >= 0; bit-- {
				want += string(byte('0' + (value>>uint(bit))&1))
			}
			if lines[4+index] != want+" 1" {
				t.Fatalf("row=%q want=%q", lines[4+index], want+" 1")
			}
		}
		table, err := NewExtraPrimeCubeTable(variables, values, ExtraPrimeLimits{})
		if err != nil {
			t.Fatal(err)
		}
		for index, value := range values {
			cube, cubeErr := table.Cube(index)
			formatted, formatErr := table.FormatCube(index, -1)
			if cubeErr != nil || formatErr != nil || len(cube) != variables || len(formatted) != variables {
				t.Fatalf("index=%d cube=%v format=%q errors=%v/%v", index, cube, formatted, cubeErr, formatErr)
			}
			for variable := 0; variable < variables; variable++ {
				bit := (value >> uint(variable)) & 1
				if cube[variable] != variable<<1|int(bit^1) || formatted[variable] != byte('0'+bit) {
					t.Fatalf("index=%d variable=%d cube=%v format=%q", index, variable, cube, formatted)
				}
			}
		}
	})
}

func FuzzExtraCubeDifferences(f *testing.F) {
	for _, seed := range []struct{ first, second uint64 }{{0, 0}, {1, 2}, {0x55, 0xaa}, {^uint64(0), 0}} {
		f.Add(seed.first, seed.second)
	}
	f.Fuzz(func(t *testing.T, firstMask, secondMask uint64) {
		first, second := make([]int, 0, 64), make([]int, 0, 64)
		for literal := 0; literal < 64; literal++ {
			if firstMask&(uint64(1)<<uint(literal)) != 0 {
				first = append(first, literal)
			}
			if secondMask&(uint64(1)<<uint(literal)) != 0 {
				second = append(second, literal)
			}
		}
		difference, err := ExtraCubeFreeDifference(first, second)
		if err != nil {
			t.Fatal(err)
		}
		common := 0
		for _, left := range first {
			if _, found := slices.BinarySearch(second, left); found {
				common++
			}
		}
		if difference.Common != common || len(difference.Tagged) != len(first)+len(second)-2*common || difference.Duplicate != (len(difference.Tagged) == 0) || difference.Contained != (len(difference.Tagged) == 1) {
			t.Fatalf("first=%v second=%v difference=%+v common=%d", first, second, difference, common)
		}
		for omitFirst := -1; omitFirst < len(first); omitFirst++ {
			for omitSecond := -1; omitSecond < len(second); omitSecond++ {
				got, equalErr := ExtraCubesEqualWithout(first, second, omitFirst, omitSecond)
				if equalErr != nil {
					t.Fatal(equalErr)
				}
				left, right := slices.Clone(first), slices.Clone(second)
				if omitFirst >= 0 {
					left = append(left[:omitFirst], left[omitFirst+1:]...)
				}
				if omitSecond >= 0 {
					right = append(right[:omitSecond], right[omitSecond+1:]...)
				}
				if got != slices.Equal(left, right) {
					t.Fatalf("first=%v second=%v omit=%d/%d got=%v", first, second, omitFirst, omitSecond, got)
				}
			}
		}
	})
}
