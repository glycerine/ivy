func TestMaccPlanExhaustiveCoefficientsAndOwnership(t *testing.T) {
	for bits := 1; bits <= 9; bits++ {
		plan, err := GenerateMaccPlan(bits, MaccLimits{})
		if err != nil {
			t.Fatal(bits, err)
		}
		if got, _ := plan.Bits(); got != bits {
			t.Fatal(got, bits)
		}
		bound := 1 << uint(bits-1)
		for constant := -bound; constant < bound; constant++ {
			got, coefficientErr := plan.Coefficient(constant, MaccLimits{})
			if coefficientErr != nil || got != constant {
				t.Fatal(bits, constant, got, coefficientErr)
			}
		}
		first, _ := plan.Entries()
		second, _ := plan.Entries()
		first[0] = 0
		if second[0] != ^uint32(0) {
			t.Fatal("entry snapshot aliases plan", bits)
		}
	}
}

func TestMaccDirectFormatting(t *testing.T) {
	got, err := FormatDirectConstMultiplier(-3, 4, 8, MaccLimits{})
	want := "// 8-bit multiplier by 4-bit constant -3 generated by ABC\n" +
		"module mul003_neg (\n" +
		"    input  [7:0] i,\n" +
		"    output [7:0] o\n" +
		");\n" +
		"    wire [3:0] c = 4'h3;\n" +
		"    wire [11:0] I = {{4{i[7]}}, i};\n" +
		"    wire [11:0] m = I * c;\n" +
		"    wire [11:0] t = -m;\n" +
		"    assign o = t[11:4];\n" +
		"endmodule\n\n"
	if err != nil || got != want {
		t.Fatal(got, want, err)
	}
	macc, err := FormatDirectConstMacc(-3, 4, 8, "2000-01-02", MaccLimits{})
	if err != nil || !strings.Contains(macc, "// 12-bit multiplier-accumulator with constant -3 generated by ABC on 2000-01-02\n") || !strings.Contains(macc, "module mulacc003_neg") || !strings.Contains(macc, "assign o = s - m;") {
		t.Fatal(macc, err)
	}
}

func TestMaccSynthesizedFormattingAndBatches(t *testing.T) {
	plan, err := GenerateMaccPlan(4, MaccLimits{})
	if err != nil {
		t.Fatal(err)
	}
	for constant := -8; constant < 8; constant++ {
		multiplier, multErr := plan.FormatMultiplier(constant, 8, MaccLimits{})
		accumulator, accErr := plan.FormatAccumulator(constant, 8, MaccLimits{})
		wide, wideErr := plan.FormatWideAccumulator(constant, 8, "stamp", MaccLimits{})
		if multErr != nil || accErr != nil || wideErr != nil || strings.Contains(multiplier, " * ") || !strings.Contains(multiplier, "module ") || !strings.Contains(accumulator, "assign o =") || !strings.Contains(wide, "generated by ABC on stamp") {
			t.Fatal(constant, multiplier, accumulator, wide, multErr, accErr, wideErr)
		}
	}
	if zero, _ := plan.FormatMultiplier(0, 8, MaccLimits{}); !strings.Contains(zero, "assign o = 8'h0;") {
		t.Fatal(zero)
	}
	if zero, _ := plan.FormatAccumulator(0, 8, MaccLimits{}); !strings.Contains(zero, "assign o = c;") {
		t.Fatal(zero)
	}
	if zero, _ := plan.FormatWideAccumulator(0, 8, "stamp", MaccLimits{}); !strings.Contains(zero, "assign o = s;") {
		t.Fatal(zero)
	}
	direct, err := GenerateDirectMaccSpecifications(4, 8, "stamp", MaccLimits{})
	synthesized, synthErr := plan.GenerateWideAccumulatorSet(8, "stamp", MaccLimits{})
	if err != nil || synthErr != nil || len(direct) != 16 || len(synthesized) != 16 || direct[0].Name != "macc_spec_008.v" || direct[15].Name != "macc_spec_007.v" || synthesized[0].Name != "macc008.v" || synthesized[15].Name != "macc007.v" {
		t.Fatal(len(direct), len(synthesized), err, synthErr)
	}
	before := slices.Clone(synthesized)
	synthesized[0].Name = "changed"
	if before[0].Name == synthesized[0].Name {
		t.Fatal("batch rows are not independently owned")
	}
}

func TestMaccErrorsLimitsAndCancellation(t *testing.T) {
	for _, bits := range []int{0, 16} {
		if _, err := GenerateMaccPlan(bits, MaccLimits{}); !errors.Is(err, ErrDimension) {
			t.Fatal(bits, err)
		}
	}
	if _, err := GenerateMaccPlan(8, MaccLimits{MaxEntries: 3}); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
	if _, err := GenerateMaccPlan(8, MaccLimits{MaxOperations: 1}); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
	if _, err := GenerateMaccPlan(8, MaccLimits{Stop: func() bool { return true }}); !errors.Is(err, ErrCancelled) {
		t.Fatal(err)
	}
	plan, _ := GenerateMaccPlan(4, MaccLimits{})
	if _, err := plan.Coefficient(8, MaccLimits{}); !errors.Is(err, ErrDimension) {
		t.Fatal(err)
	}
	if _, err := plan.FormatMultiplier(1, 0, MaccLimits{}); !errors.Is(err, ErrDimension) {
		t.Fatal(err)
	}
	if _, err := plan.FormatMultiplier(1, 8, MaccLimits{MaxBytes: 1}); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
	if _, err := plan.FormatWideAccumulator(1, 8, "bad\nstamp", MaccLimits{}); !errors.Is(err, ErrDimension) {
		t.Fatal(err)
	}
	if _, err := plan.GenerateWideAccumulatorSet(8, "stamp", MaccLimits{MaxEntries: 1}); !errors.Is(err, ErrLimit) {
		t.Fatal(err)
	}
}

func FuzzMaccPlan(f *testing.F) {
	f.Add(byte(4), int16(-3), byte(8))
	f.Add(byte(8), int16(127), byte(16))
	f.Fuzz(func(t *testing.T, rawBits byte, rawConstant int16, rawWidth byte) {
		bits := int(rawBits%9) + 1
		bound := 1 << uint(bits-1)
		constant := int(rawConstant) % bound
		if rawConstant&1 != 0 {
			constant = -constant
		}
		width := int(rawWidth%32) + 1
		plan, err := GenerateMaccPlan(bits, MaccLimits{MaxEntries: 1 << 10, MaxOperations: 1 << 22})
		if err != nil {
			t.Fatal(bits, err)
		}
		coefficient, err := plan.Coefficient(constant, MaccLimits{MaxOperations: 1 << 18})
		if err != nil || coefficient != constant {
			t.Fatal(bits, constant, coefficient, err)
		}
		text, err := plan.FormatMultiplier(constant, width, MaccLimits{MaxOperations: 1 << 18, MaxBytes: 1 << 16})
		if err != nil || !strings.Contains(text, "module ") || !strings.HasSuffix(text, "endmodule\n\n") || strings.Contains(text, " * ") {
			t.Fatal(bits, constant, width, text, err)
		}
	})
}
