package extra

// Constant multiplier generation preserves ABC's cost-ordered signed-constant
// search. Packed decompositions store the first operand in bits 16..31, the
// second in 0..14, and subtraction in bit 15. All-ones marks shifts/trivial values.
import (
	"fmt"
	"io"
	"math/bits"
	"os"
)

func maccDimensions(n, nBits, nWidth int32) (total, bound int32) {
	// Operand packing reserves 15 bits for a positive operand. Bound the search
	// before shifts or allocation; the source default is eight coefficient bits.
	if nBits < 2 || nBits > 15 || nWidth <= 0 || int64(nWidth)+int64(nBits) > 1<<31-1 {
		panic("invalid constant multiplier dimensions")
	}
	bound = 1 << (nBits - 1)
	if n < -bound || n >= bound {
		panic("constant outside multiplier range")
	}
	return nBits + nWidth, bound
}
func maccMagnitude(n int32) int32 {
	if n < 0 {
		return -n
	}
	return n
}
func maccSuffix(n int32) string {
	if n < 0 {
		return "_neg"
	}
	return "_pos"
}
func maccSign(n int32) byte {
	if n < 0 {
		return 'N'
	}
	return 'n'
}

func Macc_ConstMultSpecOne2(out io.Writer, n, nBits, nWidth int32) {
	total, _ := maccDimensions(n, nBits, nWidth)
	op := '+'
	if n < 0 {
		op = '-'
	}
	fmt.Fprintf(out, "// %d-bit multiplier-accumulator with constant %d generated by ABC on %s\n", total, n, Extra_TimeStamp())
	fmt.Fprintf(out, "module mulacc%03d%s (\n", maccMagnitude(n), maccSuffix(n))
	fmt.Fprintf(out, "    input  [%d:0] i,\n    input  [%d:0] s,\n    output [%d:0] o\n);\n", total-1, total-1, total-1)
	fmt.Fprintf(out, "    wire [%d:0] c = %d'h%x;\n    wire [%d:0] m = i * c;\n    assign o = s %c m;\nendmodule\n\n", total-1, total, maccMagnitude(n), total-1, op)
}
func Macc_ConstMultSpecOne(out io.Writer, n, nBits, nWidth int32) {
	total, _ := maccDimensions(n, nBits, nWidth)
	op := ' '
	if n < 0 {
		op = '-'
	}
	fmt.Fprintf(out, "// %d-bit multiplier by %d-bit constant %d generated by ABC\n", nWidth, nBits, n)
	fmt.Fprintf(out, "module mul%03d%s (\n    input  [%d:0] i,\n    output [%d:0] o\n);\n", maccMagnitude(n), maccSuffix(n), nWidth-1, nWidth-1)
	fmt.Fprintf(out, "    wire [%d:0] c = %d'h%x;\n    wire [%d:0] I = {{%d{i[%d]}}, i};\n", nBits-1, nBits, maccMagnitude(n), total-1, nBits, nWidth-1)
	fmt.Fprintf(out, "    wire [%d:0] m = I * c;\n    wire [%d:0] t = %cm;\n    assign o = t[%d:%d];\nendmodule\n\n", total-1, total-1, op, total-1, nBits)
}

func maccGenerate(nBits int32, out io.Writer) []uint32 {
	_, bound := maccDimensions(0, nBits, 1)
	mask := uint32(1<<nBits) - 1
	place := make([]uint32, 1<<nBits)
	groups := make([][]int32, 2*nBits)
	place[0], place[1], place[mask] = ^uint32(0), ^uint32(0), ^uint32(0)
	for i := 2; i < len(place); i += 2 {
		place[i] = ^uint32(0)
	}
	fmt.Fprintln(out, "Generating numbers using 0 adders:")
	for i := int32(0); i < nBits; i++ {
		groups[0] = append(groups[0], 1<<i)
		fmt.Fprintf(out, "%d = %d << %d\n", 1<<i, 1, i)
	}
	for cost := int32(1); cost < nBits; cost++ {
		complete := true
		for _, v := range place {
			if v == 0 {
				complete = false
				break
			}
		}
		if complete {
			break
		}
		fmt.Fprintf(out, "Generating numbers using %d adders:\n", cost)
		for a := int32(0); a < nBits; a++ {
			for b := int32(0); b < nBits; b++ {
				if a+b != cost-1 {
					continue
				}
				for _, one := range groups[a] {
					for _, two := range groups[b] {
						for op, value := range []int32{one + two, one - two, two - one} {
							if value < -bound || value >= bound || place[mask&uint32(value)] != 0 {
								continue
							}
							if value > 0 {
								groups[cost] = append(groups[cost], value)
							}
							first, second, sign := one, two, '+'
							encoding := uint32(one)<<16 | uint32(two)
							if op != 0 {
								sign = '-'
								if op == 2 {
									first, second = two, one
								}
								encoding = uint32(first)<<16 | uint32(second) | 1<<15
							}
							place[mask&uint32(value)] = encoding
							fmt.Fprintf(out, "%d = %d %c %d\n", value, first, sign, second)
						}
					}
				}
				fmt.Fprintln(out, "Adding one incrementor:")
				for _, one := range groups[cost] {
					if one < 0 {
						continue
					}
					index := mask & uint32(-one)
					if place[index] == 0 {
						place[index] = uint32(one) << 16
						fmt.Fprintf(out, "-%d = ~%d + 1\n", one, one)
					}
				}
			}
		}
	}
	return place
}
func Macc_ConstMultGenerate(nBits int32) []uint32 { return maccGenerate(nBits, os.Stdout) }

// A generated network shares each coefficient wire. The C emitter recursively
// redeclared common wires and looped forever when called with coefficient zero.
func maccEmit(out io.Writer, place []uint32, n, nBits, nWidth int32, seen map[int32]bool) {
	if seen[n] {
		return
	}
	seen[n] = true
	total, bound := maccDimensions(0, nBits, nWidth)
	// Search operands include the positive boundary power of two, even though
	// requested signed coefficients stop one below it.
	if n < -bound || n > bound {
		panic("invalid multiplier intermediate")
	}
	if n == 0 {
		fmt.Fprintf(out, "    wire [%d:0] n0 = %d'h0;\n", total-1, total)
		return
	}
	index := uint32(n) & uint32(1<<nBits-1)
	if int(index) >= len(place) {
		panic("short multiplier decomposition")
	}
	packed := place[index]
	if packed == 0 {
		panic("missing multiplier decomposition")
	}
	one, two := int32(packed>>16), int32(packed&0x7fff)
	sign := maccSign(n)
	if packed == ^uint32(0) {
		zeros := int32(bits.TrailingZeros32(uint32(n)))
		odd := n >> zeros
		if odd == -1 {
			maccEmit(out, place, -1, nBits, nWidth, seen)
		}
		if maccMagnitude(odd) != 1 {
			maccEmit(out, place, odd, nBits, nWidth, seen)
		}
		if n == -1 {
			fmt.Fprintf(out, "    wire [%d:0] N1 = -n1;\n", total-1)
		}
		if zeros > 0 {
			fmt.Fprintf(out, "    wire [%d:0] %c%d = %c%d << %d;\n", total-1, sign, maccMagnitude(n), sign, maccMagnitude(odd), zeros)
		}
	} else if one != 0 && two != 0 {
		maccEmit(out, place, one, nBits, nWidth, seen)
		maccEmit(out, place, two, nBits, nWidth, seen)
		op := '+'
		if packed>>15&1 != 0 {
			op = '-'
		}
		fmt.Fprintf(out, "    wire [%d:0] %c%d = n%d %c n%d;\n", total-1, sign, maccMagnitude(n), one, op, two)
	} else if two == 0 {
		maccEmit(out, place, one, nBits, nWidth, seen)
		fmt.Fprintf(out, "    wire [%d:0] N%d = -n%d;\n", total-1, one, one)
	} else {
		panic("invalid multiplier decomposition")
	}
}
func Macc_ConstMultGenOne_rec(out io.Writer, place []uint32, n, nBits, nWidth int32) {
	maccEmit(out, place, n, nBits, nWidth, map[int32]bool{1: true})
}

func maccModule(out io.Writer, place []uint32, n, nBits, nWidth int32, mode int) {
	total, _ := maccDimensions(n, nBits, nWidth)
	width := nWidth
	if mode == 2 {
		width = total
	}
	title, module := "multiplier", "mul"
	if mode != 0 {
		title, module = "multiplier-accumulator", "macc"
	}
	if mode == 2 {
		fmt.Fprintf(out, "// %d-bit %s by constant %d generated by ABC on %s\n", total, title, n, Extra_TimeStamp())
	} else {
		fmt.Fprintf(out, "// %d-bit %s by %d-bit constant %d generated by ABC\n", nWidth, title, nBits, n)
	}
	fmt.Fprintf(out, "module %s%03d%s (\n    input  [%d:0] i,\n", module, maccMagnitude(n), maccSuffix(n), width-1)
	if mode == 1 {
		fmt.Fprintf(out, "    input  [%d:0] c,\n", width-1)
	} else if mode == 2 {
		fmt.Fprintf(out, "    input  [%d:0] s,\n", width-1)
	}
	fmt.Fprintf(out, "    output [%d:0] o\n);\n", width-1)
	if n == 0 {
		switch mode {
		case 0:
			fmt.Fprintf(out, "    assign o = %d'h0;\n", nWidth)
		case 1:
			fmt.Fprintln(out, "    assign o = c;")
		case 2:
			fmt.Fprintln(out, "    assign o = s;")
		}
	} else {
		if mode == 2 {
			fmt.Fprintf(out, "    wire [%d:0] n1 = i;\n", total-1)
		} else {
			fmt.Fprintf(out, "    wire [%d:0] n1 = {{%d{i[%d]}}, i};\n", total-1, nBits, nWidth-1)
		}
		Macc_ConstMultGenOne_rec(out, place, n, nBits, nWidth)
		switch mode {
		case 0:
			fmt.Fprintf(out, "    assign o = %c%d[%d:%d];\n", maccSign(n), maccMagnitude(n), total-1, nBits)
		case 1:
			fmt.Fprintf(out, "    wire [%d:0] s = %c%d[%d:%d];\n    assign o = s + c;\n", nWidth-1, maccSign(n), maccMagnitude(n), total-1, nBits)
		case 2:
			fmt.Fprintf(out, "    assign o = s + %c%d;\n", maccSign(n), maccMagnitude(n))
		}
	}
	fmt.Fprint(out, "endmodule\n\n")
}
func Macc_ConstMultGenMult(out io.Writer, p []uint32, n, b, w int32)  { maccModule(out, p, n, b, w, 0) }
func Macc_ConstMultGenMacc(out io.Writer, p []uint32, n, b, w int32)  { maccModule(out, p, n, b, w, 1) }
func Macc_ConstMultGenMacc2(out io.Writer, p []uint32, n, b, w int32) { maccModule(out, p, n, b, w, 2) }
func Macc_ConstMultGenTest0()                                         { Macc_ConstMultGenerate(8) }
func maccFiles(spec bool) error {
	var p []uint32
	if !spec {
		p = Macc_ConstMultGenerate(8)
	}
	for n := int32(-128); n < 128; n++ {
		name := fmt.Sprintf("const_mul/macc%03d.v", uint32(n)&255)
		if spec {
			name = fmt.Sprintf("const_mul/macc_spec_%03d.v", uint32(n)&255)
		}
		f, err := os.Create(name)
		if err != nil {
			return err
		}
		if spec {
			Macc_ConstMultSpecOne2(f, n, 8, 16)
		} else {
			Macc_ConstMultGenMacc2(f, p, n, 8, 16)
		}
		if err = f.Close(); err != nil {
			return err
		}
	}
	return nil
}
func Macc_ConstMultSpecTest() error { return maccFiles(true) }
func Macc_ConstMultGenTest() error  { return maccFiles(false) }
