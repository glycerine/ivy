const TAB_UNUSED int32 = 65535
const ABC_PRIME_MASK = 255

type Tab_Ent_t struct{ Table, Cube, VarA, VarB, Next int32 }
type Tab_Man_t struct {
	nVars, nCubes, nLits, nTable, Degree, Mask, nEnts int32
	pCubes                                            []int32
	pValues                                           []uint64
	pTable                                            []Tab_Ent_t
	bins                                              map[int32]int32
}

func Tab_ManCube(p *Tab_Man_t, i int32) []int32 {
	if i < 0 || i >= p.nCubes {
		panic("invalid cube index")
	}
	start := int(i) * int(p.nVars+1)
	return p.pCubes[start : start+int(p.nVars+1)]
}
func Tab_ManEnt(p *Tab_Man_t, i int32) *Tab_Ent_t {
	if i == -1 {
		return nil
	}
	if i < 0 || int(i) >= len(p.pTable) {
		panic("invalid hash entry")
	}
	return &p.pTable[i]
}
func Tab_ManValue(_ *Tab_Man_t, a int32) int32 {
	if a < 0 || a > 255 {
		panic("literal outside hash range")
	}
	return int32(s_256Primes[a])
}
func Tab_ManFinal(p *Tab_Man_t, a int32) int32 { return a & p.Mask }
func Tab_ManHashValue(p *Tab_Man_t, cube []int32) uint64 {
	return Tab_ManHashValueWithoutVar(p, cube, -1)
}
func Tab_ManHashValueWithoutVar(p *Tab_Man_t, cube []int32, skip int32) uint64 {
	var value uint64
	for i := int32(1); i <= cube[0]; i++ {
		if i != skip {
			value += uint64(int64(Tab_ManValue(p, cube[i])))
		}
	}
	return value
}
func Tab_ManHashValueCube(p *Tab_Man_t, c, skip int32) uint32 {
	value := p.pValues[c]
	if skip != TAB_UNUSED {
		value -= uint64(int64(Tab_ManValue(p, Tab_ManCube(p, c)[skip+1])))
	}
	return uint32(value % uint64(p.nTable))
}
func Tab_ManPrintCube(p *Tab_Man_t, c, _ int32) {
	cube := Tab_ManCube(p, c)
	for _, lit := range cube[1 : cube[0]+1] {
		fmt.Printf("%d", 1-(lit&1))
	}
}
func Tab_ManHashAdd(p *Tab_Man_t, value, cube, a, b int32) {
	if value < 0 || value >= p.nTable {
		panic("invalid hash bin")
	}
	next := int32(-1)
	if head, ok := p.bins[value]; ok {
		next = head
	}
	entry := Tab_Ent_t{Table: -1, Cube: cube, VarA: a, VarB: b, Next: next}
	p.pTable = append(p.pTable, entry)
	p.bins[value] = p.nEnts
	p.nEnts++
}
func Tab_ManPrintEntry(p *Tab_Man_t, e int32) {
	entry := Tab_ManEnt(p, e)
	fmt.Printf("Entry %10d : Cube %6d  Value %12d  ", e, entry.Cube, Tab_ManHashValueCube(p, entry.Cube, entry.VarA))
	Tab_ManPrintCube(p, entry.Cube, entry.VarA)
	fmt.Printf("   %d %d\n", entry.VarA, entry.VarB)
}
func Tab_ManHashCollectBin(p *Tab_Man_t, bin int32, result *vec.Vec_Int_t) {
	vec.Vec_IntClear(result)
	head, ok := p.bins[bin]
	if !ok {
		return
	}
	for head != -1 {
		vec.Vec_IntPush(result, head)
		head = p.pTable[head].Next
	}
}
func Tab_ManAlloc(vars, cubes int32) *Tab_Man_t {
	if vars < 0 || vars > 128 || cubes < 0 || int64(cubes)*int64(vars+1) > 1<<31-1 {
		panic("invalid cube table dimensions")
	}
	degree := int32(bits.Len64(uint64(int64(vars+1)*int64(cubes)))) + 3
	p := &Tab_Man_t{nVars: vars, nCubes: cubes, Degree: degree, pCubes: make([]int32, int(cubes)*int(vars+1)), pValues: make([]uint64, cubes), bins: map[int32]int32{}}
	p.Mask = int32(uint64(1)<<uint(degree) - 1)
	return p
}
func Tab_ManFree(p *Tab_Man_t) {
	if p != nil {
		*p = Tab_Man_t{}
	}
}
func Tab_ManStart(p *Tab_Man_t, cubes *vec.Vec_Int_t) {
	if vec.Vec_IntSize(cubes) != int(p.nCubes) {
		panic("cube count mismatch")
	}
	p.nLits = 0
	for c := int32(0); c < p.nCubes; c++ {
		cube := Tab_ManCube(p, c)
		cube[0] = p.nVars
		value := vec.Vec_IntEntry(cubes, int(c))
		for v := int32(0); v < p.nVars; v++ {
			cube[v+1] = 2*v + 1 - (value >> v & 1)
		}
		p.pValues[c] = Tab_ManHashValue(p, cube)
		p.nLits += p.nVars
	}
}
func Tab_ManCubeFree(a, b []int32, result *vec.Vec_Int_t) int32 {
	a = a[1 : a[0]+1]
	b = b[1 : b[0]+1]
	vec.Vec_IntClear(result)
	i, j, count := 0, 0, int32(0)
	attr0, attr1 := int32(0), int32(1)
	for i < len(a) && j < len(b) {
		switch {
		case a[i] == b[j]:
			i++
			j++
			count++
		case a[i] < b[j]:
			vec.Vec_IntPush(result, 2*a[i]+attr0)
			i++
		default:
			if vec.Vec_IntSize(result) == 0 {
				attr0, attr1 = 1, 0
			}
			vec.Vec_IntPush(result, 2*b[j]+attr1)
			j++
		}
	}
	for ; i < len(a); i++ {
		vec.Vec_IntPush(result, 2*a[i]+attr0)
	}
	for ; j < len(b); j++ {
		vec.Vec_IntPush(result, 2*b[j]+attr1)
	}
	return count
}
func Tab_ManCheckEqual(a, b []int32, skipA, skipB int32) int32 {
	i, j := int32(1), int32(1)
	for {
		if i == skipA {
			i++
		}
		if j == skipB {
			j++
		}
		if i > a[0] || j > b[0] {
			if i > a[0] && j > b[0] {
				return 1
			}
			return 0
		}
		if a[i] != b[j] {
			return 0
		}
		i++
		j++
	}
}
func Tab_ManCheckEqual2(a, b []int32, skipA, skipB int32) int32 {
	return Tab_ManCheckEqual(a, b, skipA, skipB)
}
func Tab_ManCountItems(p *Tab_Man_t, distance2 int32) (int32, *vec.Vec_Int_t) {
	starts := vec.Vec_IntAlloc(int(p.nCubes))
	var count int64
	for c := int32(0); c < p.nCubes; c++ {
		cube := Tab_ManCube(p, c)
		vec.Vec_IntPush(starts, int32(count))
		if cube[0] < 0 {
			continue
		}
		count += 1 + int64(cube[0])
		if distance2 != 0 {
			count += int64(cube[0]) * int64(cube[0]-1) / 2
		}
		if count > 1<<31-1 {
			panic("cube item count overflow")
		}
	}
	return int32(count), starts
}

type tabVariant struct {
	value      uint64
	cube, a, b int32
}

func Tab_ManCollectDist1(p *Tab_Man_t, distance2 int32) *vec.Vec_Int_t {
	count, _ := Tab_ManCountItems(p, distance2)
	variants := make([]tabVariant, 0, count)
	for c := int32(0); c < p.nCubes; c++ {
		cube := Tab_ManCube(p, c)
		if cube[0] < 0 {
			continue
		}
		value := p.pValues[c]
		variants = append(variants, tabVariant{value, c, TAB_UNUSED, TAB_UNUSED})
		for a := int32(1); a <= cube[0]; a++ {
			variants = append(variants, tabVariant{value - uint64(int64(Tab_ManValue(p, cube[a]))), c, a - 1, TAB_UNUSED})
		}
		if distance2 != 0 {
			for a := int32(1); a <= cube[0]; a++ {
				for b := a + 1; b <= cube[0]; b++ {
					variants = append(variants, tabVariant{value - uint64(int64(Tab_ManValue(p, cube[a]))) - uint64(int64(Tab_ManValue(p, cube[b]))), c, a - 1, b - 1})
				}
			}
		}
	}
	// Two directional bitmap scans in C mark every item whose truncated hash
	// occurs more than once. Counting the same slots gives identical marks.
	width := bits.Len32(uint32(max(1, count)-1)) + 6
	mask := uint32(1)<<uint(width) - 1
	frequency := map[uint32]int{}
	for _, v := range variants {
		frequency[uint32(v.value)&mask]++
	}
	useful := int32(0)
	for _, v := range variants {
		if frequency[uint32(v.value)&mask] > 1 {
			useful++
		}
	}
	p.nTable = util.Abc_PrimeCudd(uint32(useful))
	p.nEnts = 0
	p.pTable = nil
	p.bins = map[int32]int32{}
	for _, v := range variants {
		if frequency[uint32(v.value)&mask] > 1 {
			Tab_ManHashAdd(p, int32(v.value%uint64(p.nTable)), v.cube, v.a, v.b)
		}
	}
	keys := make([]int32, 0, len(p.bins))
	for k := range p.bins {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	result := vec.Vec_IntAlloc(1000)
	for _, bin := range keys {
		for a := p.bins[bin]; a != -1; a = p.pTable[a].Next {
			for b := p.pTable[a].Next; b != -1; b = p.pTable[b].Next {
				ea, eb := p.pTable[a], p.pTable[b]
				if Tab_ManCheckEqual(Tab_ManCube(p, ea.Cube), Tab_ManCube(p, eb.Cube), ea.VarA+1, eb.VarA+1) != 0 {
					vec.Vec_IntPush(result, ea.Cube)
					vec.Vec_IntPush(result, eb.Cube)
				}
			}
		}
	}
	return result
}
func Tab_DecomposeTest() {
	started := time.Now()
	primes := Abc_GenPrimes(20)
	p := Tab_ManAlloc(20, int32(vec.Vec_IntSize(primes)))
	Tab_ManStart(p, primes)
	pairs := Tab_ManCollectDist1(p, 0)
	fmt.Printf("Created %d cubes dependent on %d variables.\nCollected %d pairs.\nTime = %v\n", p.nCubes, p.nVars, vec.Vec_IntSize(pairs)/2, time.Since(started))
}
