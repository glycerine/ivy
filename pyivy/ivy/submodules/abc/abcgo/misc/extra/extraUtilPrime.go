func Abc_GenCountDump(primes *vec.Vec_Int_t, n int32, name string) error {
	if n < 1 || n > 30 {
		return fmt.Errorf("invalid prime bit width")
	}
	file, err := os.Create(name)
	if err != nil {
		return err
	}
	fmt.Fprintf(file, "# %d prime numbers up to 2^%d generated by ABC on %s\n.i %d\n.o 1\n.p %d\n", vec.Vec_IntSize(primes), n, Extra_TimeStamp(), n, vec.Vec_IntSize(primes))
	for _, prime := range vec.Vec_IntArray(primes) {
		if _, err = fmt.Fprintf(file, "%0*b 1\n", int(n), prime); err != nil {
			file.Close()
			return err
		}
	}
	fmt.Fprint(file, ".e\n\n")
	return file.Close()
}
func Abc_GenCountHits1(composite *vec.Vec_Bit_t, primes *vec.Vec_Int_t, n int32) {
	started := time.Now()
	count := int64(0)
	for _, prime := range vec.Vec_IntArray(primes) {
		for k := int32(0); k < n; k++ {
			if vec.Vec_BitEntry(composite, int(prime^(1<<k))) == 0 {
				count++
			}
		}
	}
	fmt.Printf("Dist1 pairs = %d. Time = %v\n", count/2, time.Since(started))
}
func primeSieve(n int32) (*vec.Vec_Bit_t, *vec.Vec_Int_t) {
	if n < 1 || n > 30 {
		panic("prime sieve requires 1..30 bits")
	}
	limit := 1 << n
	composite := vec.Vec_BitStart(int(limit))
	vec.Vec_BitWriteEntry(composite, 0, 1)
	vec.Vec_BitWriteEntry(composite, 1, 1)
	for p := 2; p <= int(limit-1)/p; p++ {
		if vec.Vec_BitEntry(composite, p) != 0 {
			continue
		}
		for multiple := p * p; multiple < int(limit); multiple += p {
			vec.Vec_BitWriteEntry(composite, multiple, 1)
		}
	}
	primes := vec.Vec_IntAlloc(1000)
	for p := 2; p < int(limit); p++ {
		if vec.Vec_BitEntry(composite, p) == 0 {
			vec.Vec_IntPush(primes, int32(p))
		}
	}
	return composite, primes
}
func Abc_GenPrimes(n int32) *vec.Vec_Int_t {
	composite, primes := primeSieve(n)
	fmt.Printf("Primes up to 2^%d = %d\n", n, vec.Vec_IntSize(primes))
	Abc_GenCountHits1(composite, primes, n)
	return primes
}
