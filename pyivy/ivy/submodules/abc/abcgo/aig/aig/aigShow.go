package aig

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// Aig_WriteDotAig writes ABC's levelized AIG visualization. The history flag is
// retained for source compatibility; the C implementation's history-edge code
// was disabled. Bold node selection does not borrow graph traversal marks.
func Aig_WriteDotAig(p *Graph, path string, history int32, bold []Edge) error {
	data, err := aigDOT(p, bold)
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0644)
}
func aigDOT(p *Graph, bold []Edge) ([]byte, error) {
	if err := p.Check(); err != nil {
		return nil, err
	}
	if Aig_ManNodeNum(p) > 200 {
		return nil, fmt.Errorf("aig: cannot visualize more than 200 internal nodes")
	}
	highlighted := make(map[int]bool)
	for _, e := range bold {
		if !p.valid(e) {
			return nil, fmt.Errorf("aig: invalid highlighted node")
		}
		highlighted[e.NodeID()] = true
	}
	levelMax := int(Aig_ManLevelNum(p)) + 1
	// Unlike C's implicit DOT nodes for high dangling gates, give every live
	// object an explicit rank and label. Outputs remain above all logic.
	for id, n := range p.nodes {
		if !p.deleted[id] && (n.Kind == And || n.Kind == ExclusiveOr || n.Kind == Buffer) {
			levelMax = max(levelMax, n.Level+1)
		}
	}
	var b bytes.Buffer
	b.WriteString(`# AIG structure generated by IVY package

digraph AIG {
size = "7.5,10";
center = true;
edge [dir = back];

`)
	if p.Name != "" {
		fmt.Fprintf(&b, "label=%s;\n", strconv.Quote(p.Name))
	}
	b.WriteString("{\n  node [shape = plaintext];\n  edge [style = invis];\n  LevelTitle1 [label=\"\"];\n  LevelTitle2 [label=\"\"];\n")
	for level := levelMax; level >= 0; level-- {
		fmt.Fprintf(&b, "  Level%d [label = \"\"];\n", level)
	}
	b.WriteString("  LevelTitle1 ->  LevelTitle2 ->")
	for level := levelMax; level >= 0; level-- {
		fmt.Fprintf(&b, "  Level%d", level)
		if level != 0 {
			b.WriteString(" ->")
		} else {
			b.WriteString(";")
		}
	}
	b.WriteString("\n}\n\n")
	b.WriteString(`{
  rank = same;
  LevelTitle1;
  title1 [shape=plaintext,
          fontsize=20,
          fontname = "Times-Roman",
          label="AIG structure visualized by ABC\nBenchmark \"aig\". "
         ];
}

{
  rank = same;
  LevelTitle2;
  title2 [shape=plaintext,
          fontsize=18,
          fontname = "Times-Roman",
          label="`)
	fmt.Fprintf(&b, "The set contains %d logic nodes and spans %d levels.\\n\"\n         ];\n}\n\n", Aig_ManNodeNum(p), levelMax)
	writeNode := func(e Edge) {
		n, id := p.node(e), e.NodeID()
		shape, label := "ellipse", fmt.Sprint(id)
		terminal := false
		switch n.Kind {
		case Constant:
			label, terminal = "Const1", true
		case Input:
			shape, terminal = "triangle", true
		case Output:
			shape, terminal = "invtriangle", true
		case ExclusiveOr:
			shape = "doublecircle"
		case Buffer:
			shape = "diamond"
		}
		fmt.Fprintf(&b, "  Node%d [label = %s, shape = %s", id, strconv.Quote(label), shape)
		if terminal {
			b.WriteString(", color = coral, fillcolor = coral")
		} else if highlighted[id] {
			b.WriteString(", style = filled")
		}
		b.WriteString("];\n")
	}
	beginRank := func(level int) { fmt.Fprintf(&b, "{\n  rank = same;\n  Level%d;\n", level) }
	endRank := func() { b.WriteString("}\n\n") }
	beginRank(levelMax)
	for _, e := range p.outputs {
		writeNode(e)
	}
	endRank()
	for level := levelMax - 1; level > 0; level-- {
		beginRank(level)
		for id, n := range p.nodes {
			if !p.deleted[id] && n.Kind != Input && n.Kind != Output && n.Kind != Constant && n.Level == level {
				writeNode(Edge(id) << 1)
			}
		}
		endRank()
	}
	beginRank(0)
	if p.node(p.Const1()).Refs > 0 {
		writeNode(p.Const1())
	}
	for _, e := range p.inputs {
		writeNode(e)
	}
	for id, n := range p.nodes {
		if !p.deleted[id] && n.Level == 0 && (n.Kind == And || n.Kind == ExclusiveOr || n.Kind == Buffer) {
			writeNode(Edge(id) << 1)
		}
	}
	endRank()
	b.WriteString("title1 -> title2 [style = invis];\n")
	for _, e := range p.outputs {
		fmt.Fprintf(&b, "title2 -> Node%d [style = invis];\n", e.NodeID())
	}
	for i := 1; i < len(p.outputs); i++ {
		fmt.Fprintf(&b, "Node%d -> Node%d [style = invis];\n", p.outputs[i-1].NodeID(), p.outputs[i].NodeID())
	}
	for id, n := range p.nodes {
		if p.deleted[id] {
			continue
		}
		for _, fanin := range nodeFanins(n) {
			style := "bold"
			if fanin.Complemented() {
				style = "dotted"
			}
			fmt.Fprintf(&b, "Node%d -> Node%d [style = %s];\n", id, fanin.NodeID(), style)
		}
	}
	b.WriteString("}\n\n")
	return b.Bytes(), nil
}

// Aig_ManShow creates the DOT artifact and returns its path. Rendering/display
// belongs to the caller, keeping the port independent of external GUI commands.
func Aig_ManShow(p *Graph, history int32, bold []Edge) (string, error) {
	name := p.Name
	if name == "" || name == "." {
		name = "aig"
	}
	name = strings.TrimSuffix(name, filepath.Ext(name)) + ".dot"
	if err := Aig_WriteDotAig(p, name, history, bold); err != nil {
		return "", err
	}
	return name, nil
}
