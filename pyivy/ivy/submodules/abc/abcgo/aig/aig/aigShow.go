package aig

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
)

// Aig_WriteDotAig writes ABC's levelized AIG visualization. The history flag is
// retained for source compatibility; the C implementation's history-edge code
// was disabled. Bold node selection does not borrow graph traversal marks.
func Aig_WriteDotAig(p *Graph, path string, history int32, bold []Edge) error {
	data, err := aigDOT(p, bold)
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0644)
}
func aigDOT(p *Graph, bold []Edge) ([]byte, error) {
	if err := p.Check(); err != nil {
		return nil, err
	}
	if Aig_ManNodeNum(p) > 200 {
		return nil, fmt.Errorf("aig: cannot visualize more than 200 internal nodes")
	}
	highlighted := make(map[int]bool)
	for _, e := range bold {
		if !p.valid(e) {
			return nil, fmt.Errorf("aig: invalid highlighted node")
		}
		highlighted[e.NodeID()] = true
	}
	ranks := make(map[int][]int)
	max := int(Aig_ManLevelNum(p)) + 1
	for id, n := range p.nodes {
		if p.deleted[id] {
			continue
		}
		level := n.Level
		if n.Kind == Output {
			level = max
		}
		ranks[level] = append(ranks[level], id)
	}
	var b bytes.Buffer
	b.WriteString("// AIG structure generated by ABC Go\ndigraph AIG {\n  size=\"7.5,10\";\n  center=true;\n  edge [dir=back];\n")
	if p.Name != "" {
		fmt.Fprintf(&b, "  label=%s;\n", strconv.Quote(p.Name))
	}
	levels := make([]int, 0, len(ranks))
	for level := range ranks {
		levels = append(levels, level)
	}
	sort.Sort(sort.Reverse(sort.IntSlice(levels)))
	for _, level := range levels {
		fmt.Fprintf(&b, "  { rank=same; Level%d [shape=plaintext,label=%s];", level, strconv.Quote(fmt.Sprint(level)))
		for _, id := range ranks[level] {
			fmt.Fprintf(&b, " Node%d;", id)
		}
		b.WriteString(" }\n")
	}
	for i := 1; i < len(levels); i++ {
		fmt.Fprintf(&b, "  Level%d -> Level%d [style=invis];\n", levels[i-1], levels[i])
	}
	for id, n := range p.nodes {
		if p.deleted[id] {
			continue
		}
		shape, label := "ellipse", fmt.Sprint(id)
		switch n.Kind {
		case Constant:
			shape, label = "box", "1"
		case Input:
			shape = "triangle"
			label = fmt.Sprintf("PI %d", Aig_ObjCioId(p, Edge(id)<<1))
		case Output:
			shape = "invtriangle"
			label = fmt.Sprintf("PO %d", Aig_ObjCioId(p, Edge(id)<<1))
		case ExclusiveOr:
			shape = "doublecircle"
		case Buffer:
			shape = "diamond"
		}
		style := "solid"
		if highlighted[id] {
			style = "filled,bold"
		}
		fmt.Fprintf(&b, "  Node%d [shape=%s,label=%s,style=%s];\n", id, shape, strconv.Quote(label), strconv.Quote(style))
		for _, fanin := range nodeFanins(n) {
			edgeStyle := "bold"
			if fanin.Complemented() {
				edgeStyle = "dotted"
			}
			fmt.Fprintf(&b, "  Node%d -> Node%d [style=%s];\n", id, fanin.NodeID(), edgeStyle)
		}
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// Aig_ManShow creates the DOT artifact and returns its path. Rendering/display
// belongs to the caller, keeping the port independent of external GUI commands.
func Aig_ManShow(p *Graph, history int32, bold []Edge) (string, error) {
	name := filepath.Base(p.Name)
	if name == "" || name == "." {
		name = "aig"
	}
	name += ".dot"
	if err := Aig_WriteDotAig(p, name, history, bold); err != nil {
		return "", err
	}
	return name, nil
}
