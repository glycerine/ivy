package ivy

import (
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"sync/atomic"
	"time"
)

var ivyShowCounter atomic.Uint64

// Ivy_ManShow writes a DOT file and asks the platform's default opener to
// display it. The file remains available for inspection if no opener exists.
func Ivy_ManShow(p *Ivy_Man_t, haig int32, bold *Vec_Ptr_t) {
	name := fmt.Sprintf("temp%02d.dot", ivyShowCounter.Add(1)-1)
	Ivy_WriteDotAig(p, name, haig, bold)
	var cmd *exec.Cmd
	switch runtime.GOOS {
	case "darwin":
		cmd = exec.Command("open", name)
	case "windows":
		cmd = exec.Command("cmd", "/c", "start", "", name)
	default:
		cmd = exec.Command("xdg-open", name)
	}
	if err := cmd.Start(); err == nil {
		_ = cmd.Process.Release()
	}
}

// Ivy_WriteDotAig serializes a manager as Graphviz DOT. A temporary list of
// original bold marks is restored even if file generation panics.
func Ivy_WriteDotAig(p *Ivy_Man_t, filename string, haig int32, bold *Vec_Ptr_t) {
	if Ivy_ManNodeNum(p) > 200 {
		fmt.Fprintln(os.Stdout, "Cannot visualize AIG with more than 200 nodes.")
		return
	}
	file, err := os.Create(filename)
	if err != nil {
		fmt.Fprintf(os.Stdout, "Cannot open the intermediate file %q.\n", filename)
		return
	}
	defer file.Close()

	oldBold := make(map[*Ivy_Obj_t]int32)
	if bold != nil {
		for i := int32(0); i < Vec_PtrSize(bold); i++ {
			node, ok := Vec_PtrEntry(bold, i).(*Ivy_Obj_t)
			if !ok || node == nil {
				continue
			}
			node = Ivy_Regular(node)
			if _, seen := oldBold[node]; !seen {
				oldBold[node] = node.fMarkB
			}
			node.fMarkB = 1
		}
	}
	defer func() {
		for node, mark := range oldBold {
			node.fMarkB = mark
		}
	}()

	levelMax := 1 + Ivy_ManSetLevels(p, haig)
	w := func(format string, args ...any) { _, _ = fmt.Fprintf(file, format, args...) }
	w("# AIG structure generated by IVY package\n\n")
	w("digraph AIG {\nsize = \"7.5,10\";\ncenter = true;\nedge [dir = back];\n\n")
	w("{\n  node [shape = plaintext];\n  edge [style = invis];\n")
	w("  LevelTitle1 [label=\"\"];\n  LevelTitle2 [label=\"\"];\n")
	for level := levelMax; level >= 0; level-- {
		w("  Level%d [label = \"\"];\n", level)
	}
	w("  LevelTitle1 -> LevelTitle2 ->")
	for level := levelMax; level >= 0; level-- {
		w(" Level%d", level)
		if level != 0 {
			w(" ->")
		} else {
			w(";")
		}
	}
	w("\n}\n\n")

	w("{\n  rank = same;\n  LevelTitle1;\n")
	w("  title1 [shape=plaintext, fontsize=20, fontname=\"Times-Roman\", label=\"")
	w("AIG structure visualized by ABC\\nBenchmark \\\"aig\\\". Time was %s.\"];\n", time.Now().Format("Mon Jan _2 15:04:05 2006"))
	w("}\n\n")
	w("{\n  rank = same;\n  LevelTitle2;\n")
	w("  title2 [shape=plaintext, fontsize=18, fontname=\"Times-Roman\", label=\"The set contains %d logic nodes and spans %d levels.\\n\"];\n", Ivy_ManNodeNum(p), levelMax)
	w("}\n\n")

	w("{\n  rank = same;\n  Level%d;\n", levelMax)
	for _, node := range p.vObjs {
		if node == nil || Ivy_ObjIsCo(node) == 0 {
			continue
		}
		writeIvyDotLabel(w, node, haig, "_in")
		if Ivy_ObjIsLatch(node) != 0 {
			w(", shape = box")
		} else {
			w(", shape = invtriangle")
		}
		w(", color = coral, fillcolor = coral];\n")
	}
	w("}\n\n")

	for level := levelMax - 1; level > 0; level-- {
		w("{\n  rank = same;\n  Level%d;\n", level)
		for _, node := range p.vObjs {
			if node == nil || node.Level != level || Ivy_ObjIsCo(node) != 0 {
				continue
			}
			writeIvyDotLabel(w, node, haig, "")
			w(", shape = ellipse")
			if bold != nil && node.fMarkB != 0 {
				w(", style = filled")
			}
			w("];\n")
		}
		w("}\n\n")
	}

	w("{\n  rank = same;\n  Level0;\n")
	constant := Ivy_ManConst1(p)
	if Ivy_ObjRefs(constant) > 0 {
		w("  Node%d [label = \"Const1\", shape = ellipse, color = coral, fillcolor = coral];\n", constant.Id)
	}
	for _, node := range p.vObjs {
		if node == nil || Ivy_ObjIsCi(node) == 0 {
			continue
		}
		writeIvyDotLabel(w, node, haig, "_out")
		if Ivy_ObjIsLatch(node) != 0 {
			w(", shape = box")
		} else {
			w(", shape = triangle")
		}
		w(", color = coral, fillcolor = coral];\n")
	}
	w("}\n\n")
	w("title1 -> title2 [style = invis];\n")
	for _, node := range p.vObjs {
		if node != nil && Ivy_ObjIsCo(node) != 0 {
			w("title2 -> Node%d%s [style = invis];\n", node.Id, ivyLatchSuffix(node, "_in"))
		}
	}

	for _, node := range p.vObjs {
		if node == nil || Ivy_ObjIsNode(node) == 0 && Ivy_ObjIsCo(node) == 0 && Ivy_ObjIsBuf(node) == 0 {
			continue
		}
		w("Node%d%s -> Node%d%s [style = %s];\n", node.Id, ivyLatchSuffix(node, "_in"), Ivy_ObjFaninId0(node), ivyLatchSuffix(Ivy_ObjFanin0(node), "_out"), ivyDotEdgeStyle(Ivy_ObjFaninC0(node)))
		if Ivy_ObjIsNode(node) != 0 {
			w("Node%d -> Node%d%s [style = %s];\n", node.Id, Ivy_ObjFaninId1(node), ivyLatchSuffix(Ivy_ObjFanin1(node), "_out"), ivyDotEdgeStyle(Ivy_ObjFaninC1(node)))
		}
		if haig == 0 || node.pEquiv == nil || Ivy_ObjRefs(node) == 0 {
			continue
		}
		prev := node
		seen := map[*Ivy_Obj_t]bool{node: true}
		for edge := node.pEquiv; edge != node; edge = Ivy_Regular(edge.pEquiv) {
			temp := Ivy_Regular(edge)
			if temp == nil || seen[temp] {
				break
			}
			seen[temp] = true
			w("Node%d -> Node%d [style = %s];\n", prev.Id, temp.Id, ivyDotEdgeStyle(Ivy_IsComplement(edge)))
			prev = temp
		}
		if prev != node {
			w("Node%d -> Node%d [style = %s];\n", prev.Id, node.Id, ivyDotEdgeStyle(Ivy_IsComplement(prev.pEquiv)))
		}
	}
	w("}\n}\n")
}

func writeIvyDotLabel(w func(string, ...any), node *Ivy_Obj_t, haig int32, suffix string) {
	if haig != 0 || node.pEquiv == nil {
		w("  Node%d%s [label = \"%d%s\"", node.Id, ivyLatchSuffix(node, suffix), node.Id, ivyLatchSuffix(node, suffix))
		return
	}
	compl := ""
	if Ivy_IsComplement(node.pEquiv) != 0 {
		compl = "'"
	}
	w("  Node%d%s [label = \"%d%s(%d%s)\"", node.Id, ivyLatchSuffix(node, suffix), node.Id, ivyLatchSuffix(node, suffix), Ivy_ObjId(node.pEquiv), compl)
}

func ivyLatchSuffix(node *Ivy_Obj_t, suffix string) string {
	if node != nil && Ivy_ObjIsLatch(node) != 0 {
		return suffix
	}
	return ""
}

func ivyDotEdgeStyle(complement int32) string {
	if complement != 0 {
		return "dotted"
	}
	return "bold"
}
