        fmt.Fprintf(pFile, ";\n");
        if !Gia_ObjIsAnd(pNode) {
            continue; }
        // generate the edge from this node to the next
        fmt.Fprintf(pFile, "Node%d", i);
        fmt.Fprintf(pFile, " -> ");
        fmt.Fprintf(pFile, "Node%d", Gia_ObjFaninId1(pNode, i));
        fmt.Fprintf(pFile, " [");
