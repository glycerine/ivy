package gia

import (
	"fmt"
	"io"
	"os"

	"github.com/glycerine/abcgo/misc/vec"
)

const showNodeMax = 2000

// Gia_WriteDotAigSimple writes an AIG in Graphviz DOT format.
func Gia_WriteDotAigSimple(p *Gia_Man_t, filename string, bold *Vec_Int_t) {
	if Gia_ManAndNum(p) > showNodeMax {
		fmt.Printf("Cannot visualize AIG with more than %d nodes.\n", showNodeMax)
		return
	}
	f, err := os.Create(filename)
	if err != nil {
		fmt.Printf("Cannot open the intermediate file %q.\n", filename)
		return
	}
	defer f.Close()
	giaWriteDotSimple(f, p, bold)
}

func giaWriteDotSimple(w io.Writer, p *Gia_Man_t, bold *Vec_Int_t) {
	marked := make([]bool, p.nObjs)
	if bold != nil {
		for _, id := range vec.Vec_IntArray(bold) {
			marked[id] = true
		}
	} else if p.nXors != 0 || p.nMuxes != 0 {
		for _, obj := range p.pObjs {
			if Gia_ObjIsXor(obj) != 0 || Gia_ObjIsMux(p, obj) != 0 {
				marked[obj.id] = true
			}
		}
	}
	levelMax := Gia_ManLevelNum(p) + 1
	defer func() { p.vLevels = nil }()
	for _, id := range vec.Vec_IntArray(p.vCos) {
		Gia_ObjSetLevelId(p, id, levelMax)
	}
	fmt.Fprintln(w, "# AIG structure generated by GIA package\n\ndigraph AIG {\nsize = \"7.5,10\";\ncenter = true;\nedge [dir = back];")
	fmt.Fprintln(w, "{\n  node [shape = plaintext];\n  edge [style = invis];\n  LevelTitle1 [label=\"\"];\n  LevelTitle2 [label=\"\"];")
	for level := levelMax; level >= 0; level-- {
		fmt.Fprintf(w, "  Level%d [label = \"\"];\n", level)
	}
	fmt.Fprint(w, "  LevelTitle1 -> LevelTitle2")
	for level := levelMax; level >= 0; level-- {
		fmt.Fprintf(w, " -> Level%d", level)
	}
	fmt.Fprintln(w, ";\n}")
	fmt.Fprintln(w, "{ rank = same; LevelTitle1; title1 [shape=plaintext, fontsize=20, fontname=\"Times-Roman\", label=\"AIG structure visualized by ABC\\nBenchmark \\\"aig\\\". \" ]; }")
	fmt.Fprintf(w, "{ rank = same; LevelTitle2; title2 [shape=plaintext, fontsize=18, fontname=\"Times-Roman\", label=\"The AIG contains %d nodes and spans %d levels.\\n\" ]; }\n", Gia_ManAndNum(p), levelMax-1)
	fmt.Fprintf(w, "{ rank = same; Level%d;\n", levelMax)
	constant := false
	for _, id := range vec.Vec_IntArray(p.vCos) {
		obj := Gia_ManObj(p, id)
		if Gia_ObjFaninId0(obj, id) == 0 {
			constant = true
		}
		fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = invtriangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(w, "}")
	for level := levelMax - 1; level > 0; level-- {
		fmt.Fprintf(w, "{ rank = same; Level%d;\n", level)
		for _, obj := range p.pObjs {
			if Gia_ObjLevel(p, obj) != level {
				continue
			}
			shape := "ellipse"
			if Gia_ObjIsXor(obj) != 0 {
				shape = "doublecircle"
			} else if Gia_ObjIsMux(p, obj) != 0 {
				shape = "trapezium"
			}
			fill := ""
			if marked[obj.id] {
				fill = ", style = filled"
			}
			fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = %s%s];\n", obj.id, obj.id, shape, fill)
		}
		fmt.Fprintln(w, "}")
	}
	fmt.Fprintln(w, "{ rank = same; Level0;")
	if constant {
		fmt.Fprintln(w, "  Node0 [label = \"Const0\", shape = ellipse, color = coral, fillcolor = coral];")
	}
	for _, id := range vec.Vec_IntArray(p.vCis) {
		fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = triangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w, "title1 -> title2 [style = invis];")
	for _, id := range vec.Vec_IntArray(p.vCos) {
		fmt.Fprintf(w, "title2 -> Node%d [style = invis];\n", id)
	}
	for _, ids := range [][]int32{vec.Vec_IntArray(p.vCos), vec.Vec_IntArray(p.vCis)} {
		for i := 1; i < len(ids); i++ {
			fmt.Fprintf(w, "Node%d -> Node%d [style = invis];\n", ids[i-1], ids[i])
		}
	}
	edge := func(id, fan, compl int32, regular string) {
		style := regular
		if compl != 0 {
			style = "dotted"
		}
		fmt.Fprintf(w, "Node%d -> Node%d [style = %s];\n", id, fan, style)
	}
	for _, obj := range p.pObjs {
		id := obj.id
		if Gia_ObjIsAnd(obj) == 0 && Gia_ObjIsCo(obj) == 0 && Gia_ObjIsBuf(obj) == 0 {
			continue
		}
		edge(id, Gia_ObjFaninId0(obj, id), Gia_ObjFaninC0(obj), "solid")
		if Gia_ObjIsAnd(obj) == 0 {
			continue
		}
		edge(id, Gia_ObjFaninId1(obj, id), Gia_ObjFaninC1(obj), "solid")
		if Gia_ObjIsMux(p, obj) != 0 {
			edge(id, Gia_ObjFaninId2(p, id), Gia_ObjFaninC2(p, obj), "bold")
		}
	}
	fmt.Fprintln(w, "}")
}
