package gia

import (
	"fmt"
	"io"
	"os"

	"github.com/glycerine/abcgo/misc/vec"
)

type giaCriticalPath struct {
	levels              []int32
	marked              []bool
	depth, nodes, edges int32
}

// giaCriticalLuts traces every mapped edge on a longest output path.
func giaCriticalLuts(p *Gia_Man_t) giaCriticalPath {
	if Gia_ManHasMapping(p) == 0 {
		panic("gia: critical path requires LUT mapping")
	}
	result := giaCriticalPath{marked: make([]bool, p.nObjs)}
	result.depth = Gia_ManLutLevel(p, &result.levels)
	for _, id := range vec.Vec_IntArray(p.vCos) {
		obj := Gia_ManObj(p, id)
		fan := Gia_ObjFaninId0(obj, id)
		if result.levels[fan] == result.depth {
			result.marked[fan] = true
		}
	}
	for id := p.nObjs - 1; id > 0; id-- {
		if Gia_ObjIsLut(p, id) == 0 || !result.marked[id] {
			continue
		}
		result.nodes++
		for _, fan := range Gia_ObjLutFanins(p, id) {
			if result.levels[fan]+1 < result.levels[id] {
				continue
			}
			if result.levels[fan]+1 != result.levels[id] {
				panic("gia: invalid mapped level")
			}
			result.marked[fan] = true
			result.edges++
		}
	}
	return result
}

// Gia_ShowPath writes the critical mapped LUT cone as Graphviz DOT.
func Gia_ShowPath(p *Gia_Man_t, filename string) {
	path := giaCriticalLuts(p)
	if path.nodes > showNodeMax {
		fmt.Printf("Cannot visualize AIG with more than %d critical nodes.\n", showNodeMax)
		return
	}
	f, err := os.Create(filename)
	if err != nil {
		fmt.Printf("Cannot open the intermediate file %q.\n", filename)
		return
	}
	defer f.Close()
	p.vLevels = vec.Vec_IntAllocArray(path.levels, len(path.levels))
	defer func() { p.vLevels = nil }()
	giaWriteDotPath(f, p, path)
}

func giaWriteDotPath(w io.Writer, p *Gia_Man_t, path giaCriticalPath) {
	top := path.depth + 1
	fmt.Fprintln(w, "# AIG structure generated by GIA package\n\ndigraph AIG {\nsize = \"7.5,10\";\ncenter = true;\nedge [dir = back];")
	fmt.Fprintln(w, "{ node [shape = plaintext]; edge [style = invis]; LevelTitle1 [label=\"\"]; LevelTitle2 [label=\"\"];")
	for level := top; level >= 0; level-- {
		fmt.Fprintf(w, "  Level%d [label = \"\"];\n", level)
	}
	fmt.Fprint(w, "  LevelTitle1 -> LevelTitle2")
	for level := top; level >= 0; level-- {
		fmt.Fprintf(w, " -> Level%d", level)
	}
	fmt.Fprintln(w, ";\n}")
	fmt.Fprintln(w, "{ rank = same; LevelTitle1; title1 [shape=plaintext, fontsize=20, fontname=\"Times-Roman\", label=\"AIG structure visualized by ABC\\nBenchmark \\\"aig\\\". \" ]; }")
	fmt.Fprintf(w, "{ rank = same; LevelTitle2; title2 [shape=plaintext, fontsize=18, fontname=\"Times-Roman\", label=\"The critical path contains %d LUTs with %d critical edges and spans %d levels.\\n\" ]; }\n", path.nodes, path.edges, path.depth)
	fmt.Fprintf(w, "{ rank = same; Level%d;\n", top)
	var outputs []int32
	for _, id := range vec.Vec_IntArray(p.vCos) {
		obj := Gia_ManObj(p, id)
		if path.levels[Gia_ObjFaninId0(obj, id)] != path.depth {
			continue
		}
		outputs = append(outputs, id)
		fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = invtriangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(w, "}")
	for level := path.depth; level > 0; level-- {
		fmt.Fprintf(w, "{ rank = same; Level%d;\n", level)
		for _, obj := range p.pObjs {
			id := obj.id
			if !path.marked[id] || path.levels[id] != level {
				continue
			}
			label := id
			if p.vIdsOrig != nil && vec.Vec_IntSize(p.vIdsOrig) > 0 {
				label = vec.Vec_IntEntry(p.vIdsOrig, int(id))
			}
			size := int32(0)
			if Gia_ObjIsAnd(obj) != 0 {
				size = Gia_ObjLutSize(p, id)
			}
			fill := ""
			if obj.fMark0 != 0 {
				fill = ", style = filled"
			}
			fmt.Fprintf(w, "  Node%d [label = \"%d:%d\", shape = ellipse%s];\n", id, label, size, fill)
		}
		fmt.Fprintln(w, "}")
	}
	fmt.Fprintln(w, "{ rank = same; Level0;")
	var inputs []int32
	for _, id := range vec.Vec_IntArray(p.vCis) {
		if !path.marked[id] {
			continue
		}
		inputs = append(inputs, id)
		fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = triangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w, "title1 -> title2 [style = invis];")
	for _, id := range outputs {
		fmt.Fprintf(w, "title2 -> Node%d [style = invis];\n", id)
	}
	for _, ids := range [][]int32{outputs, inputs} {
		for i := 1; i < len(ids); i++ {
			fmt.Fprintf(w, "Node%d -> Node%d [style = invis];\n", ids[i-1], ids[i])
		}
	}
	for _, id := range outputs {
		obj := Gia_ManObj(p, id)
		fmt.Fprintf(w, "Node%d -> Node%d [style = solid];\n", id, Gia_ObjFaninId0(obj, id))
	}
	for id := int32(1); id < p.nObjs; id++ {
		if !path.marked[id] || Gia_ObjIsLut(p, id) == 0 {
			continue
		}
		for _, fan := range Gia_ObjLutFanins(p, id) {
			if path.levels[fan]+1 == path.levels[id] {
				fmt.Fprintf(w, "Node%d -> Node%d [style = solid];\n", id, fan)
			}
		}
	}
	fmt.Fprintln(w, "}")
}
