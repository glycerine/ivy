package gia

import (
	"fmt"
	"io"
	"os"

	"github.com/glycerine/abcgo/misc/vec"
)

// Gia_ShowProcess prepares grouped-node levels before writing DOT.
func Gia_ShowProcess(p *Gia_Man_t, filename string, bold, adds, xors *Vec_Int_t, fullOnly int32) {
	mapAdds := Gia_ShowMapAdds(p, adds, fullOnly, bold)
	mapXors := Gia_ShowMapXors(p, xors)
	order := Gia_ShowCollectObjs(p, adds, xors, mapAdds, mapXors)
	Gia_WriteDotAig(p, filename, bold, adds, xors, mapAdds, mapXors, order)
}

func Gia_WriteDotAig(p *Gia_Man_t, filename string, bold, adds, xors, mapAdds, mapXors, order *Vec_Int_t) {
	if Gia_ManAndNum(p) > showNodeMax {
		fmt.Printf("Cannot visualize AIG with more than %d nodes.\n", showNodeMax)
		return
	}
	f, err := os.Create(filename)
	if err != nil {
		fmt.Printf("Cannot open the intermediate file %q.\n", filename)
		return
	}
	defer f.Close()
	defer func() { p.vLevels = nil }()
	giaWriteDotGrouped(f, p, bold, adds, xors, mapAdds, mapXors, order)
}

func giaWriteDotGrouped(w io.Writer, p *Gia_Man_t, bold, adds, xors, mapAdds, mapXors, order *Vec_Int_t) {
	marked := make([]bool, p.nObjs)
	if bold != nil {
		for _, id := range vec.Vec_IntArray(bold) {
			marked[id] = true
		}
	}
	ad := vec.Vec_IntArray(adds)
	xd := vec.Vec_IntArray(xors)
	am := vec.Vec_IntArray(mapAdds)
	xm := vec.Vec_IntArray(mapXors)
	full := 0
	for i := 0; i < len(ad); i += 6 {
		if ad[i+2] != 0 {
			full++
		}
	}
	top := p.nLevels + 1
	for _, id := range vec.Vec_IntArray(p.vCos) {
		Gia_ObjSetLevelId(p, id, top)
	}
	fmt.Fprintln(w, "# AIG structure generated by GIA package\n\ndigraph AIG {\nsize = \"7.5,10\";\ncenter = true;\nedge [dir = back];")
	fmt.Fprintln(w, "{ node [shape = plaintext]; edge [style = invis]; LevelTitle1 [label=\"\"]; LevelTitle2 [label=\"\"];")
	for level := top; level >= 0; level-- {
		fmt.Fprintf(w, "  Level%d [label = \"\"];\n", level)
	}
	fmt.Fprint(w, "  LevelTitle1 -> LevelTitle2")
	for level := top; level >= 0; level-- {
		fmt.Fprintf(w, " -> Level%d", level)
	}
	fmt.Fprintln(w, ";\n}")
	fmt.Fprintln(w, "{ rank = same; LevelTitle1; title1 [shape=plaintext, fontsize=20, fontname=\"Times-Roman\", label=\"AIG structure visualized by ABC\\nBenchmark \\\"aig\\\". \" ]; }")
	fmt.Fprintf(w, "{ rank = same; LevelTitle2; title2 [shape=plaintext, fontsize=18, fontname=\"Times-Roman\", label=\"The AIG contains %d nodes, %d full-adders, and %d half-adders, and spans %d levels.\\n\" ]; }\n", Gia_ManAndNum(p), full, len(ad)/6-full, p.nLevels)
	fmt.Fprintf(w, "{ rank = same; Level%d;\n", top)
	constant := false
	for _, id := range vec.Vec_IntArray(p.vCos) {
		obj := Gia_ManObj(p, id)
		constant = constant || Gia_ObjFaninId0(obj, id) == 0
		fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = invtriangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(w, "}")
	for level := top - 1; level > 0; level-- {
		fmt.Fprintf(w, "{ rank = same; Level%d;\n", level)
		for _, id := range vec.Vec_IntArray(order) {
			obj := Gia_ManObj(p, id)
			if Gia_ObjLevel(p, obj) != level {
				continue
			}
			label := fmt.Sprint(id)
			shape := "ellipse"
			node := id
			if !marked[id] && am[id] >= 0 {
				box := 6 * am[id]
				node = ad[box+4]
				label = fmt.Sprintf("%d_%d", ad[box+3], ad[box+4])
				shape = "octagon"
				if ad[box+2] != 0 {
					shape = "doubleoctagon"
				}
			} else if xm[id] >= 0 || Gia_ObjIsXor(obj) != 0 {
				shape = "doublecircle"
			} else if Gia_ObjIsMux(p, obj) != 0 {
				shape = "trapezium"
			}
			fill := ""
			if marked[id] || obj.fMark0 != 0 {
				fill = ", style = filled"
			}
			fmt.Fprintf(w, "  Node%d [label = \"%s\", shape = %s%s];\n", node, label, shape, fill)
		}
		fmt.Fprintln(w, "}")
	}
	fmt.Fprintln(w, "{ rank = same; Level0;")
	if constant {
		fmt.Fprintln(w, "  Node0 [label = \"Const0\", shape = ellipse, color = coral, fillcolor = coral];")
	}
	for _, id := range vec.Vec_IntArray(p.vCis) {
		fmt.Fprintf(w, "  Node%d [label = \"%d\", shape = triangle, color = coral, fillcolor = coral];\n", id, id)
	}
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w, "title1 -> title2 [style = invis];")
	for _, id := range vec.Vec_IntArray(p.vCos) {
		fmt.Fprintf(w, "title2 -> Node%d [style = invis];\n", id)
	}
	for _, ids := range [][]int32{vec.Vec_IntArray(p.vCos), vec.Vec_IntArray(p.vCis)} {
		for i := 1; i < len(ids); i++ {
			fmt.Fprintf(w, "Node%d -> Node%d [style = invis];\n", ids[i-1], ids[i])
		}
	}
	edge := func(id, fan int32, style string) {
		fmt.Fprintf(w, "Node%d -> Node%d [style = %s];\n", id, Gia_ShowAddOut(adds, mapAdds, fan), style)
	}
	for _, id := range vec.Vec_IntArray(p.vCos) {
		obj := Gia_ManObj(p, id)
		style := "solid"
		if Gia_ObjFaninC0(obj) != 0 {
			style = "dotted"
		}
		edge(id, Gia_ObjFaninId0(obj, id), style)
	}
	for _, id := range vec.Vec_IntArray(order) {
		obj := Gia_ManObj(p, id)
		if am[id] >= 0 {
			box := 6 * am[id]
			for k := int32(0); k < 3; k++ {
				fan := ad[box+k]
				if fan == 0 {
					continue
				}
				style := "solid"
				other := am[fan]
				if other >= 0 && ad[6*other+3] == fan {
					style = "bold"
				}
				edge(ad[box+4], fan, style)
			}
			continue
		}
		if xm[id] >= 0 {
			box := 4 * xm[id]
			for k := int32(1); k < 4; k++ {
				fan := xd[box+k]
				if fan == 0 {
					continue
				}
				style := "solid"
				if xm[fan] >= 0 {
					style = "bold"
				}
				edge(id, fan, style)
			}
			continue
		}
		style := "solid"
		if Gia_ObjFaninC0(obj) != 0 {
			style = "dotted"
		}
		edge(id, Gia_ObjFaninId0(obj, id), style)
		if Gia_ObjIsAnd(obj) == 0 {
			continue
		}
		style = "solid"
		if Gia_ObjFaninC1(obj) != 0 {
			style = "dotted"
		}
		edge(id, Gia_ObjFaninId1(obj, id), style)
		if Gia_ObjIsMux(p, obj) != 0 {
			style = "solid"
			if Gia_ObjFaninC2(p, obj) != 0 {
				style = "dotted"
			}
			edge(id, Gia_ObjFaninId2(p, id), style)
		}
	}
	fmt.Fprintln(w, "}")
}
