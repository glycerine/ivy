// satNodeVar stores the SAT variable assigned to an ABC object in CopyData.
func satNodeVar(o *abc.Object) int32 {
	v, ok := o.CopyData.(int32)
	if !ok {
		panic("SAT variable missing from ABC object")
	}
	return v
}

