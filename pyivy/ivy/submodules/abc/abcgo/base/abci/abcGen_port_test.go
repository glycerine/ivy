func TestAbcWriteFullAdderOutput(t *testing.T) {
	f, err := os.CreateTemp(t.TempDir(), "full-adder-*.blif")
	if err != nil {
		t.Fatal(err)
	}
	Abc_WriteFullAdder(f)
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(f.Name())
	if err != nil {
		t.Fatal(err)
	}
	want := ".model FA\n.inputs a b cin\n.outputs s cout\n.names a b and1\n11 1\n.names a b and1_\n00 1\n.names and1 and1_ xor\n00 1\n.names cin xor and2\n11 1\n.names cin xor and2_\n00 1\n.names and2 and2_ s\n00 1\n.names and1 and2 cout\n00 0\n.end\n\n"
	if string(got) != want {
		t.Fatalf("full-adder output mismatch\ngot:\n%s", got)
	}
}

func TestAbcAdderTreeOutput(t *testing.T) {
	f, err := os.CreateTemp(t.TempDir(), "adder-tree-*.v")
	if err != nil {
		t.Fatal(err)
	}
	Abc_AdderTree(f, 2, 2)
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(f.Name())
	if err != nil {
		t.Fatal(err)
	}
	text := string(got)
	for _, line := range []string{
		"module adder_tree_2_2 (", "input i0_1, i1_1;", "output [2:0] z;",
		"wire [1:0] t0 = { i0_1, i0_0 };", "wire [2:0] s1 = t1 + t0;", "assign z = s1;", "endmodule",
	} {
		if !strings.Contains(text, line) {
			t.Errorf("missing %q in generated output:\n%s", line, text)
		}
	}
}

func TestAbcGenOneHotFileOutputAndClose(t *testing.T) {
	name := filepath.Join(t.TempDir(), "onehot.blif")
	Abc_GenOneHot(name, 2)
	got, err := os.ReadFile(name)
	if err != nil {
		t.Fatalf("read generated file (writer may not have closed it): %v", err)
	}
	text := string(got)
	if !strings.HasPrefix(text, "# One-hotness condition for 2 vars generated by ABC on ") {
		t.Fatalf("unexpected generator header: %q", text)
	}
	content := text[strings.IndexByte(text, '\n')+1:]
	want := ".model 1hot_2vars\n.inputs i0 i1\n.outputs o0\n.names i0 i1 o0\n11 0\n.end\n\n"
	if content != want {
		t.Fatalf("generated body mismatch\ngot:\n%s\nwant:\n%s", content, want)
	}
}

func TestAbcGenSignedBoothInterface(t *testing.T) {
	manager := Abc_GenSignedBooth(3, 3)
	if manager == nil {
		t.Fatal("Booth generator returned a nil manager")
	}
	defer gia.Gia_ManStop(manager)
	if got := gia.Gia_ManCiNum(manager); got != 6 {
		t.Fatalf("CI count = %d, want 6", got)
	}
	if got := gia.Gia_ManCoNum(manager); got != 18 {
		t.Fatalf("CO count = %d, want 18", got)
	}
}
