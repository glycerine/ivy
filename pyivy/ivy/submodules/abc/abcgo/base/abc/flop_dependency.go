package abc

import (
	"fmt"
	"io"
	"os"
	"time"
)

// WriteFlopDependency writes the support relationships among latch inputs.
func WriteFlopDependency(w io.Writer, n *Network) error {
	latches := n.ObjectsOfKind(ObjectLatch)
	outputs := make(map[*Object]int, len(latches))
	inputs := make([]*Object, len(latches))
	for i, latch := range latches {
		if len(latch.fanins) != 1 || len(latch.fanouts) != 1 {
			return fmt.Errorf("latch %d has invalid terminals", i)
		}
		inputs[i] = latch.fanins[0].Object
		outputs[latch.fanouts[0]] = i
	}
	if _, err := fmt.Fprintf(w, "# Flop dependency for %q generated by ABC on %s\ndigraph G {\n  graph [splines=true overlap=false];\n  size = \"7.5,10\";\n  center = true;\n  edge [dir=forward];\n", n.Name, time.Now().Format(time.RFC3339)); err != nil {
		return err
	}
	supports := make([][]*Object, len(inputs))
	for i, input := range inputs {
		supports[i] = Abc_NtkNodeSupport(n, []*Object{input}, 1)
		count := 0
		for _, obj := range supports[i] {
			if obj.Kind == ObjectPI {
				count++
			}
		}
		if _, err := fmt.Fprintf(w, "  { rank = same; %d [label=\"%d(%d)\"]; }\n", i, i, count); err != nil {
			return err
		}
	}
	for i, support := range supports {
		for _, obj := range support {
			if index, ok := outputs[obj]; ok {
				if _, err := fmt.Fprintf(w, "  %4d -> %4d\n", index, i); err != nil {
					return err
				}
			}
		}
	}
	_, err := fmt.Fprintln(w, "}")
	return err
}

func Abc_NtkWriteFlopDependency(n *Network, filename string) {
	file, err := os.Create(filename)
	if err != nil {
		fmt.Printf("Cannot open input file %s.\n", filename)
		return
	}
	if err = WriteFlopDependency(file, n); err == nil {
		err = file.Close()
	} else {
		file.Close()
	}
	if err != nil {
		fmt.Printf("Cannot write flop dependency file %s: %v\n", filename, err)
	}
}
