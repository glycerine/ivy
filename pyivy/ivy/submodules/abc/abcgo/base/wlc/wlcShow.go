// Wlc_NtkDumpDot writes a GraphViz representation of a word-level network.
func Wlc_NtkDumpDot(p *Wlc_Ntk_t, filename string, bold *Vec_Int_t) {
	if (bold != nil && Vec_IntSize(bold) > 2000) || (bold == nil && Wlc_NtkObjNum(p) > 2000) {
		fmt.Fprintln(os.Stdout, "Cannot visualize WLC with more than 2000 nodes.")
		return
	}
	f, err := os.Create(filename)
	if err != nil {
		fmt.Fprintf(os.Stdout, "Cannot open the intermediate file %q.\n", filename)
		return
	}
	defer f.Close()
	marked := func(o *Wlc_Obj_t) bool { return bold == nil || o.Mark != 0 }
	if bold != nil {
		for i := int32(0); i < Vec_IntSize(bold); i++ {
			Wlc_NtkObj(p, Vec_IntEntry(bold, i)).Mark = 1
		}
		defer Wlc_NtkCleanMarks(p)
	}
	lm := 1 + Wlc_NtkCreateLevels(p)
	if bold != nil {
		lm = Wlc_NtkRemapLevels(p, bold, lm)
	}
	fmt.Fprintln(f, "# WLC structure generated by ABC\n\ndigraph WLC {")
	fmt.Fprint(f, "size = \"7.5,10\";\ncenter = true;\nedge [dir = back];\n")
	fmt.Fprint(f, "{\n  node [shape = plaintext];\n  edge [style = invis];\n  LevelTitle1 [label=\"\"];\n  LevelTitle2 [label=\"\"];")
	for l := lm; l >= 0; l-- {
		fmt.Fprintf(f, "  Level%d [label = \"\"];\n", l)
	}
	fmt.Fprint(f, "  LevelTitle1 ->  LevelTitle2 ->")
	for l := lm; l >= 0; l-- {
		fmt.Fprintf(f, "  Level%d", l)
		if l != 0 {
			fmt.Fprint(f, " ->")
		} else {
			fmt.Fprint(f, ";")
		}
	}
	fmt.Fprint(f, "\n}\n")
	name := Extra_FileDesignName(p.pName)
	if name == "" {
		name = "unknown"
	}
	spec := "unknown"
	if p.pSpec != "" {
		spec = Extra_FileDesignName(p.pSpec)
	}
	fmt.Fprintf(f, "{\n  rank = same;\n  LevelTitle1;\n  title1 [shape=plaintext,\n          fontsize=20,\n          fontname = \"Times-Roman\",\n          label=\"WLC structure generated by ABC\\nBenchmark \\\"%s\\\" from file \\\"%s\\\". \"\n         ];\n}\n\n", name, spec)
	fmt.Fprintf(f, "{\n  rank = same;\n  LevelTitle2;\n  title2 [shape=plaintext,\n          fontsize=18,\n          fontname = \"Times-Roman\",\n          label=\"The word-level network contains %d nodes and spans %d levels.\\n\"\n         ];\n}\n\n", Wlc_NtkObjNum(p)-Wlc_NtkCiNum(p), lm-1)
	fmt.Fprintf(f, "{\n  rank = same;\n  Level%d;\n", lm)
	for i := int32(0); i < Wlc_NtkCoNum(p); i++ {
		o := Wlc_NtkCo(p, i)
		if !marked(o) {
			continue
		}
		po := Wlc_ObjCo2PoFo(p, i)
		fmt.Fprintf(f, "  NodePo%d [label = \"%s%s %d\", shape = %s, color = coral, fillcolor = coral];\n", Wlc_ObjId(p, po), Wlc_ObjName(p, Wlc_ObjId(p, po)), boolString(Wlc_ObjIsPo(po) != 0, "", "_in"), Wlc_ObjRange(po), boolString(i < Wlc_NtkPoNum(p), "invtriangle", "box"))
	}
	fmt.Fprint(f, "}\n")
	for l := lm - 1; l > 0; l-- {
		fmt.Fprintf(f, "{\n  rank = same;\n  Level%d;\n", l)
		for i := int32(1); i < Wlc_NtkObjNumMax(p); i++ {
			o := Wlc_NtkObj(p, i)
			if Wlc_ObjLevel(p, o) != l || !marked(o) {
				continue
			}
			writeDotNode(f, p, i, o, bold != nil)
		}
		fmt.Fprint(f, "}\n")
	}
	fmt.Fprintln(f, "{\n  rank = same;\n  Level0;")
	for i := int32(1); i < Wlc_NtkObjNumMax(p); i++ {
		o := Wlc_NtkObj(p, i)
		if (Wlc_ObjIsCi(o) == 0 && Wlc_ObjFaninNum(o) > 0) || !marked(o) {
			continue
		}
		if o.Type == uint32(WLC_OBJ_CONST) {
			writeDotNode(f, p, i, o, bold != nil)
			continue
		}
		id := Wlc_ObjId(p, o)
		fmt.Fprintf(f, "  Node%d [label = \"%d:%s %d\", shape = %s, color = coral, fillcolor = coral];\n", id, id, Wlc_ObjName(p, id), Wlc_ObjRange(o), boolString(Vec_IntSize(&p.vFfs2) > 0 || Wlc_ObjCiId(o) < Wlc_NtkPiNum(p), "triangle", "box"))
	}
	fmt.Fprintln(f, "}\n\ntitle1 -> title2 [style = invis];")
	prev := int32(-1)
	for i := int32(0); i < Wlc_NtkCoNum(p); i++ {
		o := Wlc_NtkCo(p, i)
		if !marked(o) {
			continue
		}
		po := Wlc_ObjCo2PoFo(p, i)
		id := Wlc_ObjId(p, po)
		fmt.Fprintf(f, "title2 -> NodePo%d [style = invis];\n", id)
		if prev >= 0 {
			fmt.Fprintf(f, "NodePo%d -> NodePo%d [style = invis];\n", prev, id)
		}
		prev = id
	}
	prev = -1
	for i := int32(0); i < Wlc_NtkCiNum(p); i++ {
		o := Wlc_NtkCi(p, i)
		if !marked(o) {
			continue
		}
		id := Wlc_ObjId(p, o)
		if prev >= 0 {
			fmt.Fprintf(f, "Node%d -> Node%d [style = invis];\n", prev, id)
		}
		prev = id
	}
	for i := int32(0); i < Wlc_NtkCoNum(p); i++ {
		o := Wlc_NtkCo(p, i)
		if !marked(o) {
			continue
		}
		po := Wlc_ObjCo2PoFo(p, i)
		fmt.Fprintf(f, "NodePo%d -> Node%d [style = %s];\n", Wlc_ObjId(p, po), Wlc_ObjId(p, o), boolString(o.Signed != 0, "dotted", "solid"))
	}
	for i := int32(1); i < Wlc_NtkObjNumMax(p); i++ {
		o := Wlc_NtkObj(p, i)
		if Wlc_ObjIsCi(o) != 0 || !marked(o) {
			continue
		}
		for k := int32(0); k < Wlc_ObjFaninNum(o); k++ {
			fanin := Wlc_ObjFaninId(o, k)
			if fanin == 0 {
				continue
			}
			style := boolString(Wlc_NtkObj(p, fanin).Signed != 0, "dotted", "solid")
			if o.Type == uint32(WLC_OBJ_MUX) && k == 0 {
				style += ", style = bold"
			}
			fmt.Fprintf(f, "Node%d -> Node%d [style = %s];\n", i, fanin, style)
		}
	}
	fmt.Fprint(f, "}\n")
}

func writeDotNode(f *os.File, p *Wlc_Ntk_t, id int32, o *Wlc_Obj_t, bold bool) {
	if o.Type == uint32(WLC_OBJ_CONST) {
		fmt.Fprintf(f, "  Node%d [label = \"%d:%d'h%s\"", id, id, Wlc_ObjRange(o), dotConstHex(Wlc_ObjConstValue(o), Wlc_ObjRange(o)))
	} else if o.Type == uint32(WLC_OBJ_BUF) || o.Type == uint32(WLC_OBJ_MUX) {
		fmt.Fprintf(f, "  Node%d [label = \"%d: %d\"", id, id, Wlc_ObjRange(o))
	} else if o.Type >= uint32(WLC_OBJ_LOGIC_NOT) && o.Type <= uint32(WLC_OBJ_COMP_MOREEQU) {
		fmt.Fprintf(f, "  Node%d [label = \"%d:%s\"", id, id, Wlc_ObjTypeName(o))
	} else {
		fmt.Fprintf(f, "  Node%d [label = \"%d:%s %d\"", id, id, Wlc_ObjTypeName(o), Wlc_ObjRange(o))
	}
	shape := "ellipse"
	switch {
	case o.Type == uint32(WLC_OBJ_ARI_MULTI):
		shape = "doublecircle"
	case o.Type >= uint32(WLC_OBJ_COMP_EQU) && o.Type <= uint32(WLC_OBJ_COMP_MOREEQU):
		shape = "diamond"
	case o.Type == uint32(WLC_OBJ_BIT_SELECT) || o.Type == uint32(WLC_OBJ_BIT_CONCAT) || o.Type == uint32(WLC_OBJ_FF):
		shape = "box"
	case o.Type == uint32(WLC_OBJ_BUF) || o.Type == uint32(WLC_OBJ_BIT_ZEROPAD) || o.Type == uint32(WLC_OBJ_BIT_SIGNEXT):
		shape = "triangle"
	case o.Type == uint32(WLC_OBJ_MUX):
		shape = "trapezium"
	}
	fmt.Fprintf(f, ", shape = %s", shape)
	if (bold && o.Mark != 0) || (!bold && ((o.Type >= uint32(WLC_OBJ_ARI_ADD) && o.Type <= uint32(WLC_OBJ_ARI_SQUARE)) || o.Type == uint32(WLC_OBJ_BIT_NOT))) {
		fmt.Fprint(f, ", style = filled")
	}
	fmt.Fprintln(f, "];")
}
func dotConstHex(v *int32, nBits int32) string {
	n := (nBits + 3) / 4
	if n > 16 {
		n = 16
	}
	var b strings.Builder
	words := unsafe.Slice(v, 4)
	for i := n - 1; i >= 0; i-- {
		bit := i * 4
		val := uint32(words[bit/32]) >> uint(bit%32) & 15
		if bit%32 > 28 && bit/32+1 < 4 {
			val |= uint32(words[bit/32+1]) << uint(32-bit%32) & 15
		}
		b.WriteByte("0123456789abcdef"[val])
	}
	if nBits > 64 {
		return b.String() + "..."
	}
	return b.String()
}

// Wlc_NtkShow dumps a DOT file and opens it with ABC's configured viewer.
func Wlc_NtkShow(p *Wlc_Ntk_t, bold *Vec_Int_t) {
	name := Extra_FileDesignName(p.pName)
	spec := "unknown"
	if p.pSpec != "" {
		spec = Extra_FileDesignName(p.pSpec)
	}
	if spec == "" || spec == "." {
		spec = "unknown"
	}
	filename := name + "_" + spec + ".dot"
	f, err := os.Create(filename)
	if err != nil {
		fmt.Fprintf(os.Stdout, "Cannot open the intermediate file %q.\n", filename)
		return
	}
	f.Close()
	Wlc_NtkDumpDot(p, filename, bold)
	Abc_ShowFile(filename)
}
