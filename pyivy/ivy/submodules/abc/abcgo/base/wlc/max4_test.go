package wlc

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
	"testing"
)

func TestGenerateCodeMax4(t *testing.T) {
	old, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err = os.Chdir(t.TempDir()); err != nil {
		t.Fatal(err)
	}
	defer os.Chdir(old)
	Wlc_GenerateCodeMax4(4)
	data, err := os.ReadFile(filepath.Join("max4.v"))
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	for _, part := range []string{"input [3:0] a, b, c, d;", "wire [8:0] A = a;", "module comp0", "module comp1", "2'b00"} {
		if !strings.Contains(text, part) {
			t.Errorf("generated Verilog missing %q", part)
		}
	}
}

// Compare the generated bytes with the checked-in C implementation.
func TestGenerateCodeMax4MatchesC(t *testing.T) {
	cc, err := exec.LookPath("cc")
	if err != nil {
		t.Skip("C compiler unavailable")
	}
	_, file, _, _ := runtime.Caller(0)
	source, err := os.ReadFile(filepath.Join(filepath.Dir(file), "../../../src/base/wlc/wlc.c"))
	if err != nil {
		t.Fatal(err)
	}
	text := string(source)
	start := strings.Index(text, "void Wlc_GenerateCodeMax4(")
	if start < 0 {
		t.Fatal("C generator missing")
	}
	brace := strings.IndexByte(text[start:], '{') + start
	depth, end := 0, brace
	for ; end < len(text); end++ {
		if text[end] == '{' {
			depth++
		}
		if text[end] == '}' {
			depth--
			if depth == 0 {
				end++
				break
			}
		}
	}
	dir := t.TempDir()
	cfile := filepath.Join(dir, "oracle.c")
	binary := filepath.Join(dir, "oracle")
	program := "#include <stdio.h>\n#include <stdlib.h>\n" + text[start:end] + "\nint main(int n, char **a) { Wlc_GenerateCodeMax4(atoi(a[1])); return 0; }\n"
	if err = os.WriteFile(cfile, []byte(program), 0600); err != nil {
		t.Fatal(err)
	}
	if output, err := exec.Command(cc, cfile, "-o", binary).CombinedOutput(); err != nil {
		t.Fatalf("compile C: %v: %s", err, output)
	}
	old, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err = os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	defer os.Chdir(old)
	for _, bits := range []int{1, 2, 4, 9} {
		if output, err := exec.Command(binary, strconv.Itoa(bits)).CombinedOutput(); err != nil {
			t.Fatalf("run C: %v: %s", err, output)
		}
		want, err := os.ReadFile("max4.v")
		if err != nil {
			t.Fatal(err)
		}
		Wlc_GenerateCodeMax4(int32(bits))
		got, err := os.ReadFile("max4.v")
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("generated Verilog differs from C for %d bits", bits)
		}
	}
}
