func Abc_NtkPrintSop(s string) string {
	return strings.ReplaceAll(strings.TrimSuffix(s, "\n"), "\n", `\n`)
}
func Abc_NtkCountLogicNodes(nodes []*abc.Object) int32 {
	var count int32
	for _, o := range nodes {
		if o.Kind == abc.ObjectNode && (len(o.Fanins()) > 0 || len(o.Fanouts()) > 0) {
			count++
		}
	}
	return count
}
func dotFunction(o *abc.Object, gateNames bool) (string, error) {
	if abc.Abc_NtkIsStrash(o.Network()) != 0 {
		return "", nil
	}
	switch f := o.Data.(type) {
	case string:
		return strings.TrimSuffix(f, "\n"), nil
	case *mio.Mio_Gate_t:
		if gateNames {
			return mio.Mio_GateReadName(f), nil
		}
		return strings.TrimSuffix(mio.Mio_GateReadSop(f), "\n"), nil
	case *core.DdNode:
		dd, ok := o.Network().FunctionManager.(*core.DdManager)
		if !ok {
			return "", fmt.Errorf("BDD node has no manager")
		}
		var cube []byte
		return strings.TrimSuffix(abc.Abc_ConvertBddToSop(nil, dd, f, f, int32(len(o.Fanins())), 0, &cube, -1), "\n"), nil
	case nil:
		return "", nil
	default:
		return "", fmt.Errorf("unsupported DOT function type %T", f)
	}
}
func dotLevels(n *abc.Network, reverse bool) (map[*abc.Object]int, error) {
	levels := make(map[*abc.Object]int)
	active := map[*abc.Object]bool{}
	var visit func(*abc.Object) (int, error)
	visit = func(o *abc.Object) (int, error) {
		if l, ok := levels[o]; ok {
			return l, nil
		}
		if active[o] {
			return 0, fmt.Errorf("combinational cycle at %s", exportName(o))
		}
		if o.IsCI() || o.Kind == abc.ObjectLatch || o.Kind == abc.ObjectConst1 {
			levels[o] = 0
			return 0, nil
		}
		active[o] = true
		l := 0
		for _, e := range o.Fanins() {
			x, err := visit(e.Object)
			if err != nil {
				return 0, err
			}
			l = max(l, x)
		}
		if o.Kind == abc.ObjectNode {
			l++
		}
		active[o] = false
		levels[o] = l
		return l, nil
	}
	maximum := 0
	for _, o := range n.Objects() {
		l, e := visit(o)
		if e != nil {
			return nil, e
		}
		maximum = max(maximum, l)
	}
	if reverse {
		depth := map[*abc.Object]int{}
		var distance func(*abc.Object) int
		distance = func(o *abc.Object) int {
			if d, ok := depth[o]; ok {
				return d
			}
			d := 0
			for _, out := range o.Fanouts() {
				if out.IsCI() || out.Kind == abc.ObjectLatch {
					continue
				}
				step := 0
				if out.Kind == abc.ObjectNode {
					step = 1
				}
				d = max(d, step+distance(out))
			}
			depth[o] = d
			return d
		}
		for _, o := range n.Objects() {
			if o.Kind == abc.ObjectNode {
				levels[o] = maximum - distance(o)
			}
		}
	}
	for _, o := range n.Objects() {
		if o.IsCO() {
			levels[o] = maximum + 1
		}
	}
	return levels, nil
}

// WriteDOT renders a selected combinational or sequential view without borrowing
// object marks, changing node levels, or converting the source function manager.
func WriteDOT(w stdio.Writer, n *abc.Network, nodes, highlight []*abc.Object, gateNames, reverse, sequential bool) error {
	if n == nil {
		return fmt.Errorf("nil network")
	}
	if nodes == nil {
		nodes = n.Objects()
	}
	limit := 500
	if sequential {
		limit = 300
	}
	if len(nodes) == 0 || len(nodes) > limit {
		return fmt.Errorf("DOT needs 1..%d selected objects", limit)
	}
	selected := map[*abc.Object]bool{}
	shown := map[*abc.Object]bool{}
	for _, o := range nodes {
		if o == nil || o.Network() != n {
			return fmt.Errorf("DOT selection contains foreign object")
		}
		selected[o] = true
	}
	for _, o := range highlight {
		if o == nil || o.Network() != n {
			return fmt.Errorf("DOT highlight contains foreign object")
		}
		shown[o] = true
	}
	levels, e := dotLevels(n, reverse)
	if e != nil {
		return e
	}
	low, high := int(^uint(0)>>1), 0
	for _, o := range nodes {
		if sequential && (o.Kind == abc.ObjectBI || o.Kind == abc.ObjectBO) {
			continue
		}
		low = min(low, levels[o])
		high = max(high, levels[o])
	}
	if low > high {
		low = 0
	}
	var b strings.Builder
	b.WriteString("# Network structure generated by ABC\n\ndigraph network {\nsize = \"7.5,10\";\ncenter = true;\nedge [dir = back];\n\n{\n  node [shape = plaintext];\n  edge [style = invis];\n  LevelTitle1 [label=\"\"];\n  LevelTitle2 [label=\"\"];\n")
	for level := high; level >= low; level-- {
		fmt.Fprintf(&b, "  Level%d [label = \"\"];\n", level)
	}
	b.WriteString("  LevelTitle1 -> LevelTitle2")
	for level := high; level >= low; level-- {
		fmt.Fprintf(&b, " -> Level%d", level)
	}
	b.WriteString(";\n}\n{ rank = same; LevelTitle1;\n")
	fmt.Fprintf(&b, "title1 [shape=plaintext, fontsize=20, fontname=\"Times-Roman\", label=%s];\n}\n", exportQuoted("Network structure visualized by ABC\nBenchmark \""+n.Name+"\"."))
	fmt.Fprintf(&b, "{ rank = same; LevelTitle2; title2 [shape=plaintext, label=%s]; }\n", exportQuoted(fmt.Sprintf("The set contains %d logic nodes and %d latches.", Abc_NtkCountLogicNodes(nodes), len(n.ObjectsOfKind(abc.ObjectLatch)))))
	for level := high; level >= low; level-- {
		fmt.Fprintf(&b, "{ rank = same; Level%d;\n", level)
		for _, o := range nodes {
			if levels[o] != level {
				continue
			}
			if o.Kind == abc.ObjectLatch && !sequential || sequential && (o.Kind == abc.ObjectBI || o.Kind == abc.ObjectBO) {
				continue
			}
			label, shape, color := exportName(o), "ellipse", false
			switch o.Kind {
			case abc.ObjectPI:
				shape, color = "triangle", true
			case abc.ObjectPO:
				shape, color = "invtriangle", true
			case abc.ObjectBI:
				shape, color = "box", true
				if len(o.Fanouts()) > 0 {
					label = exportName(o.Fanouts()[0]) + "_in"
				}
			case abc.ObjectBO:
				shape, color = "box", true
				if len(o.Fanins()) > 0 {
					label = exportName(o.Fanins()[0].Object)
				}
			case abc.ObjectLatch:
				shape, color = "box", true
			case abc.ObjectConst1:
				if len(o.Fanouts()) == 0 {
					continue
				}
				label, color = "Const1", true
			case abc.ObjectNode:
				if len(o.Fanins()) == 0 {
					if len(o.Fanouts()) == 0 {
						continue
					}
					value := "0"
					if text, ok := o.Data.(string); ok && abc.Abc_SopIsConst1(text) != 0 {
						value = "1"
					}
					label, color = "Const"+value, true
				} else {
					function, err := dotFunction(o, gateNames)
					if err != nil {
						return err
					}
					label = fmt.Sprintf("%d\n%s", o.ID, function)
				}
			}
			fmt.Fprintf(&b, "Node%d [label = %s, shape = %s", o.ID, exportQuoted(label), shape)
			if shown[o] {
				b.WriteString(", style = filled")
			}
			if color {
				b.WriteString(", color = coral, fillcolor = coral")
			}
			b.WriteString("];\n")
		}
		b.WriteString("}\n")
	}
	b.WriteString("title1 -> title2 [style = invis];\n")
	previous := -1
	for _, o := range nodes {
		if o.Kind != abc.ObjectPO {
			continue
		}
		fmt.Fprintf(&b, "title2 -> Node%d [style = invis];\n", o.ID)
		if previous >= 0 {
			fmt.Fprintf(&b, "Node%d -> Node%d [style = invis];\n", previous, o.ID)
		}
		previous = o.ID
	}
	for _, o := range nodes {
		if !sequential && o.Kind == abc.ObjectLatch || sequential && (o.Kind == abc.ObjectBI || o.Kind == abc.ObjectBO) {
			continue
		}
		for _, edge := range o.Fanins() {
			fanin, complement := edge.Object, edge.Complement
			if sequential {
				for i := 0; i < 2 && (fanin.Kind == abc.ObjectBI || fanin.Kind == abc.ObjectBO); i++ {
					inputs := fanin.Fanins()
					if len(inputs) != 1 {
						return fmt.Errorf("sequential terminal %s lacks driver", exportName(fanin))
					}
					complement = complement != inputs[0].Complement
					fanin = inputs[0].Object
				}
			} else if fanin.Kind == abc.ObjectLatch {
				continue
			}
			if !selected[fanin] {
				continue
			}
			style := "solid"
			if complement {
				style = "dotted"
			}
			fmt.Fprintf(&b, "Node%d -> Node%d [style = %s];\n", o.ID, fanin.ID, style)
		}
	}
	b.WriteString("}\n\n")
	_, err := stdio.WriteString(w, b.String())
	return err
}
func Io_WriteDot(n *abc.Network, path string) error { return Io_WriteDotNtk(n, nil, nil, path, 0, 0) }
func Io_WriteDotNtk(n *abc.Network, nodes, highlight []*abc.Object, path string, gateNames, reverse int32) error {
	return exportFile(path, func(w stdio.Writer) error {
		return WriteDOT(w, n, nodes, highlight, gateNames != 0, reverse != 0, false)
	})
}
func Io_WriteDotSeq(n *abc.Network, nodes, highlight []*abc.Object, path string, gateNames, reverse int32) error {
	return exportFile(path, func(w stdio.Writer) error {
		return WriteDOT(w, n, nodes, highlight, gateNames != 0, reverse != 0, true)
	})
}
func init() { RegisterFormat(IO_FILE_DOT, nil, Io_WriteDot) }
