package cov

import (
	"fmt"
	"os"
	"strings"
	"time"
)

func Min_CubeCreate(output *Vec_Str_t, cube *Min_Cube_t, kind byte) {
	if output == nil || Min_CubeCheck(cube) == 0 {
		panic("cov: invalid cube serialization arguments")
	}
	for variable := int32(0); variable < int32(cube.nVars); variable++ {
		switch Min_CubeGetVar(cube, variable) {
		case 1:
			Vec_StrPush(output, '0')
		case 2:
			Vec_StrPush(output, '1')
		case 3:
			Vec_StrPush(output, '-')
		default:
			panic("cov: contradictory cube")
		}
	}
	Vec_StrPush(output, ' ')
	Vec_StrPush(output, kind)
	Vec_StrPush(output, '\n')
}

func Min_CoverCreate(output *Vec_Str_t, cover *Min_Cube_t, kind byte) {
	if output == nil {
		panic("cov: nil cover output")
	}
	Vec_StrClear(output)
	for cube := cover; cube != nil; cube = cube.pNext {
		Min_CubeCreate(output, cube, kind)
	}
	Vec_StrPush(output, 0)
}

func Min_CubeWrite(file *os.File, cube *Min_Cube_t) {
	if file == nil || Min_CubeCheck(cube) == 0 {
		panic("cov: invalid cube writer arguments")
	}
	for variable := int32(0); variable < int32(cube.nVars); variable++ {
		switch Min_CubeGetVar(cube, variable) {
		case 1:
			_, _ = fmt.Fprint(file, "0")
		case 2:
			_, _ = fmt.Fprint(file, "1")
		case 3:
			_, _ = fmt.Fprint(file, "-")
		}
	}
	_, _ = fmt.Fprintln(file, " 1")
}

func Min_CoverWrite(file *os.File, cover *Min_Cube_t) {
	if file == nil {
		return
	}
	for cube := cover; cube != nil; cube = cube.pNext {
		Min_CubeWrite(file, cube)
	}
}

func Min_CoverWriteStore(file *os.File, p *Min_Man_t) {
	if file == nil || p == nil {
		return
	}
	for literals, head := range p.ppStore {
		for cube := head; cube != nil; cube = cube.pNext {
			if cube == p.pBubble {
				_, _ = fmt.Fprintf(file, "%2d : Bubble\n", literals)
				continue
			}
			_, _ = fmt.Fprintf(file, "%2d : ", literals)
			Min_CubeWrite(file, cube)
		}
	}
}

func Min_CoverWriteFile(cover *Min_Cube_t, name string, esop int32) {
	extension, label := "pla", "SOP"
	if esop != 0 {
		extension, label = "esop", "ESOP"
	}
	path := strings.NewReplacer("<", "_", ">", "_").Replace(name + "." + extension)
	file, err := os.Create(path)
	if err != nil {
		return
	}
	defer file.Close()
	variables := int32(0)
	if cover != nil {
		variables = int32(cover.nVars)
	}
	_, _ = fmt.Fprintf(file, "# %s cover for output %s generated by ABC on %s\n", label, name, time.Now().Format(time.RFC3339))
	_, _ = fmt.Fprintf(file, ".i %d\n.o 1\n.p %d\n", variables, Min_CoverCountCubes(cover))
	if esop != 0 {
		_, _ = fmt.Fprintln(file, ".type esop")
	}
	Min_CoverWrite(file, cover)
	_, _ = fmt.Fprintln(file, ".e")
}

func Min_CoverCheck(p *Min_Man_t) {
	if p == nil || len(p.ppStore) < int(p.nVars)+1 {
		panic("cov: invalid cover manager")
	}
	count := int32(0)
	for literals, head := range p.ppStore {
		for cube := head; cube != nil; cube = cube.pNext {
			if int(cube.nLits) != literals || Min_CubeCheck(cube) == 0 || int32(cube.nLits) != Min_CubeCountLits(cube) {
				panic("cov: invalid cube in cover bucket")
			}
			count++
		}
	}
	if count != p.nCubes {
		panic("cov: cube count mismatch")
	}
}

func Min_CubeCheck(cube *Min_Cube_t) int32 {
	if cube == nil || len(cube.uData) < int(cube.nWords) {
		return 0
	}
	for variable := int32(0); variable < int32(cube.nVars); variable++ {
		if Min_CubeGetVar(cube, variable) == 0 {
			return 0
		}
	}
	return 1
}

func Min_CoverCollect(p *Min_Man_t, support int32) *Min_Cube_t {
	if p == nil || support < 0 || support >= int32(len(p.ppStore)) {
		return nil
	}
	var head, tail *Min_Cube_t
	for literals := int32(0); literals <= support; literals++ {
		for cube := p.ppStore[literals]; cube != nil; {
			next := cube.pNext
			if int32(cube.nLits) != literals {
				panic("cov: cube is stored in the wrong literal bucket")
			}
			if tail == nil {
				head = cube
			} else {
				tail.pNext = cube
			}
			tail = cube
			cube = next
		}
	}
	if tail != nil {
		tail.pNext = nil
	}
	return head
}

func Min_CoverExpand(p *Min_Man_t, cover *Min_Cube_t) {
	if p == nil {
		return
	}
	Min_ManClean(p, p.nVars)
	for cube := cover; cube != nil; {
		next := cube.pNext
		cube.pNext = p.ppStore[cube.nLits]
		p.ppStore[cube.nLits] = cube
		p.nCubes++
		cube = next
	}
}

func Min_CoverSuppVarNum(p *Min_Man_t, cover *Min_Cube_t) int32 {
	if p == nil || cover == nil {
		return 0
	}
	fixed := make([]bool, p.nVars)
	for variable := range fixed {
		fixed[variable] = true
	}
	for cube := cover; cube != nil; cube = cube.pNext {
		for variable := range fixed {
			if Min_CubeGetVar(cube, int32(variable)) == 3 {
				fixed[variable] = false
			}
		}
	}
	var count int32
	for _, hasLiteral := range fixed {
		if hasLiteral {
			count++
		}
	}
	return count
}
