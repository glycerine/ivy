// Mpm_ManGetTruthWithCnf returns class truth tables in source order whose
// precomputed CNF clause count does not exceed limit.
func Mpm_ManGetTruthWithCnf(limit int32) *vec.Vec_Wrd_t {
	result := vec.Vec_WrdAlloc(1000)
	for _, class := range s_DsdClass6 {
		if class.nClauses <= limit {
			vec.Vec_WrdPush(result, uint64(class.uTruth))
		}
	}
	return result
}
