const rtlReset = "rst"

// GenerateRTLIL compiles an Ivy hardware description without erasing its
// hierarchy, then emits a Yosys RTLIL netlist.
func GenerateRTLIL(source string) (string, error) {
	mod := New()
	mod.Cfg.IsolateCfg.InterpretAllSorts = true
	mod.Cfg.IsolateCfg.ConeOfInfluence = false
	mod.Cfg.IsolateCfg.CreateImports = true
	mod.Cfg.IsolateCfg.EnforceAxioms = true
	mod.Cfg.IsolateCfg.IsolateMode = "compile"
	mod.Cfg.IsolateCfg.AssumeInvariants = false
	mod.Cfg.IsolateCfg.KeepDestructors = true
	SetVerifying(mod, false)
	if err := SourceFile(source, mod, mod.Sig, map[string]interface{}{"create_isolate": false}); err != nil {
		return "", err
	}
	leaveTheory := mod.TheoryContext()
	defer leaveTheory()
	trans, err := newRTLTranslator(mod)
	if err != nil {
		return "", err
	}
	var result strings.Builder
	fmt.Fprintf(&result, "# Generated by ivy_to_rtl from %s.ivy\n\nautoidx 1\n\n", mod.Name)
	if err := trans.emitObject(&result, trans.top); err != nil {
		return "", err
	}
	return result.String(), nil
}

// WriteRTLIL compiles source and writes the generated RTLIL to destination.
func WriteRTLIL(source, destination string) error {
	netlist, err := GenerateRTLIL(source)
	if err != nil {
		return err
	}
	return os.WriteFile(destination, []byte(netlist), 0o644)
}

type rtlUpdate struct {
	defs    map[string]*IvyDefinition
	clauses *Clauses
}

type rtlDefinition struct {
	def   *IvyDefinition
	owner string
}

type rtlTranslator struct {
	mod        *Module
	top        string
	clocks     []string
	defNames   map[string]bool
	defs       *InsMap[string, rtlDefinition]
	wires      *InsMap[string, *Const]
	updates    map[string]*InsMap[string, rtlUpdate]
	state      map[string]*InsMap[string, *Const]
	scalars    map[string]*Const
	references map[string]map[string]bool
	exported   map[string]bool
	clocked    map[string]bool
}

func newRTLTranslator(mod *Module) (*rtlTranslator, error) {
	t := &rtlTranslator{
		mod: mod, defNames: make(map[string]bool), defs: NewInsMap[string, rtlDefinition](),
		wires: NewInsMap[string, *Const](), updates: make(map[string]*InsMap[string, rtlUpdate]),
		state: make(map[string]*InsMap[string, *Const]), scalars: make(map[string]*Const),
		references: make(map[string]map[string]bool), exported: make(map[string]bool),
		clocked: make(map[string]bool),
	}
	for _, labeled := range mod.Definitions {
		def, ok := labeled.Formula.(*IvyDefinition)
		if !ok {
			continue
		}
		name := ExprName(def.Defines())
		t.defNames[name] = true
		label := lfLabelName(labeled)
		if !t.hasAttribute(label, "spec") {
			t.defs.Set(name, rtlDefinition{def: def, owner: rtlParent(label)})
		}
	}
	for _, wire := range mod.Wires.All() {
		t.wires.Set(wire.Name, wire)
	}
	if err := t.computeUpdates(); err != nil {
		return nil, err
	}
	t.pickTop()
	t.markClocked(t.top)
	for object := range mod.Hierarchy.All() {
		for name := range t.refs(object) {
			register := t.scalars[name]
			if register != nil && !rtlDescendant(object, t.owner(name)) {
				t.exported[name] = true
			}
		}
	}
	return t, nil
}

func rtlParent(name string) string {
	if index := strings.LastIndexByte(name, '.'); index >= 0 {
		return name[:index]
	}
	return "this"
}

func rtlCompose(parent, name string) string {
	if parent == "this" {
		return name
	}
	return parent + "." + name
}

func rtlLocal(object, name string) string {
	return strings.TrimPrefix(name, object+".")
}

func rtlDescendant(object, parent string) bool {
	return parent == "this" || object == parent || strings.HasPrefix(object, parent+".")
}

func (t *rtlTranslator) hasAttribute(name, attribute string) bool {
	for name != "this" && name != "" {
		if _, ok := t.mod.Attributes.Get2(name + "." + attribute); ok {
			return true
		}
		name = rtlParent(name)
	}
	return false
}

func (t *rtlTranslator) onlySpec(object string) bool {
	children := t.mod.Hierarchy.Get(object)
	if children == nil || children.Len() == 0 {
		return t.hasAttribute(object, "spec")
	}
	for name := range children.All() {
		name := rtlCompose(object, name)
		if _, child := t.mod.Hierarchy.Get2(name); child {
			if !t.onlySpec(name) {
				return false
			}
		} else if !t.hasAttribute(name, "spec") {
			return false
		}
	}
	return true
}

func (t *rtlTranslator) inDesign(object string) bool {
	_, isSort := t.mod.Sig.Sorts.Get2(object)
	return object != "this" && !isSort && !t.hasAttribute(object, "spec") &&
		!t.hasAttribute(object, "global") && !t.onlySpec(object)
}

func (t *rtlTranslator) children(object string) []string {
	var children []string
	if members := t.mod.Hierarchy.Get(object); members != nil {
		for name := range members.All() {
			child := rtlCompose(object, name)
			if _, ok := t.mod.Hierarchy.Get2(child); ok && t.inDesign(child) {
				children = append(children, child)
			}
		}
	}
	sort.Strings(children)
	return children
}

func (t *rtlTranslator) owner(name string) string {
	for candidate := name; candidate != "this"; candidate = rtlParent(candidate) {
		if _, ok := t.mod.Hierarchy.Get2(candidate); ok {
			return candidate
		}
	}
	return "this"
}

func (t *rtlTranslator) pickTop() {
	owners := make(map[string]bool)
	for _, ports := range [][]*Const{t.mod.InputWires, t.mod.OutputWires} {
		for _, port := range ports {
			owners[t.owner(port.Name)] = true
		}
	}
	if len(owners) == 1 {
		for owner := range owners {
			t.top = owner
		}
		return
	}
	t.top = "this"
	if roots := t.children("this"); len(roots) == 1 {
		t.top = roots[0]
	}
}

func (t *rtlTranslator) markClocked(object string) bool {
	clocked := t.state[object] != nil
	for _, child := range t.children(object) {
		clocked = t.markClocked(child) || clocked
	}
	t.clocked[object] = clocked
	return clocked
}

func (t *rtlTranslator) computeUpdates() error {
	clocks := make(map[string]bool)
	for _, export := range t.mod.Exports {
		name := CanonAct(export.Exported())
		if name != "init" {
			clocks[name] = true
		}
	}
	t.clocks = sortedRTLKeys(clocks)
	mixees := append(append([]string(nil), t.clocks...), "init")
	for _, mixee := range mixees {
		mixers := NewInsMap[string, []Expr]()
		for _, mixin := range t.mod.Mixins.Get(mixee) {
			name := mixin.Mixer()
			if t.hasAttribute(name, "spec") {
				continue
			}
			if !mixin.IsAfter() {
				return fmt.Errorf("%s mixes into exported action %s without an after mixin", name, mixee)
			}
			action, ok := t.mod.FindAction(name)
			if !ok {
				return fmt.Errorf("RTL mixer %s has no action", name)
			}
			owner := t.owner(name)
			mixers.Set(owner, append(mixers.Get(owner), action))
		}
		for object, actions := range mixers.All() {
			update := computeUpdate(t.mod, NewSequence(actions...))
			if update == nil || update.TR == nil {
				return fmt.Errorf("could not compute RTL update for %s on %s", object, mixee)
			}
			rtl := rtlUpdate{defs: make(map[string]*IvyDefinition), clauses: update.TR}
			for _, symbol := range update.Modified {
				if t.wires.Get(symbol.Name) != nil || t.defNames[symbol.Name] {
					continue
				}
				if owner := t.owner(symbol.Name); owner != object {
					return fmt.Errorf("interference: %s updates %s owned by %s", object, symbol.Name, owner)
				}
				if t.state[object] == nil {
					t.state[object] = NewInsMap[string, *Const]()
				}
				t.state[object].Set(symbol.Name, symbol)
				if !IsFunctionSort(symbol.CSort) {
					t.scalars[symbol.Name] = symbol
				}
			}
			for _, def := range update.TR.Defs {
				rtl.defs[ExprName(def.Defines())] = def
			}
			if t.updates[object] == nil {
				t.updates[object] = NewInsMap[string, rtlUpdate]()
			}
			t.updates[object].Set(mixee, rtl)
		}
	}
	return nil
}

func (t *rtlTranslator) refs(object string) map[string]bool {
	if names := t.references[object]; names != nil {
		return names
	}
	names := make(map[string]bool)
	var collect func(Expr)
	collect = func(expr Expr) {
		for _, symbol := range UsedSymbolsAST(expr).All() {
			name := ExprName(symbol)
			if names[name] {
				continue
			}
			names[name] = true
			if def, ok := t.defs.Get2(name); ok && IsFunctionSort(def.def.Defines().NodeSort()) {
				collect(def.def.Rhs)
			}
		}
	}
	for _, def := range t.defs.All() {
		if def.owner == object {
			collect(def.def.Rhs)
		}
	}
	if updates := t.updates[object]; updates != nil {
		for _, update := range updates.All() {
			for _, def := range update.clauses.Defs {
				collect(def.Rhs)
			}
		}
	}
	t.references[object] = names
	return names
}

func (t *rtlTranslator) foreignInputs(object string) []*Const {
	var result []*Const
	for _, name := range sortedRTLKeys(t.refs(object)) {
		wire := t.wires.Get(name)
		if wire == nil {
			wire = t.scalars[name]
		}
		if wire != nil && !IsFunctionSort(wire.CSort) && !rtlDescendant(t.owner(name), object) {
			result = append(result, wire)
		}
	}
	return result
}

func (t *rtlTranslator) classify(object string) (inputs, outputs, internal []*Const) {
	var ports = make(map[string]string)
	for _, input := range t.mod.InputWires {
		ports[input.Name] = "input"
	}
	for _, output := range t.mod.OutputWires {
		ports[output.Name] = "output"
	}
	for _, wire := range t.wires.All() {
		if t.owner(wire.Name) != object || IsFunctionSort(wire.CSort) {
			continue
		}
		direction := ports[wire.Name]
		if object != t.top {
			direction = "input"
			if def, ok := t.defs.Get2(wire.Name); ok && def.owner == object {
				direction = ""
				if t.refs(rtlParent(object))[wire.Name] {
					direction = "output"
				}
			}
			if direction == "" {
				for other := range t.mod.Hierarchy.All() {
					if !rtlDescendant(other, object) && t.refs(other)[wire.Name] {
						direction = "output"
						break
					}
				}
			}
		}
		switch direction {
		case "input":
			inputs = append(inputs, wire)
		case "output":
			outputs = append(outputs, wire)
		default:
			internal = append(internal, wire)
		}
	}
	return inputs, outputs, internal
}

func sortedRTLKeys[V any](entries map[string]V) []string {
	names := make([]string, 0, len(entries))
	for name := range entries {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

type rtlNet struct {
	name  string
	width int
}

func rtlPublic(name string) string { return "\\" + name }

func rtlBits(value *big.Int, width int) rtlNet {
	limit := new(big.Int).Lsh(big.NewInt(1), uint(width))
	bits := new(big.Int).Mod(value, limit).Text(2)
	return rtlNet{name: strconv.Itoa(width) + "'" + strings.Repeat("0", width-len(bits)) + bits, width: width}
}

func rtlInt(value int64, width int) rtlNet { return rtlBits(big.NewInt(value), width) }

type rtlModule struct {
	name      string
	wires     map[string]rtlNet
	header    strings.Builder
	body      strings.Builder
	ports     int
	automatic int
	memories  []*rtlMemory
}

func (m *rtlModule) wire(name string, width int, direction string) rtlNet {
	if net, ok := m.wires[name]; ok {
		return net
	}
	net := rtlNet{name: name, width: width}
	m.wires[name] = net
	fmt.Fprint(&m.header, "  wire")
	if width != 1 {
		fmt.Fprintf(&m.header, " width %d", width)
	}
	if direction != "" {
		m.ports++
		fmt.Fprintf(&m.header, " %s %d", direction, m.ports)
	}
	fmt.Fprintf(&m.header, " %s\n", name)
	return net
}

func (m *rtlModule) fresh(prefix string) string {
	m.automatic++
	return fmt.Sprintf("%s$%d", prefix, m.automatic)
}

func (m *rtlModule) net(width int) rtlNet { return m.wire(m.fresh(""), width, "") }

func (m *rtlModule) connect(lhs, rhs rtlNet) {
	fmt.Fprintf(&m.body, "  connect %s %s\n", lhs.name, rhs.name)
}

type rtlParam struct {
	name  string
	value any
}

type rtlPort struct {
	name string
	net  rtlNet
}

func (m *rtlModule) cell(kind, name string, params []rtlParam, ports ...rtlPort) {
	fmt.Fprintf(&m.body, "  cell %s %s\n", kind, name)
	for _, param := range params {
		fmt.Fprintf(&m.body, "    parameter %s %v\n", rtlPublic(param.name), param.value)
	}
	for _, port := range ports {
		fmt.Fprintf(&m.body, "    connect %s %s\n", rtlPublic(port.name), port.net.name)
	}
	fmt.Fprintln(&m.body, "  end")
}

func (m *rtlModule) write(out *strings.Builder) {
	fmt.Fprintf(out, "module %s\n%s%send\n\n", rtlPublic(m.name), m.header.String(), m.body.String())
}

func (t *rtlTranslator) width(s Sort) (int, error) {
	if SortEqual(s, Boolean) {
		return 1, nil
	}
	interpretation, _ := SortInterp(t.mod.Sig, s).(string)
	base, params, ok := parseIntParamsNoTrace(interpretation)
	if ok && base == "bv" && len(params) == 1 && params[0] > 0 {
		return params[0], nil
	}
	if interpretation == "bool" {
		return 1, nil
	}
	return 0, fmt.Errorf("unsupported type in hardware description: %s", s)
}
