package ivy2golang

import (
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/glycerine/ivy/goivy"
)

type Config struct {
	Target          string
	RequestedTarget string
	ClassName       string
	MainName        string
	OutDir          string
	Compiler        string
	TestIters       string
	TestRuns        string
	Build           bool
	EmitMain        bool
	Trace           bool
	Stdafx          bool
	HostOS          string
}

type Output struct {
	Source          string
	BaseName        string
	ClassName       string
	Target          string
	EffectiveTarget string
	EmitMain        bool
	Config          Config
	ExtraFiles      map[string]string
	LibSpecs        []string
	Warnings        []string
}

type Generator struct {
	Mod       *goivy.Module
	Config    Config
	BaseName  string
	ClassName string

	tempID     int
	errs       []error
	warnings   []string
	warningSet map[string]bool

	locals         []map[string]bool
	currentReturns []*goivy.Const
}

func Generate(mod *goivy.Module, cfg Config) (*Output, error) {
	if mod == nil {
		return nil, fmt.Errorf("ivy2golang: nil module")
	}
	if cfg.Target == "" && cfg.RequestedTarget == "" {
		cfg.Target = "impl"
	}
	var err error
	cfg, _, err = normalizeConfig(cfg)
	if err != nil {
		return nil, err
	}
	base := moduleBaseName(mod)
	className := cfg.ClassName
	if className == "" {
		className = goName(base)
	}
	applySessionParameters(mod, cfg)
	prepareModuleForGo(mod, cfg)
	g := &Generator{
		Mod:       mod,
		Config:    cfg,
		BaseName:  base,
		ClassName: className,
	}
	src, err := g.generate()
	if err != nil {
		return nil, err
	}
	return &Output{
		Source:          src,
		BaseName:        base,
		ClassName:       className,
		Target:          cfg.RequestedTarget,
		EffectiveTarget: cfg.Target,
		EmitMain:        cfg.EmitMain,
		Config:          cfg,
		LibSpecs:        moduleLibSpecs(mod),
		Warnings:        append([]string(nil), g.warnings...),
	}, nil
}

func (g *Generator) generate() (string, error) {
	var w goWriter
	w.line("// Code generated by ivy2golang; DO NOT EDIT.")
	w.line("package main")
	w.blank()
	g.emitImports(&w)
	g.emitSortDecls(&w)
	g.emitRuntime(&w)
	g.emitStruct(&w)
	g.emitConstructor(&w)
	g.emitInitialState(&w)
	g.emitInit(&w)
	g.emitMethods(&w)
	g.emitTick(&w)
	if g.Config.EmitMain {
		if g.Config.Target == "test" {
			g.emitTestMain(&w)
		} else {
			g.emitSmokeMain(&w)
		}
	}
	return w.String(), errors.Join(g.errs...)
}

func (g *Generator) emitImports(w *goWriter) {
	w.line("import (")
	w.indent++
	for _, imp := range []string{"fmt", "io", "math/rand", "os", "strconv", "strings"} {
		w.linef("%q", imp)
	}
	w.indent--
	w.line(")")
	w.blank()
}

func (g *Generator) emitSortDecls(w *goWriter) {
	if g.Mod == nil || g.Mod.Sig == nil {
		return
	}
	for _, name := range g.Mod.SortOrder {
		s, ok := g.Mod.Sig.Sorts.Get2(name)
		if !ok {
			continue
		}
		st, ok := s.(*goivy.LogicEnumeratedSort)
		if !ok || st.Name == "" || isNumericEnum(st) {
			continue
		}
		if !g.sortNeededForGoDecl(st.Name) {
			continue
		}
		typeName := goName(st.Name)
		w.linef("type %s int", typeName)
		w.blank()
		w.line("const (")
		w.indent++
		for i, sym := range st.Extension {
			if i == 0 {
				w.linef("%s %s = iota", goName(sym), typeName)
			} else {
				w.line(goName(sym))
			}
		}
		w.indent--
		w.line(")")
		w.blank()
		w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
		w.line("switch v {")
		w.indent++
		for _, sym := range st.Extension {
			w.linef("case %s:", goName(sym))
			w.indent++
			w.linef("return %q", memName(sym))
			w.indent--
		}
		w.indent--
		w.line("}")
		w.line(`return fmt.Sprintf("%d", int(v))`)
		w.close("")
		w.blank()
	}
}

func (g *Generator) sortNeededForGoDecl(name string) bool {
	for _, sym := range g.stateSymbols() {
		if g.sortDependenciesReferenceName(sym.Sort, name) {
			return true
		}
	}
	if g.Mod.Actions != nil {
		for _, act := range g.Mod.Actions.All() {
			for _, p := range act.GetFormalParams() {
				if g.sortDependenciesReferenceName(p.CSort, name) {
					return true
				}
			}
			for _, r := range act.GetFormalReturns() {
				if g.sortDependenciesReferenceName(r.CSort, name) {
					return true
				}
			}
		}
	}
	return false
}

func (g *Generator) emitRuntime(w *goWriter) {
	w.line("var __ivy_out io.Writer = os.Stdout")
	w.line("var __ivy_rng = rand.New(rand.NewSource(1))")
	w.blank()
	w.open("func parseIvyTestArgs(args []string) (map[string]string, []string) {")
	w.line("opts := map[string]string{}")
	w.line("var rest []string")
	w.open("for _, arg := range args {")
	w.line(`if key, value, ok := strings.Cut(arg, "="); ok {`)
	w.indent++
	w.line("opts[key] = value")
	w.indent--
	w.line("} else {")
	w.indent++
	w.line("rest = append(rest, arg)")
	w.indent--
	w.line("}")
	w.close("")
	w.line("return opts, rest")
	w.close("")
	w.blank()
	w.open("func ivyAtoiDefault(text string, def int) int {")
	w.open(`if text == "" {`)
	w.line("return def")
	w.close("")
	w.open("if n, err := strconv.Atoi(text); err == nil {")
	w.line("return n")
	w.close("")
	w.line("return def")
	w.close("")
	w.blank()
	w.open("func ivySetSeed(seed int64) {")
	w.line("__ivy_rng = rand.New(rand.NewSource(seed))")
	w.close("")
	w.blank()
	w.open("func ivyAssert(truth bool, msg string) {")
	w.open("if !truth {")
	w.line(`fmt.Fprintf(os.Stderr, "%s: error: assertion failed\n", msg)`)
	w.line("os.Exit(1)")
	w.close("")
	w.close("")
	w.blank()
	w.open("func ivyAssume(truth bool, msg string) bool {")
	w.open("if !truth {")
	w.line("return false")
	w.close("")
	w.line("return true")
	w.close("")
	w.blank()
	w.open("func ivyCheckProgress(counter, max int) {")
	w.line("_ = counter")
	w.line("_ = max")
	w.close("")
	w.blank()
	w.open("func ivyTernary[T any](cond bool, thenVal, elseVal T) T {")
	w.open("if cond {")
	w.line("return thenVal")
	w.close("")
	w.line("return elseVal")
	w.close("")
	w.blank()
}

func (g *Generator) emitStruct(w *goWriter) {
	w.open(fmt.Sprintf("type %s struct {", g.ClassName))
	w.line("__argv []string")
	for _, sym := range g.stateSymbols() {
		w.line(g.goStorageDecl(sym.Name, sym.Sort))
	}
	g.emitProgressCounterDecls(w)
	w.close("")
	w.blank()
}

func (g *Generator) emitConstructor(w *goWriter) {
	w.open(fmt.Sprintf("func new%s() *%s {", exportedishName(g.ClassName), g.ClassName))
	w.linef("ivy := &%s{}", g.ClassName)
	w.line("ivy.__initStorage()")
	w.line("ivy.__initState()")
	w.line("ivy.__init()")
	w.line("return ivy")
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (ivy *%s) __initStorage() {", g.ClassName))
	for _, sym := range g.stateSymbols() {
		if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
			st := g.goFunctionStorageFor(fs.Domain(), fs.Range())
			w.linef("ivy.%s = make(%s)", goName(sym.Name), st.Type)
		}
	}
	g.emitProgressStorageInitializers(w)
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (ivy *%s) ___ivy_choose(rng int, name string, id int) int {", g.ClassName))
	w.line("_ = name")
	w.line("_ = id")
	w.open("if rng <= 0 {")
	w.line("return 0")
	w.close("")
	w.line("return __ivy_rng.Intn(rng)")
	w.close("")
	w.blank()
}

func (g *Generator) emitInitialState(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __initState() {", g.ClassName))
	for _, sym := range g.stateSymbols() {
		if g.isParamName(sym.Name) {
			continue
		}
		g.emitRandomizeSymbol(w, sym, "init")
	}
	w.close("")
	w.blank()
}

func (g *Generator) emitRandomizeSymbol(w *goWriter, sym stateSymbol, label string) {
	if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
		g.emitDomainLoops(w, fs.Domain(), func(args []string) {
			expr, err := g.goRandomValueExpr(fs.Range(), label+"."+sym.Name, int64(len(args)))
			if err != nil {
				g.unsupported(w, "%s", err.Error())
				return
			}
			w.linef("%s = %s", g.goStorageAccess(sym.Name, sym.Sort, args, "ivy"), expr)
		})
		return
	}
	expr, err := g.goRandomValueExpr(sym.Sort, label+"."+sym.Name, 0)
	if err != nil {
		g.unsupported(w, "%s", err.Error())
		return
	}
	w.linef("ivy.%s = %s", goName(sym.Name), expr)
}

func (g *Generator) emitDomainLoops(w *goWriter, domain []goivy.Sort, body func(args []string)) {
	var args []string
	var recur func(int)
	recur = func(i int) {
		if i == len(domain) {
			body(args)
			return
		}
		name := fmt.Sprintf("__i%d", i)
		vals, ok := g.finiteValueExprs(domain[i])
		if !ok {
			g.unsupported(w, "cannot enumerate function domain sort %s", sortName(domain[i]))
			return
		}
		w.open(fmt.Sprintf("for _, %s := range []%s{%s} {", name, g.goScalarType(domain[i]), strings.Join(vals, ", ")))
		args = append(args, name)
		recur(i + 1)
		args = args[:len(args)-1]
		w.close("")
	}
	recur(0)
}

func (g *Generator) emitInit(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __init() {", g.ClassName))
	for _, act := range g.Mod.InitialActions {
		g.emitAction(w, act)
	}
	for _, na := range g.Mod.Initializers {
		if act, ok := na.Action.(goivy.Action); ok {
			g.emitAction(w, act)
		}
	}
	w.close("")
	w.blank()
}

func (g *Generator) emitMethods(w *goWriter) {
	if g.Mod.Actions == nil {
		return
	}
	initActions := g.initialMixinActionNames()
	for name, act := range g.Mod.Actions.All() {
		if initActions[name] {
			continue
		}
		g.emitSomeAction(w, name, act)
	}
}

func (g *Generator) emitSomeAction(w *goWriter, name string, act goivy.Action) {
	sig, returnNames := g.methodSignature(name, act)
	w.open(sig + " {")
	g.pushScope()
	for _, p := range act.GetFormalParams() {
		g.addLocal(p.Name)
	}
	returns := act.GetFormalReturns()
	prevReturns := g.currentReturns
	g.currentReturns = returns
	for _, r := range returns {
		g.addLocal(r.Name)
		expr, err := g.goRandomValueExpr(r.CSort, r.Name, 0)
		if err != nil {
			expr = g.goZeroValue(r.CSort)
			g.errs = append(g.errs, err)
		}
		w.linef("%s := %s", goName(r.Name), expr)
	}
	g.emitAction(w, act)
	g.currentReturns = prevReturns
	if len(returnNames) > 0 {
		w.linef("return %s", strings.Join(returnNames, ", "))
	}
	g.popScope()
	w.close("")
	w.blank()
}

func (g *Generator) methodSignature(name string, act goivy.Action) (string, []string) {
	fn, err := funName(name)
	if err != nil {
		fn = goName(name)
		g.errs = append(g.errs, err)
	}
	var params []string
	for _, p := range act.GetFormalParams() {
		params = append(params, fmt.Sprintf("%s %s", goName(p.Name), g.goType(p.CSort)))
	}
	var retTypes []string
	var retNames []string
	for _, r := range act.GetFormalReturns() {
		retTypes = append(retTypes, g.goType(r.CSort))
		retNames = append(retNames, goName(r.Name))
	}
	ret := ""
	if len(retTypes) == 1 {
		ret = " " + retTypes[0]
	} else if len(retTypes) > 1 {
		ret = " (" + strings.Join(retTypes, ", ") + ")"
	}
	return fmt.Sprintf("func (ivy *%s) %s(%s)%s", g.ClassName, fn, strings.Join(params, ", "), ret), retNames
}

func (g *Generator) emitTick(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __tick(timeout int) {", g.ClassName))
	w.line("_ = timeout")
	g.emitProgressTick(w)
	w.close("")
	w.blank()
}

func (g *Generator) emitSmokeMain(w *goWriter) {
	w.open(fmt.Sprintf("func %s() {", g.Config.MainName))
	w.line("_, _ = parseIvyTestArgs(os.Args[1:])")
	w.linef("_ = new%s()", exportedishName(g.ClassName))
	w.close("")
	w.blank()
}

func (g *Generator) emitTestMain(w *goWriter) {
	names := g.publicActionNamesSorted()
	initActions := g.initialMixinActionNames()
	var runnable []string
	for _, name := range names {
		if initActions[name] || isFinalizeName(name) {
			continue
		}
		runnable = append(runnable, name)
	}
	w.open(fmt.Sprintf("func %s() {", g.Config.MainName))
	w.line("opts, _ := parseIvyTestArgs(os.Args[1:])")
	w.linef("testIters := ivyAtoiDefault(opts[%q], %s)", "iters", g.Config.TestIters)
	if len(runnable) == 0 {
		w.line("_ = testIters")
	}
	w.linef("runs := ivyAtoiDefault(opts[%q], %s)", "runs", g.Config.TestRuns)
	w.line(`seed := int64(ivyAtoiDefault(opts["seed"], 1))`)
	w.line("ivySetSeed(seed)")
	w.open(`if out := opts["out"]; out != "" {`)
	w.line("f, err := os.Create(out)")
	w.open("if err != nil {")
	w.line(`fmt.Fprintf(os.Stderr, "cannot open to write: %s\n", out)`)
	w.line("os.Exit(1)")
	w.close("")
	w.line("defer f.Close()")
	w.line("__ivy_out = f")
	w.close("")
	w.open(`for key := range opts {`)
	w.line("switch key {")
	w.indent++
	w.line(`case "out", "iters", "runs", "seed", "delay", "wait", "modelfile":`)
	w.line("default:")
	w.indent++
	w.line(`fmt.Fprintf(os.Stderr, "unknown option: %s\n", key)`)
	w.line("os.Exit(1)")
	w.indent--
	w.indent--
	w.line("}")
	w.close("")
	w.open("for runidx := 0; runidx < runs; runidx++ {")
	w.linef("ivy := new%s()", exportedishName(g.ClassName))
	if len(runnable) == 0 {
		w.line("_ = ivy")
	} else {
		w.open("for cycle := 0; cycle < testIters; cycle++ {")
		totalWeight := 0.0
		for _, name := range runnable {
			totalWeight += g.actionWeight(name)
		}
		w.linef("__choice := __ivy_rng.Float64() * %s", goFloatLiteral(totalWeight))
		cumulative := 0.0
		for i, name := range runnable {
			fn, err := funName(name)
			if err != nil {
				fn = goName(name)
				g.errs = append(g.errs, err)
			}
			act, _ := g.Mod.Actions.Get2(name)
			cumulative += g.actionWeight(name)
			args := g.randomActualArgs(name, act)
			call := fmt.Sprintf("ivy.%s(%s)", fn, strings.Join(args, ", "))
			if i == 0 {
				w.open(fmt.Sprintf("if __choice < %s {", goFloatLiteral(cumulative)))
			} else {
				w.close(fmt.Sprintf(" else if __choice < %s {", goFloatLiteral(cumulative)))
				w.indent++
			}
			switch nret := len(act.GetFormalReturns()); nret {
			case 0:
				w.line(call)
			case 1:
				w.line("_ = " + call)
			default:
				w.line(strings.TrimSuffix(strings.Repeat("_, ", nret), ", ") + " = " + call)
			}
		}
		w.close("")
		w.line("ivy.__tick(0)")
		w.close("")
	}
	if g.hasFinalizeExport() {
		if fn, err := funName("ext:_finalize"); err == nil {
			w.linef("ivy.%s()", fn)
		}
	}
	w.close("")
	w.line(`fmt.Fprintln(__ivy_out, "test_completed")`)
	w.close("")
	w.blank()
}

func (g *Generator) randomActualArgs(actionName string, act goivy.Action) []string {
	if act == nil {
		return nil
	}
	formals := act.GetFormalParams()
	args := make([]string, len(formals))
	for i, p := range formals {
		if p == nil {
			continue
		}
		expr, err := g.goRandomValueExpr(p.CSort, actionName+"."+p.Name, int64(i))
		if err != nil {
			g.errs = append(g.errs, err)
			expr = g.goZeroValue(p.CSort)
		}
		args[i] = expr
	}
	return args
}

func goFloatLiteral(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	lower := strings.ToLower(s)
	if strings.Contains(s, ".") || strings.Contains(lower, "e") || strings.Contains(lower, "nan") || strings.Contains(lower, "inf") {
		return s
	}
	return s + ".0"
}

func (g *Generator) publicActionNamesSorted() []string {
	if g.Mod == nil || g.Mod.PublicActions == nil {
		return nil
	}
	var names []string
	for name := range g.Mod.PublicActions.All() {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func (g *Generator) initialMixinActionNames() map[string]bool {
	out := map[string]bool{}
	if g.Mod == nil || g.Mod.Mixins == nil {
		return out
	}
	for _, mixin := range g.Mod.Mixins.Get("init") {
		out[mixin.Mixer()] = true
	}
	return out
}

func isFinalizeName(name string) bool {
	return name == "ext:_finalize"
}

func (g *Generator) hasFinalizeExport() bool {
	if g.Mod == nil || g.Mod.PublicActions == nil {
		return false
	}
	for name := range g.Mod.PublicActions.All() {
		if isFinalizeName(name) {
			return true
		}
	}
	return false
}

func (g *Generator) actionWeight(name string) float64 {
	username := strings.TrimPrefix(name, "ext:")
	if g.Mod == nil || g.Mod.Attributes == nil {
		return 1.0
	}
	raw, ok := g.Mod.Attributes.Get2(username + ".weight")
	if !ok {
		return 1.0
	}
	type relnamer interface{ Relname() string }
	var s string
	switch v := raw.(type) {
	case string:
		s = v
	case relnamer:
		s = v.Relname()
	default:
		return 1.0
	}
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		s = s[1 : len(s)-1]
	}
	f, err := strconv.ParseFloat(s, 64)
	if err != nil {
		return 1.0
	}
	return f
}

func (g *Generator) nextTemp(prefix string) string {
	id := g.tempID
	g.tempID++
	return fmt.Sprintf("%s%d", prefix, id)
}

func (g *Generator) allStateSymbols() []stateSymbol {
	if g == nil || g.Mod == nil {
		return nil
	}
	seen := map[string]bool{}
	var out []stateSymbol
	add := func(name string, s goivy.Sort) {
		if name == "" || seen[name] {
			return
		}
		if g.Mod.Sig != nil && g.Mod.Sig.Constructors[name] {
			return
		}
		if g.isSortConstructorName(name) {
			return
		}
		seen[name] = true
		out = append(out, stateSymbol{Name: name, Sort: s})
	}
	if g.Mod.Sig != nil {
		for _, sym := range g.Mod.SymbolOrder {
			if sym == nil {
				continue
			}
			name := sym.Name
			if name == "" || seen[name] {
				continue
			}
			if !g.sigHasExactSymbol(name, sym.CSort) {
				continue
			}
			if g.Mod.Sig.Constructors[name] || g.isSortConstructorName(name) {
				continue
			}
			n, err := goivy.SolverName(sym, g.Mod.Sig, nil)
			if err == nil && n == "" {
				continue
			}
			add(name, sym.CSort)
		}
		for _, sym := range g.Mod.Sig.AllSymbols() {
			name := sym.Name
			if name == "" || seen[name] {
				continue
			}
			if g.Mod.Sig.Constructors[name] || g.isSortConstructorName(name) {
				continue
			}
			n, err := goivy.SolverName(sym, g.Mod.Sig, nil)
			if err == nil && n == "" {
				continue
			}
			add(name, sym.CSort)
		}
	}
	return out
}

func (g *Generator) stateSymbols() []stateSymbol {
	var out []stateSymbol
	seen := map[string]bool{}
	add := func(name string, s goivy.Sort) {
		if name == "" || seen[name] {
			return
		}
		if g.Mod.DestructorSorts != nil {
			if _, ok := g.Mod.DestructorSorts[name]; ok {
				return
			}
		}
		if g.Mod.Sig != nil && g.Mod.Sig.Constructors[name] {
			return
		}
		if g.isSortConstructorName(name) {
			return
		}
		seen[name] = true
		out = append(out, stateSymbol{Name: name, Sort: s})
	}
	for _, sym := range g.allStateSymbols() {
		add(sym.Name, sym.Sort)
	}
	return out
}

func (g *Generator) sigHasExactSymbol(name string, sort goivy.Sort) bool {
	if g == nil || g.Mod == nil || g.Mod.Sig == nil || name == "" {
		return false
	}
	entry, ok := g.Mod.Sig.Symbols.Get2(name)
	if !ok || entry == nil {
		return false
	}
	if entry.Union != nil {
		for _, s := range entry.Union.Sorts {
			if goivy.SortEqual(s, sort) {
				return true
			}
		}
		return false
	}
	return goivy.SortEqual(entry.Sort, sort)
}

func (g *Generator) isSortConstructorName(name string) bool {
	if g == nil || g.Mod == nil || name == "" {
		return false
	}
	if g.Mod.ConstructorSorts != nil {
		if _, ok := g.Mod.ConstructorSorts[name]; ok {
			return true
		}
	}
	if g.Mod.SortConstructors != nil {
		for _, conss := range g.Mod.SortConstructors.All() {
			for _, cons := range conss {
				if cons != nil && cons.Name == name {
					return true
				}
			}
		}
	}
	return false
}

func (g *Generator) isStateSymbolName(name string) (goivy.Sort, bool) {
	for _, sym := range g.stateSymbols() {
		if sym.Name == name {
			return sym.Sort, true
		}
	}
	return nil, false
}

func (g *Generator) isParamName(name string) bool {
	if g == nil || g.Mod == nil {
		return false
	}
	for _, p := range g.Mod.Params {
		if p != nil && p.Name == name {
			return true
		}
	}
	return false
}

func (g *Generator) pushScope() {
	g.locals = append(g.locals, map[string]bool{})
}

func (g *Generator) popScope() {
	if len(g.locals) > 0 {
		g.locals = g.locals[:len(g.locals)-1]
	}
}

func (g *Generator) addLocal(name string) {
	if len(g.locals) == 0 {
		g.pushScope()
	}
	g.locals[len(g.locals)-1][name] = true
}

func (g *Generator) isLocal(name string) bool {
	for i := len(g.locals) - 1; i >= 0; i-- {
		if g.locals[i][name] {
			return true
		}
	}
	return false
}

func (g *Generator) unsupported(w *goWriter, format string, args ...any) {
	err := fmt.Errorf("ivy2golang: "+format, args...)
	g.errs = append(g.errs, err)
	w.linef("panic(%q)", err.Error())
}

func linenoStr(loc goivy.Location) string {
	if loc.Line > 0 {
		return loc.String()
	}
	return ""
}
