func (g *Generator) emitRandomizedActionCycles(w *goWriter, runnable []string, testItersName, sleepMsName string) {
	if len(runnable) == 0 {
		w.line("_ = ivy")
		w.linef("_ = %s", testItersName)
		w.linef("_ = %s", sleepMsName)
	} else {
		w.open(fmt.Sprintf("for cycle := 0; cycle < %s; cycle++ {", testItersName))
		totalWeight := 0.0
		for _, name := range runnable {
			totalWeight += g.actionWeight(name)
		}
		w.linef("__choices := %s + 5.0", goFloatLiteral(totalWeight))
		w.line("__choice := float64(ivyRand31()) * __choices / 2147483648.0")
		w.open(fmt.Sprintf("if __choice >= %s {", goFloatLiteral(totalWeight)))
		w.line("cycle--")
		w.line("continue")
		w.close("")
		cumulative := 0.0
		for i, name := range runnable {
			fn, err := funName(name)
			if err != nil {
				fn = goName(name)
				g.errs = append(g.errs, err)
			}
			act, _ := g.Mod.Actions.Get2(name)
			genAct := g.actionGeneratorAnalysisAction(name, act)
			cumulative += g.actionWeight(name)
			if i == 0 {
				w.open(fmt.Sprintf("if __choice < %s {", goFloatLiteral(cumulative)))
			} else {
				w.close(fmt.Sprintf(" else if __choice < %s {", goFloatLiteral(cumulative)))
				w.indent++
			}
			genVar := g.goActionGeneratorVarName(name)
			w.linef("%s := &%s{ivy: ivy}", genVar, g.goActionGeneratorTypeName(name))
			w.open(fmt.Sprintf("if !%s.generate() {", genVar))
			w.line("cycle--")
			w.line("continue")
			w.close("")
			var args []string
			if act != nil {
				formals := act.GetFormalParams()
				args = make([]string, len(formals))
				for i, p := range formals {
					args[i] = fmt.Sprintf("__arg%d", i)
					w.linef("%s := %s.%s", args[i], genVar, goName(p.Name))
				}
			}
			call := fmt.Sprintf("ivy.%s(%s)", fn, strings.Join(args, ", "))
			trace := g.actionTraceLine(name, args)
			if g.isTestImportCallback(name) {
				w.line(trace)
				w.line("ivy._generating = true")
				switch nret := len(act.GetFormalReturns()); nret {
				case 0:
				case 1:
					w.linef("fmt.Fprintf(__ivy_out, %q, %s)", "= %s\n", g.traceValueExpr(g.goZeroValue(act.GetFormalReturns()[0].CSort)))
				default:
					lhs := strings.TrimSuffix(strings.Repeat("_, ", nret), ", ")
					rhs := make([]string, nret)
					for i := range rhs {
						rhs[i] = "0"
					}
					w.line(lhs + " = " + strings.Join(rhs, ", "))
				}
				w.line("ivy._generating = false")
				continue
			}
			if testActionNeedsTrial(genAct) {
				g.emitTestTrialActionCall(w, fn, act, args, trace)
				continue
			}
			w.line(trace)
			w.line("ivy._generating = true")
			switch nret := len(act.GetFormalReturns()); nret {
			case 0:
				w.linef("ivy.___ivy_push(%q)", name)
				w.line(call)
				w.line("ivy.___ivy_pop()")
			case 1:
				w.linef("ivy.___ivy_push(%q)", name)
				w.linef("__ivy_result := %s", call)
				w.line("ivy.___ivy_pop()")
				w.linef("fmt.Fprintf(__ivy_out, %q, %s)", "= %s\n", g.traceValueExpr("__ivy_result"))
			default:
				w.linef("ivy.___ivy_push(%q)", name)
				w.line(strings.TrimSuffix(strings.Repeat("_, ", nret), ", ") + " = " + call)
				w.line("ivy.___ivy_pop()")
			}
			w.line("ivy._generating = false")
		}
		w.close("")
		w.linef("ivy.__tick(%s)", sleepMsName)
		w.open(fmt.Sprintf("if %s > 0 {", sleepMsName))
		w.linef("time.Sleep(time.Duration(%s) * time.Millisecond)", sleepMsName)
		w.close("")
		w.close("")
	}
}

func (g *Generator) emitTestTrialActionCall(w *goWriter, fn string, act goivy.Action, args []string, trace string) {
	call := fmt.Sprintf("__ivy_trial.%s(%s)", fn, strings.Join(args, ", "))
	w.line("__ivy_trial := ivy.__ivy_clone()")
	w.line("var __ivy_trace bytes.Buffer")
	w.line("__ivy_saved_out := __ivy_out")
	w.line("__ivy_saved_assume_rejecting := __ivy_assume_rejecting")
	w.line("__ivy_saved_assume_rejected := __ivy_assume_rejected")
	w.line("__ivy_out = &__ivy_trace")
	w.line("__ivy_assume_rejecting = true")
	w.line("__ivy_assume_rejected = false")
	w.line("__ivy_trial._generating = true")
	w.linef("__ivy_trial.___ivy_push(%q)", fn)
	nret := 0
	if act != nil {
		nret = len(act.GetFormalReturns())
	}
	switch nret {
	case 0:
		w.line(call)
	case 1:
		w.line("__ivy_result := " + call)
	default:
		w.line(strings.TrimSuffix(strings.Repeat("_, ", nret), ", ") + " = " + call)
	}
	w.line("__ivy_trial.___ivy_pop()")
	w.line("__ivy_trial._generating = false")
	w.line("__ivy_trial_rejected := __ivy_assume_rejected")
	w.line("__ivy_out = __ivy_saved_out")
	w.line("__ivy_assume_rejecting = __ivy_saved_assume_rejecting")
	w.line("__ivy_assume_rejected = __ivy_saved_assume_rejected")
	w.open("if __ivy_trial_rejected {")
	w.line("cycle--")
	w.line("continue")
	w.close("")
	w.line("ivy = __ivy_trial")
	w.line(trace)
	w.line("_, _ = io.Copy(__ivy_out, &__ivy_trace)")
	if nret == 1 {
		w.linef("fmt.Fprintf(__ivy_out, %q, %s)", "= %s\n", g.traceValueExpr("__ivy_result"))
	}
}

func testActionNeedsTrial(act goivy.Action) bool {
	return actionContainsCall(act) || actionContainsAssume(act)
}

func actionContainsCall(act goivy.Action) bool {
	if act == nil {
		return false
	}
	if _, ok := act.(*goivy.LogicCallAction); ok {
		return true
	}
	for _, child := range act.ActionArgs() {
		childAct, ok := child.(goivy.Action)
		if !ok {
			continue
		}
		if actionContainsCall(childAct) {
			return true
		}
	}
	return false
}

func actionContainsAssume(act goivy.Action) bool {
	if act == nil {
		return false
	}
	if _, ok := act.(*goivy.LogicAssumeAction); ok {
		return true
	}
	for _, child := range act.ActionArgs() {
		childAct, ok := child.(goivy.Action)
		if !ok {
			continue
		}
		if actionContainsAssume(childAct) {
			return true
		}
	}
	return false
}

func (g *Generator) emitTestActionDefinedInputs(w *goWriter, name string, act goivy.Action, args []string) {
	defs := g.genActionGeneratorDefinedInputs(act, g.testActionPreconditionFormulas(name, act))
	if len(defs) == 0 {
		return
	}
	g.pushExprOverrides(actionFormalExprOverridesToArgs(act, args))
	defer g.popExprOverrides()
	for _, def := range defs {
		lhs, err := g.emitExpr(def.lhs)
		if err != nil {
			g.unsupportedAt(w, def.loc, "unsupported target=test defined input: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
			continue
		}
		expr, err := g.emitExpr(def.value)
		if err != nil {
			g.unsupportedAt(w, def.loc, "unsupported target=test defined input: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
			continue
		}
		if call, ok, err := g.goStorageSet(def.lhs, expr); ok || err != nil {
			if err != nil {
				g.unsupportedAt(w, def.loc, "unsupported target=test defined input: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
				continue
			}
			w.line(call)
			continue
		}
		w.linef("%s = %s", lhs, expr)
	}
}

