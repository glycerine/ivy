func (g *Generator) emitCloneStorage(w *goWriter, name string, s goivy.Sort) {
	fs, ok := s.(*goivy.LogicFunctionSort)
	if !ok || len(fs.Domain()) == 0 {
		return
	}
	field := goName(name)
	st := g.goFunctionStorageFor(fs.Domain(), fs.Range())
	if st.Large {
		w.linef("clone.%s = ivyThunkMap[%s, %s]{base: ivy.%s.base, zero: ivy.%s.zero}", field, st.KeyType, st.RangeType, field, field)
		w.open(fmt.Sprintf("if ivy.%s.overrides != nil {", field))
		w.linef("clone.%s.overrides = make(map[%s]%s, len(ivy.%s.overrides))", field, st.KeyType, st.RangeType, field)
		w.open(fmt.Sprintf("for k, v := range ivy.%s.overrides {", field))
		w.linef("clone.%s.overrides[k] = v", field)
		w.close("")
		w.close("")
		return
	}
	w.open(fmt.Sprintf("if ivy.%s != nil {", field))
	w.linef("clone.%s = make(map[%s]%s, len(ivy.%s))", field, st.KeyType, st.RangeType, field)
	w.open(fmt.Sprintf("for k, v := range ivy.%s {", field))
	w.linef("clone.%s[k] = v", field)
	w.close("")
	w.close("")
}

func (g *Generator) emitCloneProgressStorage(w *goWriter, p progressDecl) {
	if len(p.Vars) == 0 {
		return
	}
	name := goName(p.Name)
	domain := progressDomain(p)
	keyType := g.goMapKeyType(domain)
	w.open(fmt.Sprintf("if ivy.%s != nil {", name))
	w.linef("clone.%s = make(map[%s]int, len(ivy.%s))", name, keyType, name)
	w.open(fmt.Sprintf("for k, v := range ivy.%s {", name))
	w.linef("clone.%s[k] = v", name)
	w.close("")
	w.close("")
}

func (g *Generator) emitInitialState(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __initState() {", g.ClassName))
	retryFormulas := g.initialStateRetryFormulas()
	acts, err := g.initialConditionActions()
	if err != nil {
		if g.Config.Target != "gen" {
			if solveErr := g.emitSolvedInitialState(w); solveErr == nil {
				w.close("")
				w.blank()
				return
			}
		}
		g.unsupportedAt(w, initialErrorLocation(err), "unsupported initial condition: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
		w.close("")
		w.blank()
		return
	}
	if len(retryFormulas) > 0 {
		if solveErr := g.emitSolvedInitialState(w); solveErr == nil {
			w.close("")
			w.blank()
			return
		}
	}
	if g.Config.Target == "gen" && len(acts) == 0 {
		if constraints, constraintsErr := g.initialStateConstraints(); constraintsErr == nil && len(constraints.Formulas) > 0 {
			if solveErr := g.emitSolvedInitialState(w); solveErr == nil {
				w.close("")
				w.blank()
				return
			}
		}
	}
	if len(retryFormulas) > 0 {
		w.open("for __ivy_init_attempt := 0; ; __ivy_init_attempt++ {")
	}
	for _, sym := range g.stateSymbols() {
		if g.isParamName(sym.Name) {
			continue
		}
		g.emitRandomizeSymbol(w, sym, "init")
	}
	for _, act := range acts {
		g.emitAction(w, act)
	}
	if len(retryFormulas) > 0 {
		if expr, err := g.initialStateRetryExpr(retryFormulas); err != nil {
			g.unsupportedAt(w, initialErrorLocation(err), "unsupported initial axiom retry condition: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
		} else {
			w.open("if " + expr + " {")
			w.line("break")
			w.close("")
			w.open("if __ivy_init_attempt >= 999 {")
			w.line(`ivyAssume(false, "initial condition")`)
			w.line("break")
			w.close("")
		}
		w.close("")
	}
	w.close("")
	w.blank()
}

func (g *Generator) initialStateRetryExpr(formulas []goivy.Expr) (string, error) {
	exprs := make([]string, 0, len(formulas))
	for _, f := range formulas {
		if f == nil {
			continue
		}
		expr, err := g.emitExpr(closeFormulaForGo(f))
		if err != nil {
			return "", withInitialErrorLocation(f, err)
		}
		exprs = append(exprs, "("+expr+")")
	}
	if len(exprs) == 0 {
		return "true", nil
	}
	return strings.Join(exprs, " && "), nil
}

func (g *Generator) emitRandomizeSymbol(w *goWriter, sym stateSymbol, label string) {
	if sym.Name == "_generating" {
		w.line(`_ = ivy.___ivy_randomize(2, "init._generating", 0)`)
		w.line(`ivy._generating = ivy.___ivy_choose(0, "init", 0) != 0`)
		return
	}
	if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
		if !g.canEnumerateDomain(fs.Domain()) {
			base := "ivy." + goName(sym.Name)
			w.linef("%s = %s", base, g.goFunctionStorageInit(fs.Domain(), fs.Range()))
			g.emitNondetThunkBase(w, base, fs.Domain(), fs.Range(), label, 0)
			return
		}
		g.emitDomainLoops(w, fs.Domain(), func(args []string) {
			expr, err := g.goRandomValueExpr(fs.Range(), label+"."+sym.Name, int64(len(args)))
			if err != nil {
				g.unsupported(w, "%s", err.Error())
				return
			}
			w.linef("%s = %s", g.goStorageAccess(sym.Name, sym.Sort, args, "ivy"), expr)
		})
		return
	}
	expr, err := g.goRandomValueExpr(sym.Sort, label+"."+sym.Name, 0)
	if err != nil {
		g.unsupported(w, "%s", err.Error())
		return
	}
	w.linef("ivy.%s = %s", goName(sym.Name), expr)
}

func (g *Generator) emitNondetThunkBase(w *goWriter, base string, domain []goivy.Sort, rng goivy.Sort, label string, id int64) {
	st := g.goFunctionStorageFor(domain, rng)
	if !st.Large {
		return
	}
	expr, err := g.goNondetThunkValueExpr(rng, label, id)
	if err != nil {
		g.unsupported(w, "unsupported nondet thunk range: %s", err.Error())
		return
	}
	w.open(fmt.Sprintf("%s.base = func(__ivy_key %s) %s {", base, st.KeyType, st.RangeType))
	w.line("_ = __ivy_key")
	w.linef("return %s", expr)
	w.close("")
}

func (g *Generator) goNondetThunkValueExpr(s goivy.Sort, label string, id int64) (string, error) {
	if len(g.destructorStructFieldInfos(sortName(s))) > 0 {
		return g.goRandomValueExpr(s, label, id)
	}
	return g.goLocalNondetValueExpr(s, label, id)
}

func (g *Generator) emitDomainLoops(w *goWriter, domain []goivy.Sort, body func(args []string)) {
	var args []string
	var recur func(int)
	recur = func(i int) {
		if i == len(domain) {
			body(args)
			return
		}
		name := fmt.Sprintf("__i%d", i)
		header, ok, err := g.goLoopHeaderForSort(domain[i], name)
		if err != nil {
			g.unsupported(w, "cannot enumerate function domain sort %s: %s", sortName(domain[i]), err.Error())
			return
		}
		if !ok {
			g.unsupported(w, "cannot enumerate function domain sort %s", sortName(domain[i]))
			return
		}
		w.open(header)
		args = append(args, name)
		recur(i + 1)
		args = args[:len(args)-1]
		w.close("")
	}
	recur(0)
}

func (g *Generator) emitInit(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __init() {", g.ClassName))
	if len(g.Mod.InitialActions) > 0 {
		for _, act := range g.Mod.InitialActions {
			g.emitInitializerAction(w, act)
		}
		w.close("")
		w.blank()
		return
	}
	for _, na := range g.Mod.Initializers {
		if act, ok := na.Action.(goivy.Action); ok {
			g.emitInitializerAction(w, act)
		}
	}
	if len(g.Mod.Initializers) == 0 && g.Mod.Actions != nil && g.Mod.Mixins != nil {
		for _, mixin := range g.Mod.Mixins.Get("init") {
			if act, ok := g.Mod.Actions.Get2(mixin.Mixer()); ok {
				g.emitInitializerAction(w, act)
			}
		}
	}
	w.close("")
	w.blank()
}

func (g *Generator) emitInitializerAction(w *goWriter, act goivy.Action) {
	if act == nil || len(act.GetFormalParams()) == 0 {
		g.emitAction(w, act)
		return
	}
	type initializerLoopHeader struct {
		param  *goivy.Const
		header string
	}
	var headers []initializerLoopHeader
	for _, p := range act.GetFormalParams() {
		if p == nil {
			continue
		}
		header, ok, err := g.goLoopHeaderForSort(p.CSort, goName(p.Name))
		if err != nil {
			if initialActionCanEmitWithoutParamLoops(act) {
				g.emitAction(w, act)
			} else {
				g.unsupportedAt(w, act.GetLineno(), "cannot enumerate initializer parameter %s: %s", p.Name, strings.TrimPrefix(err.Error(), "ivy2golang: "))
			}
			return
		}
		if !ok {
			if initialActionCanEmitWithoutParamLoops(act) {
				g.emitAction(w, act)
			} else {
				g.unsupportedAt(w, act.GetLineno(), "cannot enumerate initializer parameter %s", p.Name)
			}
			return
		}
		headers = append(headers, initializerLoopHeader{param: p, header: header})
	}
	g.pushScope()
	for _, h := range headers {
		g.addLocalSort(h.param.Name, h.param.CSort)
		w.open(h.header)
	}
	g.emitAction(w, act)
	for range headers {
		w.close("")
	}
	g.popScope()
}

func initialActionCanEmitWithoutParamLoops(act goivy.Action) bool {
	if act == nil {
		return false
	}
	formals := act.GetFormalParams()
	if len(formals) == 0 {
		return true
	}
	varNames := map[string]bool{}
	for _, sub := range act.IterSubactions() {
		if sub == nil {
			continue
		}
		for _, arg := range sub.ActionArgs() {
			for _, v := range goivy.VariablesAstList(arg) {
				if v != nil {
					varNames[v.Name] = true
				}
			}
		}
	}
	for _, p := range formals {
		if p == nil {
			continue
		}
		if !varNames[p.Name] {
			return false
		}
	}
	return true
}

func (g *Generator) emitMethods(w *goWriter) {
	g.emitConstructors(w)
	g.emitNativeDefinitionMethods(w)
	if g.Mod.Actions == nil {
		return
	}
	for name, act := range g.Mod.Actions.All() {
		g.emitSomeAction(w, name, act)
	}
}

func (g *Generator) emitSomeAction(w *goWriter, name string, act goivy.Action) {
	sig, returnNames := g.methodSignature(name, act)
	w.open(sig + " {")
	if g.isReplImportCallback(name) {
		g.emitReplImportCallbackBody(w, name, act)
		w.close("")
		w.blank()
		return
	}
	g.pushScope()
	declaredGoNames := map[string]bool{}
	for _, p := range act.GetFormalParams() {
		g.addLocalSort(p.Name, p.CSort)
		declaredGoNames[goName(p.Name)] = true
	}
	traceImportCaller := g.importCallers()[name]
	if traceImportCaller {
		g.emitTraceActionPrologue(w, name, act.GetFormalParams())
		if g.Config.Trace {
			w.line(`fmt.Fprintln(__ivy_out, "{")`)
		}
	}
	returns := act.GetFormalReturns()
	prevReturns := g.currentReturns
	g.currentReturns = returns
	for _, r := range returns {
		g.addLocalSort(r.Name, r.CSort)
		rName := goName(r.Name)
		if declaredGoNames[rName] {
			continue
		}
		declaredGoNames[rName] = true
		w.linef("%s := %s", rName, g.goZeroValue(r.CSort))
	}
	g.emitAction(w, act)
	g.currentReturns = prevReturns
	if traceImportCaller && g.Config.Trace {
		w.line(`fmt.Fprintln(__ivy_out, "}")`)
	}
	if len(returnNames) > 0 {
		w.linef("return %s", strings.Join(returnNames, ", "))
	}
	g.popScope()
	w.close("")
	w.blank()
}

// importCallers mirrors Python find_import_callers through the ivy2cpp port.
// For target=test, unscoped imports named as known actions get a callback
// trace prologue at the top of the corresponding action body.
func (g *Generator) importCallers() map[string]bool {
	if g.importCallersCache != nil {
		return g.importCallersCache
	}
	out := map[string]bool{}
	if g.Config.Target == "test" && g.Mod != nil && g.Mod.Actions != nil {
		for _, imp := range g.Mod.Imports {
			impDef, ok := imp.(*goivy.ImportDef)
			if !ok {
				continue
			}
			if atom, ok := impDef.Scope.(*goivy.Atom); ok && atom.Relname() != "" {
				continue
			}
			name := ""
			if atom, ok := impDef.Imported.(*goivy.Atom); ok {
				name = atom.Relname()
			}
			if name == "" {
				continue
			}
			if _, ok := g.Mod.Actions.Get2(name); !ok {
				continue
			}
			caller := name
			if strings.HasPrefix(caller, "imp__") {
				caller = strings.TrimPrefix(caller, "imp__")
			} else {
				caller = strings.TrimPrefix(caller, "ext:")
			}
			out["ext:"+caller] = true
			out[caller] = true
		}
	}
	g.importCallersCache = out
	return out
}

func (g *Generator) isTestImportCallback(name string) bool {
	if g == nil || g.Config.Target != "test" {
		return false
	}
	return g.importCallers()[name]
}

func (g *Generator) isReplImportCallback(name string) bool {
	if g == nil || g.Config.Target != "repl" {
		return false
	}
	return g.importActions()[name]
}

func (g *Generator) importActions() map[string]bool {
	if g.importActionsCache != nil {
		return g.importActionsCache
	}
	out := map[string]bool{}
	if g.Mod != nil && g.Mod.Actions != nil {
		for _, imp := range g.Mod.Imports {
			impDef, ok := imp.(*goivy.ImportDef)
			if !ok {
				continue
			}
			if atom, ok := impDef.Scope.(*goivy.Atom); ok && atom.Relname() != "" {
				continue
			}
			name := ""
			if atom, ok := impDef.Imported.(*goivy.Atom); ok {
				name = atom.Relname()
			}
			if name == "" {
				continue
			}
			if _, ok := g.Mod.Actions.Get2(name); !ok {
				continue
			}
			out[name] = true
		}
	}
	g.importActionsCache = out
	return out
}

func (g *Generator) emitReplImportCallbackBody(w *goWriter, name string, act goivy.Action) {
	formals := act.GetFormalParams()
	display := actionDisplayName(name)
	if len(formals) == 0 {
		w.linef("fmt.Fprintln(__ivy_out, %q)", "< "+display)
	} else {
		args := make([]string, 0, len(formals))
		for _, p := range formals {
			args = append(args, g.traceValueExpr(goName(p.Name)))
		}
		format := "< " + display + "(" + strings.TrimSuffix(strings.Repeat("%s,", len(formals)), ",") + ")\n"
		w.linef("fmt.Fprintf(__ivy_out, %q, %s)", format, strings.Join(args, ", "))
	}
	returns := act.GetFormalReturns()
	if len(returns) == 0 {
		return
	}
	zeros := make([]string, len(returns))
	for i, r := range returns {
		zeros[i] = g.replImportCallbackReturnExpr(r.CSort)
	}
	w.linef("return %s", strings.Join(zeros, ", "))
}

func (g *Generator) replImportCallbackReturnExpr(s goivy.Sort) string {
	card := g.sortCard(s)
	if card <= 0 {
		return g.goZeroValue(s)
	}
	ask := fmt.Sprintf("ivyAskRet(%d)", card)
	switch st := s.(type) {
	case *goivy.BooleanSort:
		return ask + " != 0"
	case *goivy.LogicEnumeratedSort:
		if st.Name != "" && !isNumericEnum(st) {
			return fmt.Sprintf("%s(%s)", g.goScalarType(s), ask)
		}
	}
	return ask
}

func (g *Generator) emitTraceActionPrologue(w *goWriter, name string, formals []*goivy.Const) {
	display := actionDisplayName(name)
	w.linef("fmt.Fprint(__ivy_out, %q)", "< "+display)
	if len(formals) > 0 {
		w.line(`fmt.Fprint(__ivy_out, "(")`)
		for i, p := range formals {
			if i > 0 {
				w.line(`fmt.Fprint(__ivy_out, ",")`)
			}
			w.linef("fmt.Fprint(__ivy_out, ivyTraceValue(%s, %t))", goName(p.Name), g.traceHex())
		}
		w.line(`fmt.Fprint(__ivy_out, ")")`)
	}
	w.line("fmt.Fprintln(__ivy_out)")
}

func (g *Generator) methodSignature(name string, act goivy.Action) (string, []string) {
	fn, err := funName(name)
	if err != nil {
		fn = goName(name)
		g.errs = append(g.errs, err)
	}
	var params []string
	for _, p := range act.GetFormalParams() {
		params = append(params, fmt.Sprintf("%s %s", goName(p.Name), g.goType(p.CSort)))
	}
	var retTypes []string
	var retNames []string
	for _, r := range act.GetFormalReturns() {
		retTypes = append(retTypes, g.goType(r.CSort))
		retNames = append(retNames, goName(r.Name))
	}
	ret := ""
	if len(retTypes) == 1 {
		ret = " " + retTypes[0]
	} else if len(retTypes) > 1 {
		ret = " (" + strings.Join(retTypes, ", ") + ")"
	}
	return fmt.Sprintf("func (ivy *%s) %s(%s)%s", g.ClassName, fn, strings.Join(params, ", "), ret), retNames
}

