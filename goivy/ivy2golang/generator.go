type Config struct {
	Target          string
	RequestedTarget string
	ClassName       string
	MainName        string
	OutDir          string
	Compiler        string
	TestIters       string
	TestRuns        string
	Build           bool
	EmitMain        bool
	Trace           bool
	Stdafx          bool
	HostOS          string
}

type Output struct {
	Source          string
	BaseName        string
	ClassName       string
	Target          string
	EffectiveTarget string
	EmitMain        bool
	Config          Config
	ExtraFiles      map[string]string
	LibSpecs        []string
	Warnings        []string
}

type Generator struct {
	Mod       *goivy.Module
	Config    Config
	BaseName  string
	ClassName string

	tempID     int
	errs       []error
	warnings   []string
	warningSet map[string]bool

	locals             []map[string]goivy.Sort
	currentReturns     []*goivy.Const
	extRel             map[string]bool
	importCallersCache map[string]bool
	exprAliases        map[string]goivy.Expr
	exprOverrides      []map[string]string
	defStack           map[string]bool
}

func Generate(mod *goivy.Module, cfg Config) (*Output, error) {
	if mod == nil {
		return nil, fmt.Errorf("ivy2golang: nil module")
	}
	if cfg.Target == "" && cfg.RequestedTarget == "" {
		cfg.Target = "impl"
	}
	var err error
	cfg, _, err = normalizeConfig(cfg)
	if err != nil {
		return nil, err
	}
	base := moduleBaseName(mod)
	className := cfg.ClassName
	if className == "" {
		className = goName(base)
	}
	applySessionParameters(mod, cfg)
	prepareModuleForGo(mod, cfg)
	g := &Generator{
		Mod:       mod,
		Config:    cfg,
		BaseName:  base,
		ClassName: className,
	}
	g.validatePublicActions()
	src, err := g.generate()
	if err != nil {
		return nil, err
	}
	return &Output{
		Source:          src,
		BaseName:        base,
		ClassName:       className,
		Target:          cfg.RequestedTarget,
		EffectiveTarget: cfg.Target,
		EmitMain:        cfg.EmitMain,
		Config:          cfg,
		LibSpecs:        moduleLibSpecs(mod),
		Warnings:        append([]string(nil), g.warnings...),
	}, nil
}

func (g *Generator) generate() (string, error) {
	var w goWriter
	w.line("// Code generated by ivy2golang; DO NOT EDIT.")
	w.linef("package %s", g.packageName())
	w.blank()
	g.emitImports(&w)
	g.emitSortDecls(&w)
	g.emitRuntime(&w)
	g.emitStruct(&w)
	g.emitConstructor(&w)
	g.emitInitialState(&w)
	g.emitInit(&w)
	g.emitMethods(&w)
	g.emitTick(&w)
	if g.Config.EmitMain {
		if g.Config.Target == "test" {
			g.emitTestMain(&w)
		} else if g.Config.Target == "gen" {
			g.emitGenMain(&w)
		} else {
			g.emitSmokeMain(&w)
		}
		g.emitMainWrapper(&w)
	}
	return w.String(), errors.Join(g.errs...)
}

func (g *Generator) validatePublicActions() {
	if g == nil || g.Mod == nil || g.Mod.Actions == nil || g.Mod.PublicActions == nil {
		return
	}
	for name, act := range g.Mod.Actions.All() {
		if !g.Mod.PublicActions.Get(name) || act == nil {
			continue
		}
		if len(act.GetFormalReturns()) > 1 {
			g.errs = append(g.errs, fmt.Errorf("ivy2golang: cannot handle multiple output in exported actions: %s", name))
		}
	}
}

func (g *Generator) packageName() string {
	if g != nil && !g.Config.EmitMain {
		return "ivygenerated"
	}
	return "main"
}

func (g *Generator) emitImports(w *goWriter) {
	w.line("import (")
	w.indent++
	imports := []string{"fmt", "io", "math/rand/v2", "os", "strconv", "strings"}
	if g.Config.Target == "test" || g.Config.Target == "gen" {
		imports = append(imports, "time")
	}
	for _, imp := range imports {
		w.linef("%q", imp)
	}
	w.indent--
	w.line(")")
	w.blank()
}

func (g *Generator) emitSortDecls(w *goWriter) {
	if g.Mod == nil || g.Mod.Sig == nil {
		return
	}
	for _, name := range g.Mod.SortOrder {
		s, ok := g.Mod.Sig.Sorts.Get2(name)
		if !ok {
			continue
		}
		st, ok := s.(*goivy.LogicEnumeratedSort)
		if !ok || st.Name == "" || isNumericEnum(st) {
			continue
		}
		// Package-level Go type/const declarations are allowed to be unused,
		// and destructor-local variant construction can reference enum
		// constructors even when no retained state symbol mentions the enum
		// sort directly after isolate pruning.
		typeName := goName(st.Name)
		w.linef("type %s int", typeName)
		w.blank()
		w.line("const (")
		w.indent++
		for i, sym := range st.Extension {
			if i == 0 {
				w.linef("%s %s = iota", goName(sym), typeName)
			} else {
				w.line(goName(sym))
			}
		}
		w.indent--
		w.line(")")
		w.blank()
		w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
		w.line("switch v {")
		w.indent++
		for _, sym := range st.Extension {
			w.linef("case %s:", goName(sym))
			w.indent++
			w.linef("return %q", memName(sym))
			w.indent--
		}
		w.indent--
		w.line("}")
		w.line(`return fmt.Sprintf("%d", int(v))`)
		w.close("")
		w.blank()
	}
	for _, name := range g.Mod.SortOrder {
		if !g.isVariantSuperName(name) {
			continue
		}
		g.emitVariantSuperDecl(w, name)
	}
	for _, name := range g.Mod.SortOrder {
		fields := g.destructorStructFields(name)
		if len(fields) == 0 {
			continue
		}
		typeName := goName(name)
		w.open(fmt.Sprintf("type %s struct {", typeName))
		for _, d := range fields {
			fs := d.CSort.(*goivy.LogicFunctionSort)
			w.linef("%s %s", goName(memName(d.Name)), g.goScalarType(fs.Range()))
		}
		w.close("")
		w.blank()
		w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
		if len(fields) == 0 {
			w.line(`return "{}"`)
		} else {
			format := "{" + strings.Join(recordFormatLabels(fields), ",") + "}"
			args := make([]string, len(fields))
			for i, d := range fields {
				args[i] = "v." + goName(memName(d.Name))
			}
			w.linef("return fmt.Sprintf(%q, %s)", format, strings.Join(args, ", "))
		}
		w.close("")
		w.blank()
	}
}

func (g *Generator) emitVariantSuperDecl(w *goWriter, name string) {
	variants := g.Mod.Variants[name]
	typeName := goName(name)
	w.open(fmt.Sprintf("type %s struct {", typeName))
	w.line("tag int")
	w.line("value any")
	w.line("valid bool")
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
	w.open("if !v.valid {")
	w.line(`return "{}"`)
	w.close("")
	w.line("switch v.tag {")
	w.indent++
	for i, sub := range variants {
		subName := sortName(sub)
		payloadType := g.goScalarType(sub)
		w.linef("case %d:", i)
		w.indent++
		w.linef("return fmt.Sprintf(%q, v.value.(%s))", "{"+subName+":%v}", payloadType)
		w.indent--
	}
	w.indent--
	w.line("}")
	w.line(`return "{}"`)
	w.close("")
	w.blank()
}

func recordFormatLabels(fields []*goivy.Const) []string {
	labels := make([]string, 0, len(fields))
	for _, d := range fields {
		labels = append(labels, fmt.Sprintf("%s:%%v", memName(d.Name)))
	}
	return labels
}

func (g *Generator) sortNeededForGoDecl(name string) bool {
	for _, sym := range g.stateSymbols() {
		if g.sortDependenciesReferenceName(sym.Sort, name) {
			return true
		}
	}
	if g.Mod.Actions != nil {
		for _, act := range g.Mod.Actions.All() {
			for _, p := range act.GetFormalParams() {
				if g.sortDependenciesReferenceName(p.CSort, name) {
					return true
				}
			}
			for _, r := range act.GetFormalReturns() {
				if g.sortDependenciesReferenceName(r.CSort, name) {
					return true
				}
			}
		}
	}
	return false
}

