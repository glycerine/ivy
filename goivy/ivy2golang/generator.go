func (g *Generator) randomActualArgs(actionName string, act goivy.Action) []string {
	if act == nil {
		return nil
	}
	formals := act.GetFormalParams()
	args := make([]string, len(formals))
	for i, p := range formals {
		if p == nil {
			continue
		}
		expr, err := g.goActionParamRandomValueExpr(p.CSort, actionName+"."+p.Name, int64(i))
		if err != nil {
			g.errs = append(g.errs, errorAt(p.GetLineno(), err))
			expr = g.goZeroValue(p.CSort)
		}
		args[i] = expr
	}
	return args
}

func (g *Generator) actionTraceLine(name string, args []string) string {
	display := actionDisplayName(name)
	if len(args) == 0 {
		return fmt.Sprintf("fmt.Fprintln(__ivy_out, %q)", "> "+display)
	}
	format := "> " + display + "(" + strings.TrimSuffix(strings.Repeat("%s,", len(args)), ",") + ")\n"
	return fmt.Sprintf("fmt.Fprintf(__ivy_out, %q, %s)", format, strings.Join(g.traceValueExprs(args), ", "))
}

func (g *Generator) traceValueExpr(expr string) string {
	return fmt.Sprintf("ivyTraceValue(%s, %t)", expr, g.traceHex())
}

func (g *Generator) traceValueExprs(args []string) []string {
	out := make([]string, len(args))
	for i, arg := range args {
		out[i] = g.traceValueExpr(arg)
	}
	return out
}

func actionDisplayName(name string) string {
	if idx := strings.LastIndex(name, ":"); idx >= 0 {
		return name[idx+1:]
	}
	return name
}

func goFloatLiteral(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	lower := strings.ToLower(s)
	if strings.Contains(s, ".") || strings.Contains(lower, "e") || strings.Contains(lower, "nan") || strings.Contains(lower, "inf") {
		return s
	}
	return s + ".0"
}

