func (g *Generator) pushScope() {
	g.locals = append(g.locals, map[string]goivy.Sort{})
}

func (g *Generator) popScope() {
	if len(g.locals) > 0 {
		g.locals = g.locals[:len(g.locals)-1]
	}
}

func (g *Generator) addLocal(name string) {
	g.addLocalSort(name, nil)
}

func (g *Generator) addLocalSort(name string, sort goivy.Sort) {
	if len(g.locals) == 0 {
		g.pushScope()
	}
	g.locals[len(g.locals)-1][name] = sort
}

func (g *Generator) isLocal(name string) bool {
	_, ok := g.localSort(name)
	return ok
}

func (g *Generator) localSort(name string) (goivy.Sort, bool) {
	for i := len(g.locals) - 1; i >= 0; i-- {
		if sort, ok := g.locals[i][name]; ok {
			return sort, true
		}
	}
	return nil, false
}

func (g *Generator) pushExprOverrides(overrides map[string]string) {
	g.exprOverrides = append(g.exprOverrides, overrides)
}

func (g *Generator) popExprOverrides() {
	if len(g.exprOverrides) > 0 {
		g.exprOverrides = g.exprOverrides[:len(g.exprOverrides)-1]
	}
}

func (g *Generator) exprOverride(name string) (string, bool) {
	if g == nil {
		return "", false
	}
	for i := len(g.exprOverrides) - 1; i >= 0; i-- {
		if code, ok := g.exprOverrides[i][name]; ok {
			return code, true
		}
	}
	return "", false
}

