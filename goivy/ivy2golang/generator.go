func (g *Generator) emitGenActionGeneratorGenerate(w *goWriter, name string, act goivy.Action) {
	w.line("ivy := gen.ivy")
	if act == nil {
		w.line("_ = ivy")
		w.line("return true")
		return
	}
	g.emitGenActionGeneratorRandomizeState(w)
	if len(act.GetFormalParams()) == 0 {
		w.line("_ = ivy")
		g.emitGenActionGeneratorAssumeGuards(w, name, act)
		w.line("return true")
		return
	}
	for i, p := range act.GetFormalParams() {
		expr, err := g.goActionParamRandomValueExpr(p.CSort, actionFormalGeneratorLabel(p), int64(i))
		if err != nil {
			g.unsupported(w, "unsupported action generator parameter: %s", err.Error())
			continue
		}
		w.linef("gen.%s = %s", goName(p.Name), expr)
	}
	g.emitGenActionGeneratorDefinedInputs(w, name, act)
	g.emitGenActionGeneratorAssumeGuards(w, name, act)
	w.line("return true")
}

func (g *Generator) emitGenActionGeneratorRandomizeState(w *goWriter) {
	for _, sym := range g.stateSymbols() {
		if g.isParamName(sym.Name) {
			continue
		}
		g.emitGenRandomizeSymbol(w, sym, "randomize")
	}
}

func (g *Generator) emitGenRandomizeSymbol(w *goWriter, sym stateSymbol, label string) {
	if g.isVariantSuperName(sortName(sym.Sort)) {
		w.linef("ivy.%s = %s", goName(sym.Name), g.goZeroValue(sym.Sort))
		return
	}
	if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
		if !g.canEnumerateDomain(fs.Domain()) {
			base := "ivy." + goName(sym.Name)
			w.linef("%s = %s", base, g.goFunctionStorageInit(fs.Domain(), fs.Range()))
			g.emitNondetThunkBase(w, base, fs.Domain(), fs.Range(), label, 0)
			return
		}
		g.emitDomainLoops(w, fs.Domain(), func(args []string) {
			expr, err := g.goActionParamRandomValueExpr(fs.Range(), label+"."+sym.Name, int64(len(args)))
			if err != nil {
				g.unsupported(w, "%s", err.Error())
				return
			}
			w.linef("%s = %s", g.goStorageAccess(sym.Name, sym.Sort, args, "ivy"), expr)
		})
		return
	}
	expr, err := g.goActionParamRandomValueExpr(sym.Sort, label+"."+sym.Name, 0)
	if err != nil {
		g.unsupported(w, "%s", err.Error())
		return
	}
	w.linef("ivy.%s = %s", goName(sym.Name), expr)
}

type genDefinedInput struct {
	param *goivy.Const
	value goivy.Expr
}

func (g *Generator) emitGenActionGeneratorDefinedInputs(w *goWriter, name string, act goivy.Action) {
	defs := genActionGeneratorDefinedInputs(act, g.genActionPreconditionFormulas(name, act))
	if len(defs) == 0 {
		return
	}
	g.pushExprOverrides(genActionFormalExprOverrides(act))
	defer g.popExprOverrides()
	for _, def := range defs {
		expr, err := g.emitExpr(def.value)
		if err != nil {
			g.unsupported(w, "unsupported action generator defined input: %s", err.Error())
			continue
		}
		w.linef("gen.%s = %s", goName(def.param.Name), expr)
	}
}

func genActionGeneratorDefinedInputs(act goivy.Action, guards []goivy.Expr) []genDefinedInput {
	params := genActionFormalParamMap(act)
	if len(params) == 0 {
		return nil
	}
	var defs []genDefinedInput
	for _, guard := range guards {
		eq, ok := guard.(*goivy.Eq)
		if !ok {
			continue
		}
		if p, ok := genExprFormalParam(eq.T1, params); ok {
			defs = append(defs, genDefinedInput{param: p, value: eq.T2})
			continue
		}
		if p, ok := genExprFormalParam(eq.T2, params); ok {
			defs = append(defs, genDefinedInput{param: p, value: eq.T1})
		}
	}
	return defs
}

func genActionFormalParamMap(act goivy.Action) map[string]*goivy.Const {
	params := map[string]*goivy.Const{}
	if act == nil {
		return params
	}
	for _, p := range act.GetFormalParams() {
		if p == nil {
			continue
		}
		for _, name := range formalExprOverrideNames(p.Name) {
			params[name] = p
		}
	}
	return params
}

func genExprFormalParam(e goivy.Expr, params map[string]*goivy.Const) (*goivy.Const, bool) {
	c, ok := e.(*goivy.Const)
	if !ok || c == nil {
		return nil, false
	}
	p, ok := params[c.Name]
	return p, ok
}

func genActionFormalExprOverrides(act goivy.Action) map[string]string {
	overrides := map[string]string{}
	if act == nil {
		return overrides
	}
	for _, p := range act.GetFormalParams() {
		if p == nil {
			continue
		}
		field := "gen." + goName(p.Name)
		for _, name := range formalExprOverrideNames(p.Name) {
			overrides[name] = field
		}
	}
	return overrides
}

func (g *Generator) emitGenActionGeneratorAssumeGuards(w *goWriter, name string, act goivy.Action) {
	guards := g.genActionPreconditionFormulas(name, act)
	if len(guards) == 0 {
		return
	}
	g.pushExprOverrides(genActionFormalExprOverrides(act))
	defer g.popExprOverrides()
	for _, guard := range guards {
		expr, err := g.emitExpr(goivy.CloseFormula(guard))
		if err != nil {
			g.unsupported(w, "unsupported action generator assume guard: %s", err.Error())
			continue
		}
		w.open(fmt.Sprintf("if !(%s) {", expr))
		w.line("return false")
		w.close("")
	}
}

func (g *Generator) genActionPreconditionFormulas(name string, act goivy.Action) []goivy.Expr {
	var guards []goivy.Expr
	if g != nil && g.Mod != nil && g.Mod.ExtPreconds != nil {
		if pre := g.Mod.ExtPreconds[name]; pre != nil {
			guards = append(guards, pre)
		}
	}
	guards = append(guards, leadingAssumeFormulas(act)...)
	return guards
}

func leadingAssumeFormulas(act goivy.Action) []goivy.Expr {
	switch a := act.(type) {
	case *goivy.LogicAssumeAction:
		if a.Formula == nil {
			return nil
		}
		return []goivy.Expr{a.Formula}
	case *goivy.LogicSequence:
		var guards []goivy.Expr
		for _, elem := range a.Elems {
			assume, ok := elem.(*goivy.LogicAssumeAction)
			if !ok {
				break
			}
			if assume.Formula != nil {
				guards = append(guards, assume.Formula)
			}
		}
		return guards
	default:
		return nil
	}
}

func formalExprOverrideNames(name string) []string {
	base := name
	switch {
	case strings.HasPrefix(name, "__fml:"):
		base = strings.TrimPrefix(name, "__fml:")
	case strings.HasPrefix(name, "fml:"):
		base = strings.TrimPrefix(name, "fml:")
	}
	candidates := []string{name, base, "fml:" + base, "__fml:" + base}
	names := make([]string, 0, len(candidates))
	seen := map[string]bool{}
	for _, candidate := range candidates {
		if seen[candidate] {
			continue
		}
		seen[candidate] = true
		names = append(names, candidate)
	}
	return names
}

func actionFormalGeneratorLabel(p *goivy.Const) string {
	if p == nil {
		return "__fml:"
	}
	name := p.Name
	switch {
	case strings.HasPrefix(name, "__fml:"):
		return name
	case strings.HasPrefix(name, "fml:"):
		return "__" + name
	default:
		return "__fml:" + name
	}
}

func (g *Generator) emitGenActionGeneratorExecute(w *goWriter, name string, act goivy.Action) {
	w.line("ivy := gen.ivy")
	if act == nil {
		w.line("_ = ivy")
		return
	}
	args := make([]string, 0, len(act.GetFormalParams()))
	for _, p := range act.GetFormalParams() {
		args = append(args, "gen."+goName(p.Name))
	}
	fn, err := funName(name)
	if err != nil {
		fn = goName(name)
		g.errs = append(g.errs, err)
	}
	call := fmt.Sprintf("ivy.%s(%s)", fn, strings.Join(args, ", "))
	w.line(g.actionTraceLine(name, args))
	if g.Config.Trace {
		w.line(`fmt.Fprintln(__ivy_out, "{")`)
	}
	w.line("ivy._generating = true")
	if g.isTestImportCallback(name) {
		switch nret := len(act.GetFormalReturns()); nret {
		case 0:
		case 1:
			w.linef("fmt.Fprintf(__ivy_out, %q, %s)", "= %v\n", g.goZeroValue(act.GetFormalReturns()[0].CSort))
		default:
			lhs := strings.TrimSuffix(strings.Repeat("_, ", nret), ", ")
			rhs := make([]string, nret)
			for i := range rhs {
				rhs[i] = "0"
			}
			w.line(lhs + " = " + strings.Join(rhs, ", "))
		}
		w.line("ivy._generating = false")
		w.line("return")
		return
	}
	switch nret := len(act.GetFormalReturns()); nret {
	case 0:
		w.line(call)
		if g.Config.Trace {
			w.line(`fmt.Fprintln(__ivy_out, "}")`)
		}
	case 1:
		if g.Config.Trace {
			w.linef("__res := %s", call)
			w.line(`fmt.Fprintln(__ivy_out, "}")`)
			w.linef("fmt.Fprintf(__ivy_out, %q, __res)", "= %v\n")
		} else {
			w.linef("fmt.Fprintf(__ivy_out, %q, %s)", "= %v\n", call)
		}
	default:
		w.line(strings.TrimSuffix(strings.Repeat("_, ", nret), ", ") + " = " + call)
		if g.Config.Trace {
			w.line(`fmt.Fprintln(__ivy_out, "}")`)
		}
	}
	w.line("ivy._generating = false")
}

func (g *Generator) emitGenActionCycles(w *goWriter, runnable []string, testItersName, sleepMsName string) {
	if len(runnable) == 0 {
		w.line("_ = ivy")
		w.linef("_ = %s", testItersName)
		w.linef("_ = %s", sleepMsName)
		return
	}
	for _, name := range runnable {
		w.linef("%s := &%s{ivy: ivy}", g.goActionGeneratorVarName(name), g.goActionGeneratorTypeName(name))
	}
	w.open(fmt.Sprintf("for cycle := 0; cycle < %s; cycle++ {", testItersName))
	totalWeight := 0.0
	for _, name := range runnable {
		totalWeight += g.actionWeight(name)
	}
	w.linef("__choices := %s + 5.0", goFloatLiteral(totalWeight))
	w.line("__choice := float64(ivyRand31()) * __choices / 2147483648.0")
	w.open(fmt.Sprintf("if __choice >= %s {", goFloatLiteral(totalWeight)))
	w.line("cycle--")
	w.line("continue")
	w.close("")
	cumulative := 0.0
	for i, name := range runnable {
		genVar := g.goActionGeneratorVarName(name)
		cumulative += g.actionWeight(name)
		if i == 0 {
			w.open(fmt.Sprintf("if __choice < %s {", goFloatLiteral(cumulative)))
		} else {
			w.close(fmt.Sprintf(" else if __choice < %s {", goFloatLiteral(cumulative)))
			w.indent++
		}
		w.line("ivy._generating = true")
		w.open(fmt.Sprintf("if %s.generate() {", genVar))
		w.linef("%s.execute()", genVar)
		w.line("ivy._generating = false")
		w.close(" else {")
		w.indent++
		w.line("ivy._generating = false")
		w.line("cycle--")
		w.line("continue")
		w.indent--
		w.close("")
	}
	w.close("")
	w.line("ivy.__tick(0)")
	w.open(fmt.Sprintf("if %s > 0 {", sleepMsName))
	w.linef("time.Sleep(time.Duration(%s) * time.Millisecond)", sleepMsName)
	w.close("")
	w.close("")
}

