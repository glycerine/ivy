func (g *Generator) emitStruct(w *goWriter) {
	w.open(fmt.Sprintf("type %s struct {", g.ClassName))
	w.line("__argv []string")
	for _, sym := range g.stateSymbols() {
		w.line(g.goStorageDecl(sym.Name, sym.Sort))
	}
	g.emitProgressCounterDecls(w)
	w.close("")
	w.blank()
}

func (g *Generator) emitConstructor(w *goWriter) {
	w.open(fmt.Sprintf("func new%s(%s) *%s {", exportedishName(g.ClassName), strings.Join(g.constructorParamDecls(), ", "), g.ClassName))
	w.linef("ivy := &%s{}", g.ClassName)
	w.line("ivy.__initStorage()")
	for _, p := range g.Mod.Params {
		if p == nil {
			continue
		}
		w.linef("ivy.%s = %s", goName(p.Name), goName(p.Name))
	}
	w.line("ivy.__initState()")
	w.line("ivy.__init()")
	w.line("return ivy")
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (ivy *%s) __initStorage() {", g.ClassName))
	for _, sym := range g.stateSymbols() {
		if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
			w.linef("ivy.%s = %s", goName(sym.Name), g.goFunctionStorageInit(fs.Domain(), fs.Range()))
		}
	}
	g.emitProgressStorageInitializers(w)
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (ivy *%s) ___ivy_choose(rng int, name string, id int) int {", g.ClassName))
	w.line("_ = name")
	w.line("_ = id")
	w.open("if rng <= 0 {")
	w.line("return 0")
	w.close("")
	w.line("return ivyRand31() % rng")
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (ivy *%s) ___ivy_randomize(rng int, name string, id int) int {", g.ClassName))
	w.line("_ = name")
	w.line("_ = id")
	w.line("return ivyRandRange64(rng)")
	w.close("")
	w.blank()
}

func (g *Generator) emitInitialState(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __initState() {", g.ClassName))
	for _, sym := range g.stateSymbols() {
		if g.isParamName(sym.Name) {
			continue
		}
		g.emitRandomizeSymbol(w, sym, "init")
	}
	acts, err := g.initialConditionActions()
	if err != nil {
		g.unsupported(w, "unsupported initial condition: %s", err.Error())
	} else {
		for _, act := range acts {
			g.emitAction(w, act)
		}
	}
	w.close("")
	w.blank()
}

func (g *Generator) emitRandomizeSymbol(w *goWriter, sym stateSymbol, label string) {
	if sym.Name == "_generating" {
		w.line(`_ = ivy.___ivy_randomize(2, "init._generating", 0)`)
		w.line(`ivy._generating = ivy.___ivy_choose(0, "init", 0) != 0`)
		return
	}
	if g.isVariantSuperName(sortName(sym.Sort)) {
		w.linef("ivy.%s = %s", goName(sym.Name), g.goZeroValue(sym.Sort))
		return
	}
	if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
		if !g.canEnumerateDomain(fs.Domain()) {
			base := "ivy." + goName(sym.Name)
			w.linef("%s = %s", base, g.goFunctionStorageInit(fs.Domain(), fs.Range()))
			g.emitNondetThunkBase(w, base, fs.Domain(), fs.Range(), label, 0)
			return
		}
		g.emitDomainLoops(w, fs.Domain(), func(args []string) {
			expr, err := g.goRandomValueExpr(fs.Range(), label+"."+sym.Name, int64(len(args)))
			if err != nil {
				g.unsupported(w, "%s", err.Error())
				return
			}
			w.linef("%s = %s", g.goStorageAccess(sym.Name, sym.Sort, args, "ivy"), expr)
		})
		return
	}
	expr, err := g.goRandomValueExpr(sym.Sort, label+"."+sym.Name, 0)
	if err != nil {
		g.unsupported(w, "%s", err.Error())
		return
	}
	w.linef("ivy.%s = %s", goName(sym.Name), expr)
}

func (g *Generator) emitNondetThunkBase(w *goWriter, base string, domain []goivy.Sort, rng goivy.Sort, label string, id int64) {
	st := g.goFunctionStorageFor(domain, rng)
	if !st.Large {
		return
	}
	expr, err := g.goLocalNondetValueExpr(rng, label, id)
	if err != nil {
		g.unsupported(w, "unsupported nondet thunk range: %s", err.Error())
		return
	}
	w.open(fmt.Sprintf("%s.base = func(__ivy_key %s) %s {", base, st.KeyType, st.RangeType))
	w.line("_ = __ivy_key")
	w.linef("return %s", expr)
	w.close("")
}

func (g *Generator) emitDomainLoops(w *goWriter, domain []goivy.Sort, body func(args []string)) {
	var args []string
	var recur func(int)
	recur = func(i int) {
		if i == len(domain) {
			body(args)
			return
		}
		name := fmt.Sprintf("__i%d", i)
		vals, ok := g.finiteValueExprs(domain[i])
		if !ok {
			g.unsupported(w, "cannot enumerate function domain sort %s", sortName(domain[i]))
			return
		}
		w.open(fmt.Sprintf("for _, %s := range []%s{%s} {", name, g.goScalarType(domain[i]), strings.Join(vals, ", ")))
		args = append(args, name)
		recur(i + 1)
		args = args[:len(args)-1]
		w.close("")
	}
	recur(0)
}

func (g *Generator) emitInit(w *goWriter) {
	w.open(fmt.Sprintf("func (ivy *%s) __init() {", g.ClassName))
	if len(g.Mod.InitialActions) > 0 {
		for _, act := range g.Mod.InitialActions {
			g.emitAction(w, act)
		}
		w.close("")
		w.blank()
		return
	}
	for _, na := range g.Mod.Initializers {
		if act, ok := na.Action.(goivy.Action); ok {
			g.emitAction(w, act)
		}
	}
	if len(g.Mod.Initializers) == 0 && g.Mod.Actions != nil && g.Mod.Mixins != nil {
		for _, mixin := range g.Mod.Mixins.Get("init") {
			if act, ok := g.Mod.Actions.Get2(mixin.Mixer()); ok {
				g.emitAction(w, act)
			}
		}
	}
	w.close("")
	w.blank()
}

func (g *Generator) emitMethods(w *goWriter) {
	if g.Mod.Actions == nil {
		return
	}
	initActions := g.initialMixinActionNames()
	for name, act := range g.Mod.Actions.All() {
		if initActions[name] {
			continue
		}
		g.emitSomeAction(w, name, act)
	}
}

func (g *Generator) emitSomeAction(w *goWriter, name string, act goivy.Action) {
	sig, returnNames := g.methodSignature(name, act)
	w.open(sig + " {")
	g.pushScope()
	for _, p := range act.GetFormalParams() {
		g.addLocal(p.Name)
	}
	traceImportCaller := g.importCallers()[name]
	if traceImportCaller {
		g.emitTraceActionPrologue(w, name, act.GetFormalParams())
		if g.Config.Trace {
			w.line(`fmt.Fprintln(__ivy_out, "{")`)
		}
	}
	returns := act.GetFormalReturns()
	prevReturns := g.currentReturns
	g.currentReturns = returns
	for _, r := range returns {
		g.addLocal(r.Name)
		w.linef("%s := %s", goName(r.Name), g.goZeroValue(r.CSort))
	}
	g.emitAction(w, act)
	g.currentReturns = prevReturns
	if traceImportCaller && g.Config.Trace {
		w.line(`fmt.Fprintln(__ivy_out, "}")`)
	}
	if len(returnNames) > 0 {
		w.linef("return %s", strings.Join(returnNames, ", "))
	}
	g.popScope()
	w.close("")
	w.blank()
}

// importCallers mirrors Python find_import_callers through the ivy2cpp port.
// For target=test, unscoped imports named as known actions get a callback
// trace prologue at the top of the corresponding action body.
func (g *Generator) importCallers() map[string]bool {
	if g.importCallersCache != nil {
		return g.importCallersCache
	}
	out := map[string]bool{}
	if g.Config.Target == "test" && g.Mod != nil && g.Mod.Actions != nil {
		for _, imp := range g.Mod.Imports {
			impDef, ok := imp.(*goivy.ImportDef)
			if !ok {
				continue
			}
			if atom, ok := impDef.Scope.(*goivy.Atom); ok && atom.Relname() != "" {
				continue
			}
			name := ""
			if atom, ok := impDef.Imported.(*goivy.Atom); ok {
				name = atom.Relname()
			}
			if name == "" {
				continue
			}
			if _, ok := g.Mod.Actions.Get2(name); !ok {
				continue
			}
			caller := name
			if strings.HasPrefix(caller, "imp__") {
				caller = strings.TrimPrefix(caller, "imp__")
			} else {
				caller = strings.TrimPrefix(caller, "ext:")
			}
			out["ext:"+caller] = true
			out[caller] = true
		}
	}
	g.importCallersCache = out
	return out
}

func (g *Generator) isTestImportCallback(name string) bool {
	if g == nil || g.Config.Target != "test" {
		return false
	}
	return g.importCallers()[name]
}

