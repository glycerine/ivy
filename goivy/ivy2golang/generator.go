func (g *Generator) emitGenRandomizeSymbol(w *goWriter, sym stateSymbol, label string) {
	if g.isVariantSuperName(sortName(sym.Sort)) {
		expr, err := g.goActionParamRandomValueExpr(sym.Sort, label+"."+sym.Name, 0)
		if err != nil {
			g.unsupported(w, "%s", err.Error())
			return
		}
		w.linef("ivy.%s = %s", goName(sym.Name), expr)
		return
	}
	if fs, ok := sym.Sort.(*goivy.LogicFunctionSort); ok && len(fs.Domain()) > 0 {
		if !g.canEnumerateDomain(fs.Domain()) {
			base := "ivy." + goName(sym.Name)
			w.linef("%s = %s", base, g.goFunctionStorageInit(fs.Domain(), fs.Range()))
			g.emitNondetThunkBase(w, base, fs.Domain(), fs.Range(), label, 0)
			return
		}
		g.emitDomainLoops(w, fs.Domain(), func(args []string) {
			expr, err := g.goActionParamRandomValueExpr(fs.Range(), label+"."+sym.Name, int64(len(args)))
			if err != nil {
				g.unsupported(w, "%s", err.Error())
				return
			}
			w.linef("%s = %s", g.goStorageAccess(sym.Name, sym.Sort, args, "ivy"), expr)
		})
		return
	}
	expr, err := g.goActionParamRandomValueExpr(sym.Sort, label+"."+sym.Name, 0)
	if err != nil {
		g.unsupported(w, "%s", err.Error())
		return
	}
	w.linef("ivy.%s = %s", goName(sym.Name), expr)
}

type genDefinedInput struct {
	lhs   goivy.Expr
	value goivy.Expr
	loc   goivy.Location
}

type actionGeneratorVariantWitness struct {
	lhs   goivy.Expr
	rhs   goivy.Expr
	super goivy.Sort
	sub   goivy.Sort
	loc   goivy.Location
}

func (g *Generator) emitGenActionGeneratorDefinedInputs(w *goWriter, name string, act goivy.Action) {
	defs := g.genActionGeneratorDefinedInputs(act, g.genActionPreconditionFormulas(name, act))
	if len(defs) == 0 {
		return
	}
	g.pushExprOverrides(genActionFormalExprOverrides(act))
	defer g.popExprOverrides()
	for _, def := range defs {
		lhs, err := g.emitExpr(def.lhs)
		if err != nil {
			g.unsupportedAt(w, def.loc, "unsupported action generator defined input: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
			continue
		}
		expr, err := g.emitExpr(def.value)
		if err != nil {
			g.unsupportedAt(w, def.loc, "unsupported action generator defined input: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
			continue
		}
		if call, ok, err := g.goStorageSet(def.lhs, expr); ok || err != nil {
			if err != nil {
				g.unsupportedAt(w, def.loc, "unsupported action generator defined input: %s", strings.TrimPrefix(err.Error(), "ivy2golang: "))
				continue
			}
			w.line(call)
			continue
		}
		w.linef("%s = %s", lhs, expr)
	}
}

func (g *Generator) genActionGeneratorDefinedInputs(act goivy.Action, guards []goivy.Expr) []genDefinedInput {
	params := genActionFormalParamMap(act)
	if len(params) == 0 {
		return nil
	}
	var defs []genDefinedInput
	for _, guard := range guards {
		defs = g.collectGenActionGeneratorDefinedInputs(defs, guard, params)
	}
	return orderGenDefinedInputs(defs)
}

func (g *Generator) collectGenActionGeneratorDefinedInputs(defs []genDefinedInput, guard goivy.Expr, params map[string]*goivy.Const) []genDefinedInput {
	switch n := guard.(type) {
	case *goivy.LogicAnd:
		for _, term := range n.Terms {
			defs = g.collectGenActionGeneratorDefinedInputs(defs, term, params)
		}
		return defs
	}
	t1, t2, ok := actionGeneratorEqTerms(guard)
	if !ok {
		return defs
	}
	loc := guard.GetLineno()
	if g.genExprDefinedInputLHS(t1, params) {
		return append(defs, genDefinedInput{lhs: t1, value: t2, loc: loc})
	}
	if g.genExprDefinedInputLHS(t2, params) {
		return append(defs, genDefinedInput{lhs: t2, value: t1, loc: loc})
	}
	return defs
}

