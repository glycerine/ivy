func (g *Generator) reverseImageActionPreconditionFormulasOK(act goivy.Action) (guards []goivy.Expr, ok bool) {
	defer func() {
		if recover() != nil {
			guards = nil
			ok = false
		}
	}()
	if g == nil || g.Mod == nil || act == nil {
		return nil, true
	}
	upd := goivy.GetUpdateForArt(act, g.Mod, nil)
	if upd == nil {
		return nil, false
	}
	pre := goivy.ReverseImage(goivy.TrueClauses(nil), goivy.TrueClauses(nil), upd)
	pre = goivy.TrimClauses(pre)
	pre, ok = inlinePreimageClauseDefinitions(pre)
	if !ok {
		return nil, false
	}
	if pre == nil || pre.IsTrue() {
		return nil, true
	}
	f := pre.ToFormula()
	if f == nil || goivy.IsTrue(f) {
		return nil, true
	}
	if g.reverseImageGuardHasLocalSymbol(f, act) {
		return nil, false
	}
	return []goivy.Expr{f}, true
}

func (g *Generator) reverseImageGuardHasLocalSymbol(expr goivy.Expr, act goivy.Action) bool {
	if g == nil || g.Mod == nil || g.Mod.Sig == nil || expr == nil {
		return false
	}
	allowed := map[string]bool{}
	if act != nil {
		for _, p := range act.GetFormalParams() {
			if p == nil {
				continue
			}
			for _, name := range formalExprOverrideNames(p.Name) {
				allowed[name] = true
			}
		}
	}
	for _, sym := range goivy.UsedSymbolsAst(expr).All() {
		c, ok := sym.(*goivy.Const)
		if !ok || c == nil {
			continue
		}
		if allowed[c.Name] {
			continue
		}
		if g.Mod.Sig.ContainsSymbol(c.Name, c.CSort) {
			continue
		}
		if g.Mod.Sig.Constructors[c.Name] {
			continue
		}
		name, err := goivy.SolverName(c, g.Mod.Sig, nil)
		if err == nil && name != "" {
			return true
		}
	}
	return false
}

type preimageInlineDefinition struct {
	fn     *goivy.Const
	params []*goivy.LogicVariable
	rhs    goivy.Expr
}

func inlinePreimageClauseDefinitions(pre *goivy.Clauses) (*goivy.Clauses, bool) {
	if pre == nil || len(pre.Defs) == 0 {
		return pre, true
	}
	defs := make(map[goivy.NodeKey]preimageInlineDefinition, len(pre.Defs))
	for _, def := range pre.Defs {
		if def == nil {
			continue
		}
		app, ok := def.Lhs.(*goivy.Apply)
		if !ok {
			return nil, false
		}
		fn, ok := app.Func.(*goivy.Const)
		if !ok || fn == nil {
			return nil, false
		}
		params := make([]*goivy.LogicVariable, len(app.Terms))
		for i, term := range app.Terms {
			v, ok := term.(*goivy.LogicVariable)
			if !ok || v == nil {
				return nil, false
			}
			params[i] = v
		}
		defs[goivy.Key(fn)] = preimageInlineDefinition{fn: fn, params: params, rhs: def.Rhs}
	}
	fmlas := make([]goivy.Expr, 0, len(pre.Fmlas))
	for _, f := range pre.Fmlas {
		inlined, ok := inlinePreimageDefinitionExpr(f, defs)
		if !ok {
			return nil, false
		}
		fmlas = append(fmlas, inlined)
	}
	return goivy.NewClauses(fmlas, nil, pre.Annot), true
}

func inlinePreimageDefinitionExpr(expr goivy.Expr, defs map[goivy.NodeKey]preimageInlineDefinition) (goivy.Expr, bool) {
	switch n := expr.(type) {
	case nil, *goivy.Const, *goivy.LogicVariable:
		return expr, true
	case *goivy.Apply:
		terms := make([]goivy.Expr, len(n.Terms))
		for i, term := range n.Terms {
			inlined, ok := inlinePreimageDefinitionExpr(term, defs)
			if !ok {
				return nil, false
			}
			terms[i] = inlined
		}
		if fn, ok := n.Func.(*goivy.Const); ok && fn != nil {
			if def, ok := defs[goivy.Key(fn)]; ok {
				if len(def.params) != len(terms) {
					return nil, false
				}
				subs := map[goivy.NodeKey]goivy.Expr{}
				for i, p := range def.params {
					subs[goivy.Key(p)] = terms[i]
				}
				repl, err := goivy.Substitute(def.rhs, subs)
				if err != nil {
					return nil, false
				}
				return inlinePreimageDefinitionExpr(repl, defs)
			}
		}
		app, err := goivy.NewApply(n.Func, terms...)
		if err != nil {
			return nil, false
		}
		return app, true
	case *goivy.Eq:
		t1, ok := inlinePreimageDefinitionExpr(n.T1, defs)
		if !ok {
			return nil, false
		}
		t2, ok := inlinePreimageDefinitionExpr(n.T2, defs)
		if !ok {
			return nil, false
		}
		eq, err := goivy.NewEq(t1, t2)
		return eq, err == nil
	case *goivy.LogicNot:
		body, ok := inlinePreimageDefinitionExpr(n.Body, defs)
		if !ok {
			return nil, false
		}
		not, err := goivy.NewNot(body)
		return not, err == nil
	case *goivy.LogicLiteral:
		atom, ok := inlinePreimageDefinitionExpr(n.Atom, defs)
		if !ok {
			return nil, false
		}
		return &goivy.LogicLiteral{Atom: atom, Polarity: n.Polarity}, true
	case *goivy.LogicAnd:
		terms, ok := inlinePreimageDefinitionExprs(n.Terms, defs)
		if !ok {
			return nil, false
		}
		and, err := goivy.NewAnd(terms...)
		return and, err == nil
	case *goivy.LogicOr:
		terms, ok := inlinePreimageDefinitionExprs(n.Terms, defs)
		if !ok {
			return nil, false
		}
		or, err := goivy.NewOr(terms...)
		return or, err == nil
	case *goivy.LogicImplies:
		t1, ok := inlinePreimageDefinitionExpr(n.T1, defs)
		if !ok {
			return nil, false
		}
		t2, ok := inlinePreimageDefinitionExpr(n.T2, defs)
		if !ok {
			return nil, false
		}
		impl, err := goivy.NewImplies(t1, t2)
		return impl, err == nil
	case *goivy.LogicIff:
		t1, ok := inlinePreimageDefinitionExpr(n.T1, defs)
		if !ok {
			return nil, false
		}
		t2, ok := inlinePreimageDefinitionExpr(n.T2, defs)
		if !ok {
			return nil, false
		}
		iff, err := goivy.NewIff(t1, t2)
		return iff, err == nil
	case *goivy.LogicIte:
		cond, ok := inlinePreimageDefinitionExpr(n.Cond, defs)
		if !ok {
			return nil, false
		}
		thenExpr, ok := inlinePreimageDefinitionExpr(n.Then, defs)
		if !ok {
			return nil, false
		}
		elseExpr, ok := inlinePreimageDefinitionExpr(n.Else, defs)
		if !ok {
			return nil, false
		}
		ite, err := goivy.NewIte(cond, thenExpr, elseExpr)
		return ite, err == nil
	case *goivy.ForAll:
		body, ok := inlinePreimageDefinitionExpr(n.Body, defs)
		if !ok {
			return nil, false
		}
		return goivy.IvyForAll(n.Variables, body), true
	case *goivy.LogicExists:
		body, ok := inlinePreimageDefinitionExpr(n.Body, defs)
		if !ok {
			return nil, false
		}
		return goivy.IvyExists(n.Variables, body), true
	default:
		return expr, true
	}
}

func inlinePreimageDefinitionExprs(exprs []goivy.Expr, defs map[goivy.NodeKey]preimageInlineDefinition) ([]goivy.Expr, bool) {
	out := make([]goivy.Expr, len(exprs))
	for i, expr := range exprs {
		inlined, ok := inlinePreimageDefinitionExpr(expr, defs)
		if !ok {
			return nil, false
		}
		out[i] = inlined
	}
	return out, true
}

type actionPreimageContext struct {
	subs        map[goivy.NodeKey]goivy.Expr
	choiceSubs  map[goivy.NodeKey][]goivy.Expr
	pointUpdate map[goivy.NodeKey][]preimagePointUpdate
	localAlias  map[goivy.NodeKey]bool
}

type preimagePointUpdate struct {
	fn    *goivy.Const
	args  []goivy.Expr
	value goivy.Expr
	guard goivy.Expr
}

func newActionPreimageContext() *actionPreimageContext {
	return &actionPreimageContext{
		subs:        map[goivy.NodeKey]goivy.Expr{},
		choiceSubs:  map[goivy.NodeKey][]goivy.Expr{},
		pointUpdate: map[goivy.NodeKey][]preimagePointUpdate{},
		localAlias:  map[goivy.NodeKey]bool{},
	}
}

func (ctx *actionPreimageContext) copy() *actionPreimageContext {
	if ctx == nil {
		return newActionPreimageContext()
	}
	out := newActionPreimageContext()
	for key, value := range ctx.subs {
		out.subs[key] = value
	}
	for key, values := range ctx.choiceSubs {
		out.choiceSubs[key] = append([]goivy.Expr(nil), values...)
	}
	for key, updates := range ctx.pointUpdate {
		out.pointUpdate[key] = append([]preimagePointUpdate(nil), updates...)
	}
	for key, value := range ctx.localAlias {
		out.localAlias[key] = value
	}
	return out
}

func (g *Generator) collectTestActionPrefixPreimageAssumeFormulas(act goivy.Action, ctx *actionPreimageContext, seen map[string]bool) ([]goivy.Expr, bool) {
	if ctx == nil {
		ctx = newActionPreimageContext()
	}
	switch a := act.(type) {
	case *goivy.LogicAssumeAction:
		if a.Formula == nil {
			return nil, true
		}
		guard, ok := g.substituteExprForPreimage(a.Formula, ctx)
		if !ok {
			return nil, false
		}
		return []goivy.Expr{guard}, true
	case *goivy.LogicSequence:
		var guards []goivy.Expr
		for _, elem := range a.Elems {
			child, ok := elem.(goivy.Action)
			if !ok {
				return guards, false
			}
			childGuards, ok := g.collectTestActionPrefixPreimageAssumeFormulas(child, ctx, seen)
			if !ok {
				return guards, false
			}
			guards = append(guards, childGuards...)
		}
		return guards, true
	case *goivy.LogicAssertAction:
		return nil, true
	case *goivy.LogicAssignAction:
		return nil, g.recordSimplePreimageAssign(a, ctx)
	case *goivy.LogicSetAction:
		if a.Lit == nil {
			return nil, false
		}
		target, value := setTargetAndValue(a.Lit)
		return nil, g.recordSimplePreimageAssign(goivy.NewAssignAction(target, goivy.NewConst(value, goivy.Boolean)), ctx)
	case *goivy.LogicIfAction:
		guards, ok := g.conditionalPreimageAssumeGuards(a, ctx, seen)
		return guards, ok
	case *goivy.LogicChoiceAction:
		return g.choicePreimageAssumeGuards(a, ctx, seen)
	case *goivy.LogicEnvAction:
		return g.choicePreimageAssumeGuards(&a.LogicChoiceAction, ctx, seen)
	case *goivy.LogicCallAction:
		return g.callPreimageAssumeGuards(a, ctx, seen)
	case *goivy.LogicLocalAction:
		return g.localPreimageAssumeGuardsSeen(a, ctx, seen)
	default:
		return nil, false
	}
}

func (g *Generator) localPreimageAssumeGuards(a *goivy.LogicLocalAction, ctx *actionPreimageContext) ([]goivy.Expr, bool) {
	return g.localPreimageAssumeGuardsSeen(a, ctx, map[string]bool{})
}

func (g *Generator) localPreimageAssumeGuardsSeen(a *goivy.LogicLocalAction, ctx *actionPreimageContext, seen map[string]bool) ([]goivy.Expr, bool) {
	if a == nil || a.Body == nil {
		return nil, false
	}
	body, ok := a.Body.(goivy.Action)
	if !ok {
		return nil, false
	}
	localNames := map[string]bool{}
	localKeys := map[goivy.NodeKey]bool{}
	previousLocal := map[goivy.NodeKey]bool{}
	previousLocalHad := map[goivy.NodeKey]bool{}
	previousSub := map[goivy.NodeKey]goivy.Expr{}
	previousSubHad := map[goivy.NodeKey]bool{}
	for _, local := range a.Locals {
		if name := goivy.ExprName(local); name != "" {
			localNames[name] = true
		}
		key := goivy.Key(local)
		localKeys[key] = true
		previousLocal[key], previousLocalHad[key] = ctx.localAlias[key]
		previousSub[key], previousSubHad[key] = ctx.subs[key]
		ctx.localAlias[key] = true
	}
	defer func() {
		for key := range localKeys {
			if previousLocalHad[key] {
				ctx.localAlias[key] = previousLocal[key]
			} else {
				delete(ctx.localAlias, key)
			}
			if previousSubHad[key] {
				ctx.subs[key] = previousSub[key]
			} else {
				delete(ctx.subs, key)
			}
		}
	}()
	guards, ok := g.collectTestActionPrefixPreimageAssumeFormulas(body, ctx, seen)
	if !ok {
		return nil, false
	}
	for _, guard := range guards {
		if exprReferencesAnyName(guard, localNames) {
			return nil, false
		}
	}
	if preimageContextReferencesAnyName(ctx, localNames, localKeys) {
		return nil, false
	}
	return guards, true
}

func preimageContextReferencesAnyName(ctx *actionPreimageContext, names map[string]bool, localKeys map[goivy.NodeKey]bool) bool {
	if ctx == nil || len(names) == 0 {
		return false
	}
	for key, expr := range ctx.subs {
		if localKeys[key] {
			continue
		}
		if exprReferencesAnyName(expr, names) {
			return true
		}
	}
	for _, updates := range ctx.pointUpdate {
		for _, update := range updates {
			for _, arg := range update.args {
				if exprReferencesAnyName(arg, names) {
					return true
				}
			}
			if exprReferencesAnyName(update.value, names) || exprReferencesAnyName(update.guard, names) {
				return true
			}
		}
	}
	for key, values := range ctx.choiceSubs {
		if localKeys[key] {
			continue
		}
		for _, value := range values {
			if exprReferencesAnyName(value, names) {
				return true
			}
		}
	}
	return false
}

func exprReferencesAnyName(expr goivy.Expr, names map[string]bool) bool {
	if expr == nil || len(names) == 0 {
		return false
	}
	for _, sym := range goivy.UsedSymbolsAst(expr).All() {
		if names[goivy.ExprName(sym)] {
			return true
		}
	}
	return false
}

func exprReferencesAnyNameIncludingVariables(expr goivy.Expr, names map[string]bool) bool {
	if expr == nil || len(names) == 0 {
		return false
	}
	switch n := expr.(type) {
	case *goivy.Const:
		return names[n.Name]
	case *goivy.LogicVariable:
		return names[n.Name]
	}
	for _, child := range expr.Children() {
		if exprReferencesAnyNameIncludingVariables(child, names) {
			return true
		}
	}
	return false
}

func exprContainsLogicVariable(expr goivy.Expr) bool {
	if expr == nil {
		return false
	}
	if _, ok := expr.(*goivy.LogicVariable); ok {
		return true
	}
	for _, child := range expr.Children() {
		if exprContainsLogicVariable(child) {
			return true
		}
	}
	return false
}

func (g *Generator) choicePreimageAssumeGuards(a *goivy.LogicChoiceAction, ctx *actionPreimageContext, seen map[string]bool) ([]goivy.Expr, bool) {
	if a == nil || len(a.Branches) == 0 {
		return nil, true
	}
	baseCtx := ctx.copy()
	var branchTerms []goivy.Expr
	var branchCtxs []*actionPreimageContext
	for _, branch := range a.Branches {
		branchAct, ok := goivy.ToAction(branch)
		if !ok {
			return nil, false
		}
		branchCtx := baseCtx.copy()
		guards, ok := g.collectTestActionPrefixPreimageAssumeFormulas(branchAct, branchCtx, seen)
		if !ok {
			return nil, false
		}
		term, ok := preimageGuardConjunction(guards)
		if !ok {
			return nil, false
		}
		branchCtxs = append(branchCtxs, branchCtx)
		if goivy.IsTrue(term) {
			continue
		}
		branchTerms = append(branchTerms, term)
	}
	contextsEqual := true
	for _, branchCtx := range branchCtxs {
		if !preimageContextsEqual(baseCtx, branchCtx) {
			contextsEqual = false
			break
		}
	}
	if len(branchTerms) == 0 {
		if contextsEqual {
			return nil, true
		}
		return nil, g.mergeChoicePreimageSubstitutions(baseCtx, branchCtxs, ctx)
	}
	if !contextsEqual {
		return nil, false
	}
	if len(branchTerms) == 1 {
		return []goivy.Expr{branchTerms[0]}, true
	}
	or, err := goivy.NewOr(branchTerms...)
	if err != nil {
		return nil, false
	}
	return []goivy.Expr{or}, true
}

func (g *Generator) mergeChoicePreimageSubstitutions(baseCtx *actionPreimageContext, branchCtxs []*actionPreimageContext, out *actionPreimageContext) bool {
	if g == nil || baseCtx == nil || out == nil || len(branchCtxs) == 0 {
		return false
	}
	stateConsts := g.preimageStateConstsByKey()
	keys := map[goivy.NodeKey]bool{}
	for _, branchCtx := range branchCtxs {
		if branchCtx == nil {
			return false
		}
		if !preimagePointUpdateMapsEqual(baseCtx.pointUpdate, branchCtx.pointUpdate) || !preimageLocalAliasMapsEqual(baseCtx.localAlias, branchCtx.localAlias) || len(branchCtx.choiceSubs) != len(baseCtx.choiceSubs) {
			return false
		}
		for key := range branchCtx.choiceSubs {
			if !preimageExprSlicesEqual(baseCtx.choiceSubs[key], branchCtx.choiceSubs[key]) {
				return false
			}
		}
		for key := range branchCtx.subs {
			if stateConsts[key] != nil && !exprEqual(branchCtx.subs[key], baseCtx.subs[key]) {
				keys[key] = true
			}
		}
		for key := range baseCtx.subs {
			if stateConsts[key] != nil && !exprEqual(branchCtx.subs[key], baseCtx.subs[key]) {
				keys[key] = true
			}
		}
	}
	for key := range keys {
		state := stateConsts[key]
		if state == nil {
			return false
		}
		var values []goivy.Expr
		allSame := true
		var first goivy.Expr
		for i, branchCtx := range branchCtxs {
			value := branchCtx.subs[key]
			if value == nil {
				value = baseCtx.subs[key]
			}
			if value == nil {
				value = state
			}
			values = append(values, value)
			if i == 0 {
				first = value
			} else if !exprEqual(first, value) {
				allSame = false
			}
		}
		if allSame {
			if exprEqual(first, state) && baseCtx.subs[key] == nil {
				delete(out.subs, key)
			} else {
				out.subs[key] = first
			}
			delete(out.choiceSubs, key)
			continue
		}
		delete(out.subs, key)
		out.choiceSubs[key] = values
	}
	return true
}

func preimagePointUpdateMapsEqual(a, b map[goivy.NodeKey][]preimagePointUpdate) bool {
	if len(a) != len(b) {
		return false
	}
	for key, av := range a {
		bv, ok := b[key]
		if !ok || len(av) != len(bv) {
			return false
		}
		for i := range av {
			if !preimagePointUpdatesEqual(av[i], bv[i]) {
				return false
			}
		}
	}
	return true
}

func preimageLocalAliasMapsEqual(a, b map[goivy.NodeKey]bool) bool {
	if len(a) != len(b) {
		return false
	}
	for key, av := range a {
		if b[key] != av {
			return false
		}
	}
	return true
}

func preimageExprSlicesEqual(a, b []goivy.Expr) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if !exprEqual(a[i], b[i]) {
			return false
		}
	}
	return true
}

func preimageGuardConjunction(guards []goivy.Expr) (goivy.Expr, bool) {
	switch len(guards) {
	case 0:
		return goivy.True, true
	case 1:
		return guards[0], true
	default:
		and, err := goivy.NewAnd(guards...)
		if err != nil {
			return nil, false
		}
		return and, true
	}
}

func preimageContextsEqual(a, b *actionPreimageContext) bool {
	if a == nil || b == nil {
		return a == b
	}
	if len(a.subs) != len(b.subs) || len(a.pointUpdate) != len(b.pointUpdate) || len(a.localAlias) != len(b.localAlias) {
		return false
	}
	if len(a.choiceSubs) != len(b.choiceSubs) {
		return false
	}
	for key, av := range a.subs {
		if !exprEqual(av, b.subs[key]) {
			return false
		}
	}
	for key, av := range a.choiceSubs {
		if !preimageExprSlicesEqual(av, b.choiceSubs[key]) {
			return false
		}
	}
	for key, av := range a.localAlias {
		if b.localAlias[key] != av {
			return false
		}
	}
	for key, au := range a.pointUpdate {
		bu, ok := b.pointUpdate[key]
		if !ok || len(au) != len(bu) {
			return false
		}
		for i := range au {
			if !preimagePointUpdatesEqual(au[i], bu[i]) {
				return false
			}
		}
	}
	return true
}

func preimagePointUpdatesEqual(a, b preimagePointUpdate) bool {
	if (a.fn == nil) != (b.fn == nil) {
		return false
	}
	if a.fn != nil && goivy.Key(a.fn) != goivy.Key(b.fn) {
		return false
	}
	if len(a.args) != len(b.args) {
		return false
	}
	for i := range a.args {
		if !exprEqual(a.args[i], b.args[i]) {
			return false
		}
	}
	return exprEqual(a.value, b.value) && exprEqual(a.guard, b.guard)
}

func (g *Generator) callPreimageAssumeGuards(a *goivy.LogicCallAction, ctx *actionPreimageContext, seen map[string]bool) ([]goivy.Expr, bool) {
	name := ""
	if a != nil {
		name = a.CalleeName()
	}
	if name == "" || seen[name] {
		return nil, false
	}
	callee, formalSubs, ok := g.callPreimageCalleeAndSubstitutions(a, ctx)
	if !ok {
		return nil, false
	}
	previous := make(map[goivy.NodeKey]goivy.Expr, len(formalSubs))
	hadPrevious := make(map[goivy.NodeKey]bool, len(formalSubs))
	for key, value := range formalSubs {
		prev, had := ctx.subs[key]
		previous[key] = prev
		hadPrevious[key] = had
		ctx.subs[key] = value
	}
	seen[name] = true
	guards, ok := g.collectTestActionPrefixPreimageAssumeFormulas(callee, ctx, seen)
	delete(seen, name)
	for key := range formalSubs {
		if hadPrevious[key] {
			ctx.subs[key] = previous[key]
		} else {
			delete(ctx.subs, key)
		}
	}
	return guards, ok
}

func (g *Generator) callPreimageCalleeAndSubstitutions(a *goivy.LogicCallAction, ctx *actionPreimageContext) (goivy.Action, map[goivy.NodeKey]goivy.Expr, bool) {
	if g == nil || g.Mod == nil || g.Mod.Actions == nil || a == nil {
		return nil, nil, false
	}
	name := a.CalleeName()
	callee, ok := g.Mod.Actions.Get2(name)
	if !ok || callee == nil {
		return nil, nil, false
	}
	args := callArgs(a.Callee)
	formals := callee.GetFormalParams()
	returns := callee.GetFormalReturns()
	if len(args) != len(formals) || len(a.ActualReturns) != len(returns) {
		return nil, nil, false
	}
	formalSubs := map[goivy.NodeKey]goivy.Expr{}
	for i, formal := range formals {
		if formal == nil {
			return nil, nil, false
		}
		actual := args[i]
		if substituted, ok := g.substituteExprForPreimage(actual, ctx); ok {
			actual = substituted
		} else {
			return nil, nil, false
		}
		formalSubs[goivy.Key(formal)] = actual
	}
	for i, ret := range returns {
		if ret == nil {
			return nil, nil, false
		}
		formalSubs[goivy.Key(ret)] = a.ActualReturns[i]
	}
	return callee, formalSubs, true
}

func (g *Generator) transparentCallPreimageAssumeGuards(a *goivy.LogicCallAction, subs map[goivy.NodeKey]goivy.Expr) ([]goivy.Expr, bool) {
	if a == nil || !g.actionCallIsPreconditionOnly(a, map[string]bool{}) {
		return nil, false
	}
	name := a.CalleeName()
	callee, ok := g.Mod.Actions.Get2(name)
	if !ok || callee == nil {
		return nil, false
	}
	args := callArgs(a.Callee)
	formals := callee.GetFormalParams()
	if len(args) != len(formals) {
		return nil, false
	}
	formalSubs := map[goivy.NodeKey]goivy.Expr{}
	for i, formal := range formals {
		if formal == nil {
			return nil, false
		}
		actual := args[i]
		if len(subs) > 0 {
			substituted, err := goivy.Substitute(actual, subs)
			if err != nil {
				return nil, false
			}
			actual = substituted
		}
		formalSubs[goivy.Key(formal)] = actual
	}
	var guards []goivy.Expr
	for _, guard := range g.testActionPrefixPreimageAssumeFormulas(callee) {
		if guard == nil {
			continue
		}
		var err error
		if len(formalSubs) > 0 {
			guard, err = goivy.Substitute(guard, formalSubs)
			if err != nil {
				return nil, false
			}
		}
		tmpCtx := newActionPreimageContext()
		for key, value := range subs {
			tmpCtx.subs[key] = value
		}
		guard, ok = g.substituteExprForPreimage(guard, tmpCtx)
		if !ok {
			return nil, false
		}
		guards = append(guards, guard)
	}
	return guards, true
}

func (g *Generator) actionCallIsPreconditionOnly(a *goivy.LogicCallAction, seen map[string]bool) bool {
	if g == nil || g.Mod == nil || g.Mod.Actions == nil || a == nil {
		return false
	}
	if len(a.ActualReturns) > 0 {
		return false
	}
	name := a.CalleeName()
	if seen[name] {
		return false
	}
	callee, ok := g.Mod.Actions.Get2(name)
	if !ok || callee == nil || len(callee.GetFormalReturns()) > 0 {
		return false
	}
	seen[name] = true
	ok = g.preconditionOnlyActionForPreimage(callee, seen)
	delete(seen, name)
	return ok
}

func (g *Generator) preconditionOnlyActionForPreimage(act goivy.Action, seen map[string]bool) bool {
	switch a := act.(type) {
	case nil:
		return true
	case *goivy.LogicAssumeAction, *goivy.LogicAssertAction:
		return true
	case *goivy.LogicCallAction:
		return g.actionCallIsPreconditionOnly(a, seen)
	case *goivy.LogicLocalAction:
		_, ok := g.localPreimageAssumeGuards(a, nil)
		return ok
	case *goivy.LogicSequence:
		for _, elem := range a.Elems {
			child, ok := elem.(goivy.Action)
			if !ok || !g.preconditionOnlyActionForPreimage(child, seen) {
				return false
			}
		}
		return true
	case *goivy.LogicIfAction:
		if a.ThenBody != nil {
			thenAct, ok := goivy.ToAction(a.ThenBody)
			if !ok || !g.preconditionOnlyActionForPreimage(thenAct, seen) {
				return false
			}
		}
		if a.ElseBody != nil {
			elseAct, ok := goivy.ToAction(a.ElseBody)
			if !ok || !g.preconditionOnlyActionForPreimage(elseAct, seen) {
				return false
			}
		}
		return true
	default:
		return false
	}
}

func (g *Generator) conditionalPreimageAssumeGuards(a *goivy.LogicIfAction, ctx *actionPreimageContext, seen map[string]bool) ([]goivy.Expr, bool) {
	if a == nil || a.Cond == nil {
		return nil, false
	}
	cond, ok := g.substituteExprForPreimage(a.Cond, ctx)
	if !ok {
		return nil, false
	}
	baseCtx := ctx.copy()
	thenCtx := ctx.copy()
	elseCtx := ctx.copy()
	var guards []goivy.Expr
	if a.ThenBody != nil {
		thenAct, ok := goivy.ToAction(a.ThenBody)
		if !ok {
			return nil, false
		}
		thenGuards, ok := g.collectTestActionPrefixPreimageAssumeFormulas(thenAct, thenCtx, seen)
		if !ok {
			return nil, false
		}
		for _, guard := range thenGuards {
			impl, err := goivy.NewImplies(cond, guard)
			if err != nil {
				return nil, false
			}
			guards = append(guards, impl)
		}
	}
	if a.ElseBody != nil {
		elseAct, ok := goivy.ToAction(a.ElseBody)
		if !ok {
			return nil, false
		}
		notCond, err := goivy.NewNot(cond)
		if err != nil {
			return nil, false
		}
		elseGuards, ok := g.collectTestActionPrefixPreimageAssumeFormulas(elseAct, elseCtx, seen)
		if !ok {
			return nil, false
		}
		for _, guard := range elseGuards {
			impl, err := goivy.NewImplies(notCond, guard)
			if err != nil {
				return nil, false
			}
			guards = append(guards, impl)
		}
	}
	if !g.mergeConditionalPreimageSubstitutions(cond, baseCtx.subs, thenCtx.subs, elseCtx.subs, ctx.subs) {
		return nil, false
	}
	if !g.mergeConditionalPreimagePointUpdates(cond, baseCtx, thenCtx, elseCtx, ctx) {
		return nil, false
	}
	return guards, true
}

func (g *Generator) mergeConditionalPreimageSubstitutions(cond goivy.Expr, baseSubs, thenSubs, elseSubs, out map[goivy.NodeKey]goivy.Expr) bool {
	if cond == nil || out == nil {
		return false
	}
	stateConsts := g.preimageStateConstsByKey()
	keys := map[goivy.NodeKey]bool{}
	for key := range thenSubs {
		if stateConsts[key] != nil {
			keys[key] = true
		}
	}
	for key := range elseSubs {
		if stateConsts[key] != nil {
			keys[key] = true
		}
	}
	for key := range keys {
		state := stateConsts[key]
		oldValue := baseSubs[key]
		hadBase := oldValue != nil
		if oldValue == nil {
			oldValue = state
		}
		thenValue := thenSubs[key]
		if thenValue == nil {
			thenValue = oldValue
		}
		elseValue := elseSubs[key]
		if elseValue == nil {
			elseValue = oldValue
		}
		if exprEqual(thenValue, elseValue) {
			if hadBase || !exprEqual(thenValue, state) {
				out[key] = thenValue
			}
			continue
		}
		ite, err := goivy.NewIte(cond, thenValue, elseValue)
		if err != nil {
			return false
		}
		out[key] = ite
	}
	return true
}

func (g *Generator) preimageStateConstsByKey() map[goivy.NodeKey]*goivy.Const {
	out := map[goivy.NodeKey]*goivy.Const{}
	for _, sym := range g.stateSymbols() {
		c := goivy.NewConst(sym.Name, sym.Sort)
		out[goivy.Key(c)] = c
	}
	return out
}

func exprEqual(a, b goivy.Expr) bool {
	if a == nil || b == nil {
		return a == b
	}
	return a.Equal(b)
}

func (g *Generator) mergeConditionalPreimagePointUpdates(cond goivy.Expr, baseCtx, thenCtx, elseCtx, out *actionPreimageContext) bool {
	if cond == nil || baseCtx == nil || thenCtx == nil || elseCtx == nil || out == nil {
		return false
	}
	notCond, err := goivy.NewNot(cond)
	if err != nil {
		return false
	}
	appendBranchUpdates := func(branchCtx *actionPreimageContext, guard goivy.Expr) {
		for key, updates := range branchCtx.pointUpdate {
			baseLen := len(baseCtx.pointUpdate[key])
			if len(updates) <= baseLen {
				continue
			}
			for _, update := range updates[baseLen:] {
				update.guard = guard
				out.pointUpdate[key] = append(out.pointUpdate[key], update)
			}
		}
	}
	appendBranchUpdates(thenCtx, cond)
	appendBranchUpdates(elseCtx, notCond)
	return true
}

func (g *Generator) substituteExprForPreimage(expr goivy.Expr, ctx *actionPreimageContext) (goivy.Expr, bool) {
	if expr == nil {
		return nil, true
	}
	if ctx == nil {
		return expr, true
	}
	if len(ctx.subs) > 0 {
		substituted, err := goivy.Substitute(expr, ctx.subs)
		if err != nil {
			return nil, false
		}
		expr = substituted
	}
	if len(ctx.choiceSubs) > 0 {
		expanded, ok := expandChoiceSubstitutionsForPreimage(expr, ctx.choiceSubs)
		if !ok {
			return nil, false
		}
		expr = expanded
	}
	if len(ctx.pointUpdate) == 0 {
		return expr, true
	}
	rewritten, err := g.rewritePointUpdatesForPreimage(expr, ctx)
	if err != nil {
		return nil, false
	}
	return rewritten, true
}

func expandChoiceSubstitutionsForPreimage(expr goivy.Expr, choices map[goivy.NodeKey][]goivy.Expr) (goivy.Expr, bool) {
	if expr == nil || len(choices) == 0 {
		return expr, true
	}
	used := goivy.UsedSymbolsAst(expr)
	var chosen goivy.NodeKey
	found := false
	for key, values := range choices {
		if len(values) == 0 {
			return nil, false
		}
		if _, ok := used.Get2(key); ok {
			chosen = key
			found = true
			break
		}
	}
	if !found {
		return expr, true
	}
	nextChoices := make(map[goivy.NodeKey][]goivy.Expr, len(choices)-1)
	for key, values := range choices {
		if key == chosen {
			continue
		}
		nextChoices[key] = values
	}
	var terms []goivy.Expr
	for _, value := range choices[chosen] {
		substituted, err := goivy.Substitute(expr, map[goivy.NodeKey]goivy.Expr{chosen: value})
		if err != nil {
			return nil, false
		}
		expanded, ok := expandChoiceSubstitutionsForPreimage(substituted, nextChoices)
		if !ok {
			return nil, false
		}
		terms = append(terms, expanded)
	}
	if len(terms) == 1 {
		return terms[0], true
	}
	or, err := goivy.NewOr(terms...)
	if err != nil {
		return nil, false
	}
	return or, true
}

func (g *Generator) rewritePointUpdatesForPreimage(expr goivy.Expr, ctx *actionPreimageContext) (goivy.Expr, error) {
	switch n := expr.(type) {
	case nil, *goivy.Const, *goivy.LogicVariable:
		return expr, nil
	case *goivy.Apply:
		terms := make([]goivy.Expr, len(n.Terms))
		for i, term := range n.Terms {
			rewritten, err := g.rewritePointUpdatesForPreimage(term, ctx)
			if err != nil {
				return nil, err
			}
			terms[i] = rewritten
		}
		rewrittenApply, err := goivy.NewApply(n.Func, terms...)
		if err != nil {
			return nil, err
		}
		var rewritten goivy.Expr = rewrittenApply
		fn, ok := n.Func.(*goivy.Const)
		if !ok {
			return rewritten, nil
		}
		for _, update := range ctx.pointUpdate[goivy.Key(fn)] {
			var conds []goivy.Expr
			if len(terms) != len(update.args) {
				return nil, fmt.Errorf("point update arity mismatch for %s", fn.Name)
			}
			for i := range terms {
				eq, err := goivy.NewEq(terms[i], update.args[i])
				if err != nil {
					return nil, err
				}
				conds = append(conds, eq)
			}
			var cond goivy.Expr = goivy.True
			if len(conds) == 1 {
				cond = conds[0]
			} else if len(conds) > 1 {
				and, err := goivy.NewAnd(conds...)
				if err != nil {
					return nil, err
				}
				cond = and
			}
			cellUpdate, err := goivy.NewIte(cond, update.value, rewritten)
			if err != nil {
				return nil, err
			}
			if update.guard != nil {
				rewritten, err = goivy.NewIte(update.guard, cellUpdate, rewritten)
				if err != nil {
					return nil, err
				}
				continue
			}
			rewritten = cellUpdate
		}
		return rewritten, nil
	case *goivy.Eq:
		t1, err := g.rewritePointUpdatesForPreimage(n.T1, ctx)
		if err != nil {
			return nil, err
		}
		t2, err := g.rewritePointUpdatesForPreimage(n.T2, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.NewEq(t1, t2)
	case *goivy.LogicNot:
		body, err := g.rewritePointUpdatesForPreimage(n.Body, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.NewNot(body)
	case *goivy.LogicLiteral:
		atom, err := g.rewritePointUpdatesForPreimage(n.Atom, ctx)
		if err != nil {
			return nil, err
		}
		return &goivy.LogicLiteral{Atom: atom, Polarity: n.Polarity}, nil
	case *goivy.LogicAnd:
		terms := make([]goivy.Expr, len(n.Terms))
		for i, term := range n.Terms {
			rewritten, err := g.rewritePointUpdatesForPreimage(term, ctx)
			if err != nil {
				return nil, err
			}
			terms[i] = rewritten
		}
		return goivy.NewAnd(terms...)
	case *goivy.LogicOr:
		terms := make([]goivy.Expr, len(n.Terms))
		for i, term := range n.Terms {
			rewritten, err := g.rewritePointUpdatesForPreimage(term, ctx)
			if err != nil {
				return nil, err
			}
			terms[i] = rewritten
		}
		return goivy.NewOr(terms...)
	case *goivy.LogicImplies:
		t1, err := g.rewritePointUpdatesForPreimage(n.T1, ctx)
		if err != nil {
			return nil, err
		}
		t2, err := g.rewritePointUpdatesForPreimage(n.T2, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.NewImplies(t1, t2)
	case *goivy.LogicIff:
		t1, err := g.rewritePointUpdatesForPreimage(n.T1, ctx)
		if err != nil {
			return nil, err
		}
		t2, err := g.rewritePointUpdatesForPreimage(n.T2, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.NewIff(t1, t2)
	case *goivy.LogicIte:
		cond, err := g.rewritePointUpdatesForPreimage(n.Cond, ctx)
		if err != nil {
			return nil, err
		}
		thenExpr, err := g.rewritePointUpdatesForPreimage(n.Then, ctx)
		if err != nil {
			return nil, err
		}
		elseExpr, err := g.rewritePointUpdatesForPreimage(n.Else, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.NewIte(cond, thenExpr, elseExpr)
	case *goivy.ForAll:
		body, err := g.rewritePointUpdatesForPreimage(n.Body, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.IvyForAll(n.Variables, body), nil
	case *goivy.LogicExists:
		body, err := g.rewritePointUpdatesForPreimage(n.Body, ctx)
		if err != nil {
			return nil, err
		}
		return goivy.IvyExists(n.Variables, body), nil
	default:
		return expr, nil
	}
}

func preconditionOnlyAction(act goivy.Action) bool {
	switch a := act.(type) {
	case nil:
		return true
	case *goivy.LogicAssumeAction, *goivy.LogicAssertAction:
		return true
	case *goivy.LogicSequence:
		for _, elem := range a.Elems {
			child, ok := elem.(goivy.Action)
			if !ok || !preconditionOnlyAction(child) {
				return false
			}
		}
		return true
	case *goivy.LogicIfAction:
		if a.ThenBody != nil {
			thenAct, ok := goivy.ToAction(a.ThenBody)
			if !ok || !preconditionOnlyAction(thenAct) {
				return false
			}
		}
		if a.ElseBody != nil {
			elseAct, ok := goivy.ToAction(a.ElseBody)
			if !ok || !preconditionOnlyAction(elseAct) {
				return false
			}
		}
		return true
	default:
		return false
	}
}

func (g *Generator) recordSimplePreimageAssign(a *goivy.LogicAssignAction, ctx *actionPreimageContext) bool {
	if a == nil || a.LHS == nil || a.RHS == nil || ctx == nil {
		return false
	}
	if g.recordPointPreimageAssign(a, ctx) {
		return true
	}
	lhsExpr := a.LHS
	if lhsConst, ok := lhsExpr.(*goivy.Const); ok {
		if _, isState := g.isStateSymbolName(lhsConst.Name); !isState {
			if repl, ok := ctx.subs[goivy.Key(lhsConst)]; ok {
				lhsExpr = repl
			} else if ctx.localAlias[goivy.Key(lhsConst)] {
				rhs, ok := g.substituteExprForPreimage(a.RHS, ctx)
				if !ok {
					return false
				}
				ctx.subs[goivy.Key(lhsConst)] = rhs
				return true
			}
		}
	}
	lhs, ok := lhsExpr.(*goivy.Const)
	if !ok {
		return false
	}
	if _, ok := g.isStateSymbolName(lhs.Name); !ok {
		return false
	}
	rhs, ok := g.substituteExprForPreimage(a.RHS, ctx)
	if !ok {
		return false
	}
	ctx.subs[goivy.Key(lhs)] = rhs
	return true
}

func (g *Generator) recordPointPreimageAssign(a *goivy.LogicAssignAction, ctx *actionPreimageContext) bool {
	lhs, ok := a.LHS.(*goivy.Apply)
	if !ok || len(goivy.UsedVariablesAST(lhs)) > 0 || len(goivy.UsedVariablesAST(a.RHS)) > 0 {
		return false
	}
	fn, ok := lhs.Func.(*goivy.Const)
	if !ok || fn == nil {
		return false
	}
	sort, ok := g.isStateSymbolName(fn.Name)
	if !ok {
		return false
	}
	fs, ok := sort.(*goivy.LogicFunctionSort)
	if !ok || len(fs.Domain()) != len(lhs.Terms) {
		return false
	}
	args := make([]goivy.Expr, len(lhs.Terms))
	for i, arg := range lhs.Terms {
		substituted, ok := g.substituteExprForPreimage(arg, ctx)
		if !ok {
			return false
		}
		args[i] = substituted
	}
	value, ok := g.substituteExprForPreimage(a.RHS, ctx)
	if !ok {
		return false
	}
	key := goivy.Key(fn)
	ctx.pointUpdate[key] = append(ctx.pointUpdate[key], preimagePointUpdate{fn: fn, args: args, value: value})
	return true
}

func formalExprOverrideNames(name string) []string {
	base := name
	switch {
	case strings.HasPrefix(name, "__fml:"):
		base = strings.TrimPrefix(name, "__fml:")
	case strings.HasPrefix(name, "fml:"):
		base = strings.TrimPrefix(name, "fml:")
	}
	candidates := []string{name, base, "fml:" + base, "__fml:" + base}
	names := make([]string, 0, len(candidates))
	seen := map[string]bool{}
	for _, candidate := range candidates {
		if seen[candidate] {
			continue
		}
		seen[candidate] = true
		names = append(names, candidate)
	}
	return names
}

func actionFormalGeneratorLabel(p *goivy.Const) string {
	if p == nil {
		return "__fml:"
	}
	name := p.Name
	switch {
	case strings.HasPrefix(name, "__fml:"):
		return name
	case strings.HasPrefix(name, "fml:"):
		return "__" + name
	default:
		return "__fml:" + name
	}
}

