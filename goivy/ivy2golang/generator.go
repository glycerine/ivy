type Config struct {
	Target          string
	RequestedTarget string
	ClassName       string
	MainName        string
	OutDir          string
	Compiler        string
	TestIters       string
	TestRuns        string
	Build           bool
	EmitMain        bool
	Trace           bool
	Stdafx          bool
	HostOS          string
}

type Output struct {
	Source          string
	BaseName        string
	ClassName       string
	Target          string
	EffectiveTarget string
	EmitMain        bool
	Config          Config
	ExtraFiles      map[string]string
	LibSpecs        []string
	Warnings        []string
}

type Generator struct {
	Mod       *goivy.Module
	Config    Config
	BaseName  string
	ClassName string

	tempID     int
	errs       []error
	warnings   []string
	warningSet map[string]bool

	locals             []map[string]goivy.Sort
	currentReturns     []*goivy.Const
	extRel             map[string]bool
	supportRel         map[string]bool
	importCallersCache map[string]bool
	importActionsCache map[string]bool
	exprAliases        map[string]goivy.Expr
	exprOverrides      []map[string]string
	defStack           map[string]bool
}

func Generate(mod *goivy.Module, cfg Config) (*Output, error) {
	if mod == nil {
		return nil, fmt.Errorf("ivy2golang: nil module")
	}
	if cfg.Target == "" && cfg.RequestedTarget == "" {
		cfg.Target = "impl"
	}
	var err error
	cfg, _, err = normalizeConfig(cfg)
	if err != nil {
		return nil, err
	}
	base := moduleBaseName(mod)
	className := cfg.ClassName
	if className == "" {
		className = goIdentifierName(base)
	} else {
		className = goIdentifierName(className)
	}
	cfg.ClassName = className
	applySessionParameters(mod, cfg)
	prepareModuleForGo(mod, cfg)
	g := &Generator{
		Mod:       mod,
		Config:    cfg,
		BaseName:  base,
		ClassName: className,
	}
	g.validatePublicActions()
	g.validateNativeSemantics()
	if err := joinUniqueErrors(g.errs); err != nil {
		return nil, err
	}
	if err := g.checkGeneratedNames(); err != nil {
		return nil, err
	}
	src, err := g.generate()
	if err != nil {
		return nil, err
	}
	return &Output{
		Source:          src,
		BaseName:        base,
		ClassName:       className,
		Target:          cfg.RequestedTarget,
		EffectiveTarget: cfg.Target,
		EmitMain:        cfg.EmitMain,
		Config:          cfg,
		LibSpecs:        moduleLibSpecs(mod),
		Warnings:        append([]string(nil), g.warnings...),
	}, nil
}

func (g *Generator) generate() (string, error) {
	var w goWriter
	w.line("// Code generated by ivy2golang; DO NOT EDIT.")
	w.linef("package %s", g.packageName())
	w.blank()
	g.emitImports(&w)
	g.emitTopLevelNativeComments(&w)
	g.emitNativeTypeComments(&w)
	g.emitSortDecls(&w)
	g.emitRuntime(&w)
	g.emitStruct(&w)
	g.emitConstructor(&w)
	g.emitClone(&w)
	g.emitInitialState(&w)
	g.emitInit(&w)
	g.emitMethods(&w)
	g.emitTick(&w)
	if g.Config.EmitMain {
		emittedMain := true
		if g.Config.Target == "test" {
			g.emitTestMain(&w)
		} else if g.Config.Target == "gen" {
			g.emitGenMain(&w)
		} else if g.Config.Target == "repl" {
			g.emitReplMain(&w)
		} else {
			emittedMain = false
		}
		if emittedMain {
			g.emitMainWrapper(&w)
		}
	}
	return w.String(), joinUniqueErrors(g.errs)
}

func (g *Generator) emitTopLevelNativeComments(w *goWriter) {
	if g == nil || g.Mod == nil || len(g.Mod.Natives) == 0 {
		return
	}
	g.warnOnce("ivy2golang: top-level native C++ blocks are emitted as Go comments")
	for _, node := range g.Mod.Natives {
		code, ok := topLevelNativeCode(node)
		if !ok || !topLevelNativeBlockAllowedAsComment(code) {
			continue
		}
		w.line("// ivy top-level native block omitted: C++ native code is not translated to Go")
		for _, line := range strings.Split(code, "\n") {
			line = strings.TrimSpace(strings.TrimRight(line, "\r"))
			if line == "" {
				continue
			}
			w.line("// native: " + line)
		}
		w.blank()
	}
}

func (g *Generator) emitNativeTypeComments(w *goWriter) {
	if g == nil || g.Mod == nil || len(g.Mod.NativeTypes) == 0 {
		return
	}
	g.warnOnce("ivy2golang: native C++ type interpretations are represented as Go int placeholders")
	names := make([]string, 0, len(g.Mod.NativeTypes))
	for name := range g.Mod.NativeTypes {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		w.linef("// ivy native type %s represented as Go int placeholder", name)
	}
	w.blank()
}

func joinUniqueErrors(errs []error) error {
	if len(errs) == 0 {
		return nil
	}
	seen := map[string]bool{}
	uniq := make([]error, 0, len(errs))
	for _, err := range errs {
		if err == nil {
			continue
		}
		msg := err.Error()
		if seen[msg] {
			continue
		}
		seen[msg] = true
		uniq = append(uniq, err)
	}
	return errors.Join(uniq...)
}

func (g *Generator) validatePublicActions() {
	if g == nil || g.Mod == nil || g.Mod.Actions == nil || g.Mod.PublicActions == nil {
		return
	}
	for name, act := range g.Mod.Actions.All() {
		if !g.Mod.PublicActions.Get(name) || act == nil {
			continue
		}
		if len(act.GetFormalReturns()) > 1 {
			g.errs = append(g.errs, fmt.Errorf("ivy2golang: cannot handle multiple output in exported actions: %s", name))
		}
	}
}

func (g *Generator) validateNativeSemantics() {
	if g == nil || g.Mod == nil {
		return
	}
	for _, node := range g.Mod.Natives {
		code, ok := topLevelNativeCode(node)
		if !ok || topLevelNativeBlockAllowedAsComment(code) {
			continue
		}
		kind := topLevelNativeBlockKind(code)
		if kind == "" {
			kind = "unknown"
		}
		err := fmt.Errorf("ivy2golang: top-level native C++ block is not translated to Go: %s", kind)
		loc := goivy.Location{}
		if withLoc, ok := node.(interface{ GetLineno() goivy.Location }); ok {
			loc = withLoc.GetLineno()
		}
		g.errs = append(g.errs, errorAt(loc, err))
	}
	if len(g.Mod.NativeTypes) > 0 {
		names := make([]string, 0, len(g.Mod.NativeTypes))
		for name := range g.Mod.NativeTypes {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			g.errs = append(g.errs, fmt.Errorf("ivy2golang: native C++ type interpretation is not translated to Go: %s", name))
		}
	}
	for _, lf := range g.Mod.NativeDefinitions {
		if lf == nil {
			continue
		}
		name := "definition"
		if def, ok := lf.Formula.(*goivy.LogicDefinition); ok && def != nil {
			if defName := goivy.ExprName(def.Defines()); defName != "" {
				name = defName
			}
		}
		err := fmt.Errorf("ivy2golang: native C++ expression definition is not translated to Go: %s", name)
		g.errs = append(g.errs, errorAt(labeledFormulaLocation(lf), err))
	}
	if g.Mod.Actions == nil {
		return
	}
	for name, act := range g.Mod.Actions.All() {
		if act == nil || !actionContainsNativeAction(act) || g.actionAllowsNativeRuntimeHandleFactory(act) {
			continue
		}
		err := fmt.Errorf("ivy2golang: native C++ action code is not translated to Go in action %s", name)
		if native := firstNativeAction(act); native != nil {
			g.errs = append(g.errs, errorAt(native.GetLineno(), err))
		} else {
			g.errs = append(g.errs, err)
		}
	}
}

func topLevelNativeCode(node goivy.Node) (string, bool) {
	if node == nil {
		return "", false
	}
	args := node.Args()
	if len(args) < 2 {
		return "", false
	}
	code, ok := args[1].(*goivy.NativeCode)
	if !ok || code == nil {
		return "", false
	}
	return code.Code, true
}

func topLevelNativeBlockAllowedAsComment(code string) bool {
	lines := topLevelNativeBlockLines(code)
	if len(lines) == 0 || lines[0] != "header" {
		return false
	}
	for _, line := range lines[1:] {
		if strings.HasPrefix(line, "#include") || strings.HasPrefix(line, "//") {
			continue
		}
		return false
	}
	return true
}

func topLevelNativeBlockKind(code string) string {
	lines := topLevelNativeBlockLines(code)
	if len(lines) == 0 {
		return ""
	}
	return lines[0]
}

func topLevelNativeBlockLines(code string) []string {
	var lines []string
	for _, line := range strings.Split(code, "\n") {
		line = strings.TrimSpace(strings.TrimRight(line, "\r"))
		if line != "" {
			lines = append(lines, line)
		}
	}
	return lines
}

func labeledFormulaLocation(lf *goivy.LabeledFormula) goivy.Location {
	if lf == nil {
		return goivy.Location{}
	}
	if withLoc, ok := lf.Formula.(interface{ GetLineno() goivy.Location }); ok {
		if loc := withLoc.GetLineno(); loc != (goivy.Location{}) {
			return loc
		}
	}
	if line := lf.Lineno(); line > 0 {
		return goivy.Location{Line: line}
	}
	return goivy.Location{}
}

func firstNativeAction(act goivy.Action) *goivy.LogicNativeAction {
	switch a := act.(type) {
	case nil:
		return nil
	case *goivy.LogicNativeAction:
		return a
	}
	for _, child := range act.ActionArgs() {
		childAct, ok := child.(goivy.Action)
		if !ok {
			continue
		}
		if native := firstNativeAction(childAct); native != nil {
			return native
		}
	}
	return nil
}

func (g *Generator) actionAllowsNativeRuntimeHandleFactory(act goivy.Action) bool {
	if g == nil || act == nil || !actionReturnsOnlyRuntimeHandles(g, act) {
		return false
	}
	return actionContainsNativeAction(act)
}

func actionReturnsOnlyRuntimeHandles(g *Generator, act goivy.Action) bool {
	if g == nil || act == nil {
		return false
	}
	returns := act.GetFormalReturns()
	if len(returns) == 0 {
		return false
	}
	for _, ret := range returns {
		if ret == nil || !g.isRuntimeHandleSort(ret.CSort) {
			return false
		}
	}
	return true
}

func nativeActionsAllMatchZeroHandleReturn(act goivy.Action, returns []*goivy.Const) bool {
	switch a := act.(type) {
	case nil:
		return true
	case *goivy.LogicNativeAction:
		return nativeActionMatchesZeroHandleReturn(a, returns)
	}
	for _, child := range act.ActionArgs() {
		childAct, ok := child.(goivy.Action)
		if !ok {
			continue
		}
		if !nativeActionsAllMatchZeroHandleReturn(childAct, returns) {
			return false
		}
	}
	return true
}

func nativeActionMatchesZeroHandleReturn(a *goivy.LogicNativeAction, returns []*goivy.Const) bool {
	if a == nil || len(returns) == 0 {
		return false
	}
	code := nativeActionCode(a)
	if code == "" {
		return false
	}
	norm := normalizeNativeCode(code)
	for _, ret := range returns {
		if ret == nil || ret.Name == "" {
			return false
		}
		if !strings.Contains(norm, normalizeNativeCode(ret.Name+"=0;")) {
			return false
		}
	}
	return true
}

func nativeActionCode(a *goivy.LogicNativeAction) string {
	if a == nil || a.Code == nil {
		return ""
	}
	if code, ok := a.Code.(*goivy.NativeCode); ok && code != nil {
		return code.Code
	}
	return a.Code.String()
}

func normalizeNativeCode(code string) string {
	code = strings.ReplaceAll(code, "impure", "")
	return strings.Map(func(r rune) rune {
		switch r {
		case ' ', '\t', '\n', '\r':
			return -1
		default:
			return r
		}
	}, code)
}

// checkGeneratedNames mirrors ivy2cpp's member-name guard for actions, symbols,
// and sorts, then adds the Go-specific package-level declarations emitted for
// named enum elements and record/variant sorts.
func (g *Generator) checkGeneratedNames() error {
	if g == nil || g.Mod == nil {
		return nil
	}
	names := map[string]bool{}
	add := func(name string) {
		if name != "" {
			names[goName(name)] = true
		}
	}
	if g.Mod.Sig != nil {
		for name := range g.Mod.Sig.Symbols.All() {
			add(name)
		}
		for name, s := range g.Mod.Sig.Sorts.All() {
			add(name)
			if st, ok := s.(*goivy.LogicEnumeratedSort); ok && st.Name != "" && !isNumericEnum(st) {
				add(st.Name)
				for _, sym := range st.Extension {
					add(sym)
				}
			}
		}
	}
	for _, name := range g.Mod.SortOrder {
		if g.isVariantSuperName(name) || len(g.destructorStructFields(name)) > 0 {
			add(name)
		}
	}
	if g.Mod.Actions != nil {
		for name := range g.Mod.Actions.All() {
			add(name)
		}
	}
	if names[g.ClassName] {
		return fmt.Errorf(
			"ivy2golang: cannot create Go type %s with generated name %s.\n"+
				"Use command line option classname=... to change the type name",
			g.ClassName, g.ClassName)
	}
	return nil
}

func (g *Generator) packageName() string {
	if g != nil && !g.Config.EmitMain {
		return "ivygenerated"
	}
	return "main"
}

func (g *Generator) emitImports(w *goWriter) {
	w.line("import (")
	w.indent++
	imports := []string{"fmt", "io", "math/rand/v2", "os", "strconv", "strings"}
	if g.Config.Target == "repl" && g.Config.EmitMain {
		imports = append(imports, "bufio")
	}
	if g.Config.Target == "test" {
		imports = append(imports, "syscall", "time", "unsafe")
		if g.testTargetEmitsTrial() {
			imports = append(imports, "bytes")
		}
	}
	sort.Strings(imports)
	for _, imp := range imports {
		w.linef("%q", imp)
	}
	w.indent--
	w.line(")")
	w.blank()
}

func (g *Generator) testTargetEmitsTrial() bool {
	if g == nil || g.Config.Target != "test" {
		return false
	}
	for _, name := range g.runnableActionNames() {
		act, _ := g.Mod.Actions.Get2(name)
		genAct := g.actionGeneratorAnalysisAction(name, act)
		if g.testActionNeedsTrial(genAct) {
			return true
		}
	}
	return false
}

func (g *Generator) emitSortDecls(w *goWriter) {
	if g.Mod == nil || g.Mod.Sig == nil {
		return
	}
	for _, name := range g.Mod.SortOrder {
		s, ok := g.Mod.Sig.Sorts.Get2(name)
		if !ok {
			continue
		}
		st, ok := s.(*goivy.LogicEnumeratedSort)
		if !ok || st.Name == "" || isNumericEnum(st) {
			continue
		}
		// Package-level Go type/const declarations are allowed to be unused,
		// and destructor-local variant construction can reference enum
		// constructors even when no retained state symbol mentions the enum
		// sort directly after isolate pruning.
		typeName := goName(st.Name)
		w.linef("type %s int", typeName)
		w.blank()
		w.line("const (")
		w.indent++
		for i, sym := range st.Extension {
			if i == 0 {
				w.linef("%s %s = iota", goName(sym), typeName)
			} else {
				w.line(goName(sym))
			}
		}
		w.indent--
		w.line(")")
		w.blank()
		w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
		w.line("switch v {")
		w.indent++
		for _, sym := range st.Extension {
			w.linef("case %s:", goName(sym))
			w.indent++
			w.linef("return %q", memName(sym))
			w.indent--
		}
		w.indent--
		w.line("}")
		w.line(`return fmt.Sprintf("%d", int(v))`)
		w.close("")
		w.blank()
	}
	for _, name := range g.Mod.SortOrder {
		if !g.isVariantSuperName(name) {
			continue
		}
		g.emitVariantSuperDecl(w, name)
	}
	for _, name := range g.Mod.SortOrder {
		fields := g.destructorStructFieldInfos(name)
		if len(fields) == 0 {
			continue
		}
		typeName := goName(name)
		w.open(fmt.Sprintf("type %s struct {", typeName))
		for _, field := range fields {
			typ, _ := g.goDestructorFieldType(field.Sort)
			w.linef("%s %s", field.FieldName, typ)
		}
		w.close("")
		w.blank()
		w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
		if len(fields) == 0 {
			w.line(`return "{}"`)
		} else if destructorStringNeedsBuilder(fields) {
			g.emitDestructorStringBuilder(w, fields)
		} else {
			format := "{" + strings.Join(recordFormatLabels(fields), ",") + "}"
			args := make([]string, len(fields))
			for i, field := range fields {
				args[i] = "v." + field.FieldName
			}
			w.linef("return fmt.Sprintf(%q, %s)", format, strings.Join(args, ", "))
		}
		w.close("")
		w.blank()
		if g.destructorStructNeedsEqualMethod(fields) {
			g.emitDestructorEqualMethod(w, typeName, fields)
			w.blank()
		}
	}
}

func (g *Generator) emitVariantSuperDecl(w *goWriter, name string) {
	variants := g.Mod.Variants[name]
	typeName := goName(name)
	w.open(fmt.Sprintf("type %s struct {", typeName))
	w.line("tag int")
	w.line("value any")
	w.line("valid bool")
	w.close("")
	w.blank()
	w.open(fmt.Sprintf("func (v %s) String() string {", typeName))
	w.open("if !v.valid {")
	w.line(`return "{}"`)
	w.close("")
	w.line("switch v.tag {")
	w.indent++
	for i, sub := range variants {
		subName := sortName(sub)
		payloadType := g.goScalarType(sub)
		w.linef("case %d:", i)
		w.indent++
		w.linef("return fmt.Sprintf(%q, v.value.(%s))", "{"+subName+":%v}", payloadType)
		w.indent--
	}
	w.indent--
	w.line("}")
	w.line(`return "{}"`)
	w.close("")
	w.blank()
	g.emitVariantEqualMethod(w, typeName, variants)
	w.blank()
}

func (g *Generator) emitVariantEqualMethod(w *goWriter, typeName string, variants []goivy.Sort) {
	w.open(fmt.Sprintf("func (v %s) Equal(other %s) bool {", typeName, typeName))
	w.open("if v.valid != other.valid {")
	w.line("return false")
	w.close("")
	w.open("if !v.valid {")
	w.line("return true")
	w.close("")
	w.open("if v.tag != other.tag {")
	w.line("return false")
	w.close("")
	w.line("switch v.tag {")
	w.indent++
	for i, sub := range variants {
		payloadType := g.goScalarType(sub)
		lhs := fmt.Sprintf("v.value.(%s)", payloadType)
		rhs := fmt.Sprintf("other.value.(%s)", payloadType)
		w.linef("case %d:", i)
		w.indent++
		w.linef("return %s", g.goEqualExpr(lhs, rhs, sub))
		w.indent--
	}
	w.indent--
	w.line("}")
	w.line("return true")
	w.close("")
}

func recordFormatLabels(fields []goDestructorField) []string {
	labels := make([]string, 0, len(fields))
	for _, field := range fields {
		labels = append(labels, fmt.Sprintf("%s:%%v", memName(field.Const.Name)))
	}
	return labels
}

func destructorStringNeedsBuilder(fields []goDestructorField) bool {
	for _, field := range fields {
		if len(field.Sort.Domain()) > 1 {
			return true
		}
	}
	return false
}

func (g *Generator) emitDestructorStringBuilder(w *goWriter, fields []goDestructorField) {
	w.line("var __b strings.Builder")
	w.line(`__b.WriteString("{")`)
	for i, field := range fields {
		if i > 0 {
			w.line(`__b.WriteString(",")`)
		}
		w.linef("__b.WriteString(%q)", memName(field.Const.Name)+":")
		if g.destructorFieldIsLarge(field) {
			w.line(`__b.WriteString("<hash_thunk>")`)
			continue
		}
		g.emitDestructorStringValue(w, "v."+field.FieldName, field.Sort.Domain()[1:], i, 0)
	}
	w.line(`__b.WriteString("}")`)
	w.line("return __b.String()")
}

func (g *Generator) emitDestructorStringValue(w *goWriter, expr string, domain []goivy.Sort, fieldOrdinal int, depth int) {
	if len(domain) == 0 {
		w.linef("__b.WriteString(fmt.Sprintf(%q, %s))", "%v", expr)
		return
	}
	idx := fmt.Sprintf("__i%d", depth)
	first := fmt.Sprintf("__ivy_first%d_%d", fieldOrdinal, depth)
	vals, ok := g.finiteValueExprs(domain[0])
	if !ok {
		g.unsupported(w, "cannot enumerate destructor string domain sort %s", sortName(domain[0]))
		return
	}
	w.line(`__b.WriteString("[")`)
	w.linef("%s := true", first)
	w.open(fmt.Sprintf("for _, %s := range []%s{%s} {", idx, g.goScalarType(domain[0]), strings.Join(vals, ", ")))
	w.open(fmt.Sprintf("if !%s {", first))
	w.line(`__b.WriteString(",")`)
	w.close("")
	w.linef("%s = false", first)
	g.emitDestructorStringValue(w, expr+"["+idx+"]", domain[1:], fieldOrdinal, depth+1)
	w.close("")
	w.line(`__b.WriteString("]")`)
}

func (g *Generator) emitDestructorEqualMethod(w *goWriter, typeName string, fields []goDestructorField) {
	w.open(fmt.Sprintf("func (v %s) Equal(other %s) bool {", typeName, typeName))
	for i, field := range fields {
		if g.destructorFieldIsLarge(field) {
			continue
		}
		g.emitDestructorEqualValue(w, "v."+field.FieldName, "other."+field.FieldName, field.Sort.Domain()[1:], field.Sort.Range(), i, 0)
	}
	w.line("return true")
	w.close("")
}

func (g *Generator) emitDestructorEqualValue(w *goWriter, left, right string, domain []goivy.Sort, rng goivy.Sort, fieldOrdinal int, depth int) {
	if len(domain) == 0 {
		w.open(fmt.Sprintf("if !(%s) {", g.goEqualExpr(left, right, rng)))
		w.line("return false")
		w.close("")
		return
	}
	idx := fmt.Sprintf("__i%d", depth)
	vals, ok := g.finiteValueExprs(domain[0])
	if !ok {
		g.unsupported(w, "cannot enumerate destructor equality domain sort %s", sortName(domain[0]))
		return
	}
	w.open(fmt.Sprintf("for _, %s := range []%s{%s} {", idx, g.goScalarType(domain[0]), strings.Join(vals, ", ")))
	g.emitDestructorEqualValue(w, left+"["+idx+"]", right+"["+idx+"]", domain[1:], rng, fieldOrdinal, depth+1)
	w.close("")
}

func (g *Generator) sortNeededForGoDecl(name string) bool {
	for _, sym := range g.stateSymbols() {
		if g.sortDependenciesReferenceName(sym.Sort, name) {
			return true
		}
	}
	if g.Mod.Actions != nil {
		for _, act := range g.Mod.Actions.All() {
			for _, p := range act.GetFormalParams() {
				if g.sortDependenciesReferenceName(p.CSort, name) {
					return true
				}
			}
			for _, r := range act.GetFormalReturns() {
				if g.sortDependenciesReferenceName(r.CSort, name) {
					return true
				}
			}
		}
	}
	return false
}

