var (
	commandTestBinaryOnce sync.Once
	commandTestBinary     string
	commandTestBinaryDir  string
	commandTestBinaryErr  error
	commandTestEnvOnce    sync.Once
	commandTestEnvVals    []string
	commandTestEnvRoot    string
	commandTestEnvErr     error
)

func TestMain(m *testing.M) {
	code := m.Run()
	if commandTestBinaryDir != "" {
		_ = os.RemoveAll(commandTestBinaryDir)
	}
	if commandTestEnvRoot != "" {
		_ = os.RemoveAll(commandTestEnvRoot)
	}
	os.Exit(code)
}

func requireSlowCommandTest(t *testing.T) {
	t.Helper()
	if os.Getenv("SLOWTEST") != "1" {
		t.Skip("set SLOWTEST=1 to build and run the ivy2golang command binary")
	}
}

func TestCommandWritePathLibraryFast(t *testing.T) {
	dir := t.TempDir()
	spec := filepath.Join(dir, "tiny.ivy")
	if err := os.WriteFile(spec, []byte(`#lang ivy1.7
action step = {
}
export step
`), 0o644); err != nil {
		t.Fatalf("write spec: %v", err)
	}
	outDir := filepath.Join(dir, "out")
	batch, err := ivy2golanglib.CompileAndGenerateAll(spec, map[string]string{
		"target":    "test",
		"classname": "Tiny",
	}, ivy2golanglib.Config{})
	if err != nil {
		t.Fatalf("CompileAndGenerateAll: %v", err)
	}
	if err := ivy2golanglib.WriteBatchOutput(batch, outDir); err != nil {
		t.Fatalf("WriteBatchOutput: %v", err)
	}
	data, err := os.ReadFile(filepath.Join(outDir, "Tiny.go"))
	if err != nil {
		t.Fatalf("missing generated Go: %v", err)
	}
	for _, want := range []string{
		"// Code generated by ivy2golang; DO NOT EDIT.",
		"package main",
		"type Tiny struct",
		"func main()",
		`fmt.Fprintln(__ivy_out, "test_completed")`,
	} {
		if !strings.Contains(string(data), want) {
			t.Fatalf("generated Go missing %q:\n%s", want, data)
		}
	}
	dsc, err := os.ReadFile(filepath.Join(outDir, "Tiny.dsc"))
	if err != nil {
		t.Fatalf("missing descriptor: %v", err)
	}
	if !strings.Contains(string(dsc), `"test_params":["iters","runs","seed","delay","wait","modelfile"]`) {
		t.Fatalf("descriptor missing test params:\n%s", dsc)
	}
}

