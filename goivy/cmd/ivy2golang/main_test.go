package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	ivy2golanglib "github.com/glycerine/ivy/goivy/ivy2golang"
)

func requireSlowCommandTest(t *testing.T) {
	t.Helper()
	if os.Getenv("SLOWTEST") != "1" {
		t.Skip("set SLOWTEST=1 to build and run the ivy2golang command binary")
	}
}

func TestCommandWritePathLibraryFast(t *testing.T) {
	dir := t.TempDir()
	spec := filepath.Join(dir, "tiny.ivy")
	if err := os.WriteFile(spec, []byte(`#lang ivy1.7
action step = {
}
export step
`), 0o644); err != nil {
		t.Fatalf("write spec: %v", err)
	}
	outDir := filepath.Join(dir, "out")
	batch, err := ivy2golanglib.CompileAndGenerateAll(spec, map[string]string{
		"target":    "test",
		"classname": "Tiny",
	}, ivy2golanglib.Config{})
	if err != nil {
		t.Fatalf("CompileAndGenerateAll: %v", err)
	}
	if err := ivy2golanglib.WriteBatchOutput(batch, outDir); err != nil {
		t.Fatalf("WriteBatchOutput: %v", err)
	}
	data, err := os.ReadFile(filepath.Join(outDir, "Tiny.go"))
	if err != nil {
		t.Fatalf("missing generated Go: %v", err)
	}
	for _, want := range []string{
		"// Code generated by ivy2golang; DO NOT EDIT.",
		"package main",
		"type Tiny struct",
		"func main()",
		`fmt.Fprintln(__ivy_out, "test_completed")`,
	} {
		if !strings.Contains(string(data), want) {
			t.Fatalf("generated Go missing %q:\n%s", want, data)
		}
	}
	dsc, err := os.ReadFile(filepath.Join(outDir, "Tiny.dsc"))
	if err != nil {
		t.Fatalf("missing descriptor: %v", err)
	}
	if !strings.Contains(string(dsc), `"test_params":["iters","runs","seed","delay","wait","modelfile"]`) {
		t.Fatalf("descriptor missing test params:\n%s", dsc)
	}
}

func TestCommandWritesGoSourceAndDescriptor(t *testing.T) {
	bin := buildIvy2GolangCommand(t)
	dir := t.TempDir()
	spec := filepath.Join(dir, "tiny.ivy")
	if err := os.WriteFile(spec, []byte(`#lang ivy1.7
action step = {
}
export step
`), 0o644); err != nil {
		t.Fatalf("write spec: %v", err)
	}
	outDir := filepath.Join(dir, "out")
	stdout, stderr, err := runIvy2GolangCommand(t, bin,
		"target=test",
		"classname=Tiny",
		"outdir="+outDir,
		spec,
	)
	if err != nil {
		t.Fatalf("run ivy2golang: %v\nstdout:\n%s\nstderr:\n%s", err, stdout, stderr)
	}
	if stdout != "" {
		t.Fatalf("command should not write stdout for generation, got %q", stdout)
	}
	goPath := filepath.Join(outDir, "Tiny.go")
	data, err := os.ReadFile(goPath)
	if err != nil {
		t.Fatalf("missing generated Go file %s: %v\nstderr:\n%s", goPath, err, stderr)
	}
	for _, want := range []string{
		"// Code generated by ivy2golang; DO NOT EDIT.",
		"package main",
		"type Tiny struct",
		"func main()",
		`fmt.Fprintln(__ivy_out, "test_completed")`,
	} {
		if !strings.Contains(string(data), want) {
			t.Fatalf("generated Go missing %q:\n%s", want, data)
		}
	}
	dscPath := filepath.Join(outDir, "Tiny.dsc")
	dsc, err := os.ReadFile(dscPath)
	if err != nil {
		t.Fatalf("missing descriptor %s: %v", dscPath, err)
	}
	if !strings.Contains(string(dsc), `"test_params":["iters","runs","seed","delay","wait","modelfile"]`) {
		t.Fatalf("descriptor missing test params:\n%s", dsc)
	}
}

func TestCommandBuildTrueBuildsGeneratedGoProgram(t *testing.T) {
	bin := buildIvy2GolangCommand(t)
	dir := t.TempDir()
	spec := filepath.Join(dir, "tinybuild.ivy")
	if err := os.WriteFile(spec, []byte(`#lang ivy1.7
type color = {red, green}
action echo(c:color) returns (out:color) = {
    out := c
}
export echo
`), 0o644); err != nil {
		t.Fatalf("write spec: %v", err)
	}
	outDir := filepath.Join(dir, "build")
	stdout, stderr, err := runIvy2GolangCommand(t, bin,
		"target=test",
		"build=true",
		"classname=TinyBuild",
		"outdir="+outDir,
		spec,
	)
	if err != nil {
		t.Fatalf("run ivy2golang build=true: %v\nstdout:\n%s\nstderr:\n%s", err, stdout, stderr)
	}
	if stdout != "" {
		t.Fatalf("command should not write stdout for build=true, got %q", stdout)
	}
	goPath := filepath.Join(outDir, "TinyBuild.go")
	if _, err := os.Stat(goPath); err != nil {
		t.Fatalf("build=true should write generated Go file %s: %v", goPath, err)
	}
	exe := filepath.Join(outDir, "TinyBuild")
	if runtime.GOOS == "windows" {
		exe += ".exe"
	}
	if _, err := os.Stat(exe); err != nil {
		t.Fatalf("build=true should build executable %s: %v\nstderr:\n%s", exe, err, stderr)
	}
	if _, err := os.Stat(filepath.Join(outDir, "TinyBuild.dsc")); err != nil {
		t.Fatalf("build=true should write descriptor: %v", err)
	}
}

func buildIvy2GolangCommand(t *testing.T) string {
	t.Helper()
	requireSlowCommandTest(t)
	dir := t.TempDir()
	bin := filepath.Join(dir, "ivy2golang")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	cmd := exec.Command("go", "build", "-o", bin, ".")
	cmd.Env = commandTestEnv(t)
	data, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go build cmd/ivy2golang: %v\n%s", err, data)
	}
	return bin
}

func runIvy2GolangCommand(t *testing.T, bin string, args ...string) (string, string, error) {
	t.Helper()
	cmd := exec.Command(bin, args...)
	cmd.Env = commandTestEnv(t)
	var stdout, stderr strings.Builder
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	err := cmd.Run()
	return stdout.String(), stderr.String(), err
}

func commandTestEnv(t *testing.T) []string {
	t.Helper()
	cacheDir := filepath.Join(t.TempDir(), "gocache")
	tmpDir := filepath.Join(t.TempDir(), "gotmp")
	for _, dir := range []string{cacheDir, tmpDir} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatalf("create %s: %v", dir, err)
		}
	}
	base := os.Environ()
	return append(base,
		"GOCACHE="+cacheDir,
		"GOTMPDIR="+tmpDir,
	)
}
