// This file implements printing of expressions.

import type { Expr, Field, FieldList, FuncType, Ident } from "../../front/ast.js";
import { TokenKind } from "../../front/token.js";
import { hasDots } from "./util.js";

// ExprString returns the (possibly shortened) string representation for x.
// Shortened representations are suitable for user interfaces but may not
// necessarily follow Go syntax.
export function ExprString(x: Expr | unknown): string {
  const buf: string[] = [];
  WriteExpr(buf, x);
  return buf.join("");
}

// WriteExpr writes the (possibly shortened) string representation for x to buf.
// Shortened representations are suitable for user interfaces but may not
// necessarily follow Go syntax.
export function WriteExpr(buf: string[], x: Expr | unknown): void {
  // The AST preserves source-level parentheses so there is
  // no need to introduce them here to correct for different
  // operator precedences. (This assumes that the AST was
  // generated by a Go parser.)

  const expr = x as Expr | null | undefined;
  switch (expr?.kind) {
    default:
      buf.push(`(ast: ${expr?.kind ?? "<nil>"})`); // nil, ast.BadExpr, ast.KeyValueExpr
      break;

    case "Ident":
      buf.push(expr.name);
      break;

    case "Ellipsis":
      buf.push("...");
      if (expr.element !== undefined) {
        WriteExpr(buf, expr.element);
      }
      break;

    case "BasicLit":
      buf.push(expr.value);
      break;

    case "FuncLit":
      buf.push("(");
      WriteExpr(buf, expr.type);
      buf.push(" literal)"); // shortened
      break;

    case "CompositeLit":
      WriteExpr(buf, expr.type);
      buf.push("{");
      if (expr.elements.length > 0) {
        buf.push("...");
      }
      buf.push("}");
      break;

    case "ParenExpr":
      buf.push("(");
      WriteExpr(buf, expr.expr);
      buf.push(")");
      break;

    case "SelectorExpr":
      WriteExpr(buf, expr.object);
      buf.push(".");
      buf.push(expr.selector.name);
      break;

    case "IndexExpr":
      WriteExpr(buf, expr.object);
      buf.push("[");
      WriteExpr(buf, expr.index);
      buf.push("]");
      break;

    case "IndexListExpr":
      WriteExpr(buf, expr.object);
      buf.push("[");
      writeExprList(buf, expr.indices);
      buf.push("]");
      break;

    case "SliceExpr":
      WriteExpr(buf, expr.object);
      buf.push("[");
      if (expr.low !== undefined) {
        WriteExpr(buf, expr.low);
      }
      buf.push(":");
      if (expr.high !== undefined) {
        WriteExpr(buf, expr.high);
      }
      if (expr.max !== undefined) {
        buf.push(":");
        WriteExpr(buf, expr.max);
      }
      buf.push("]");
      break;

    case "TypeAssertExpr":
      WriteExpr(buf, expr.object);
      buf.push(".(");
      WriteExpr(buf, expr.type);
      buf.push(")");
      break;

    case "CallExpr":
      WriteExpr(buf, expr.fun);
      buf.push("(");
      writeExprList(buf, expr.args);
      if (hasDots(expr)) {
        buf.push("...");
      }
      buf.push(")");
      break;

    case "StarExpr":
      buf.push("*");
      WriteExpr(buf, expr.expr);
      break;

    case "UnaryExpr":
      buf.push(tokenString(expr.op));
      WriteExpr(buf, expr.expr);
      break;

    case "BinaryExpr":
      WriteExpr(buf, expr.left);
      buf.push(" ");
      buf.push(tokenString(expr.op));
      buf.push(" ");
      WriteExpr(buf, expr.right);
      break;

    case "KeyValueExpr":
      WriteExpr(buf, expr.key);
      buf.push(": ");
      WriteExpr(buf, expr.value);
      break;

    case "CellRefExpr":
      buf.push(expr.namespace.name);
      buf.push(".");
      buf.push(expr.address.raw);
      break;

    case "RangeRefExpr":
      buf.push(expr.namespace.name);
      buf.push(".");
      buf.push(expr.start.raw);
      buf.push(":");
      buf.push(expr.end.raw);
      break;

    case "ArrayType":
      buf.push("[");
      if (expr.inferredLength) {
        buf.push("...");
      } else if (expr.length !== undefined) {
        WriteExpr(buf, expr.length);
      }
      buf.push("]");
      WriteExpr(buf, expr.element);
      break;

    case "StructType":
      buf.push("struct{");
      writeFieldList(buf, expr.fields.fields, "; ", false);
      buf.push("}");
      break;

    case "FuncType":
      buf.push("func");
      writeSigExpr(buf, expr);
      break;

    case "InterfaceType":
      buf.push("interface{");
      writeFieldList(buf, expr.methods.fields, "; ", true);
      buf.push("}");
      break;

    case "MapType":
      buf.push("map[");
      WriteExpr(buf, expr.key);
      buf.push("]");
      WriteExpr(buf, expr.value);
      break;

    case "ChanType": {
      let s: string;
      switch (expr.direction) {
        case "send":
          s = "chan<- ";
          break;
        case "receive":
          s = "<-chan ";
          break;
        default:
          s = "chan ";
          break;
      }
      buf.push(s);
      WriteExpr(buf, expr.value);
      break;
    }
  }
}

export function writeSigExpr(buf: string[], sig: FuncType): void {
  buf.push("(");
  writeFieldList(buf, sig.params.fields, ", ", false);
  buf.push(")");

  const res = sig.results;
  const n = numFields(res);
  if (n === 0) {
    // no result
    return;
  }

  buf.push(" ");
  if (n === 1 && res!.fields[0]!.names.length === 0) {
    // single unnamed result
    WriteExpr(buf, res!.fields[0]!.type);
    return;
  }

  // multiple or named result(s)
  buf.push("(");
  writeFieldList(buf, res!.fields, ", ", false);
  buf.push(")");
}

export function writeFieldList(buf: string[], list: Field[], sep: string, iface: boolean): void {
  for (let i = 0; i < list.length; i++) {
    const f = list[i]!;
    if (i > 0) {
      buf.push(sep);
    }

    // field list names
    writeIdentList(buf, f.names);

    // types of interface methods consist of signatures only
    const sig = f.type.kind === "FuncType" ? f.type : null;
    if (sig !== null && iface) {
      writeSigExpr(buf, sig);
      continue;
    }

    // named fields are separated with a blank from the field type
    if (f.names.length > 0) {
      buf.push(" ");
    }

    WriteExpr(buf, f.type);

    // ignore tag
  }
}

export function writeIdentList(buf: string[], list: Ident[]): void {
  for (let i = 0; i < list.length; i++) {
    const x = list[i]!;
    if (i > 0) {
      buf.push(", ");
    }
    buf.push(x.name);
  }
}

export function writeExprList(buf: string[], list: Expr[]): void {
  for (let i = 0; i < list.length; i++) {
    const x = list[i]!;
    if (i > 0) {
      buf.push(", ");
    }
    WriteExpr(buf, x);
  }
}

function numFields(list: FieldList | undefined): number {
  return list?.fields.reduce((n, f) => n + Math.max(f.names.length, 1), 0) ?? 0;
}

function tokenString(kind: TokenKind): string {
  switch (kind) {
    case TokenKind.OrOr:
      return "||";
    case TokenKind.AndAnd:
      return "&&";
    case TokenKind.Equal:
      return "==";
    case TokenKind.NotEqual:
      return "!=";
    case TokenKind.Less:
      return "<";
    case TokenKind.LessEqual:
      return "<=";
    case TokenKind.Greater:
      return ">";
    case TokenKind.GreaterEqual:
      return ">=";
    case TokenKind.Plus:
      return "+";
    case TokenKind.Minus:
      return "-";
    case TokenKind.Or:
      return "|";
    case TokenKind.Caret:
      return "^";
    case TokenKind.Star:
      return "*";
    case TokenKind.Slash:
      return "/";
    case TokenKind.Percent:
      return "%";
    case TokenKind.Shl:
      return "<<";
    case TokenKind.Shr:
      return ">>";
    case TokenKind.Amp:
      return "&";
    case TokenKind.BitClear:
      return "&^";
    case TokenKind.Bang:
      return "!";
    case TokenKind.Tilde:
      return "~";
    case TokenKind.Arrow:
      return "<-";
    default:
      return kind;
  }
}

